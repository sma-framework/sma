/**
 * generator.mjs — the R3 write engine of pillar 1's layered memory.
 *
 * Turns the memory corpus into MEMORY.md = an always-load CORE section (blockers,
 * current-task pointer, top facts) plus a sparse one-line-per-fact index (C1, B9,
 * B10). CORE is generated ONLY from memory notes — the repo instruction file is
 * NEVER an input. Output is byte-deterministic: no clock, no mtime, no HEAD
 * read in the output-producing path — the commit hash and the last-commit date map
 * are INJECTED so lint's MEM-REGEN (9-08) can byte-compare a committed artifact
 * against a fresh regeneration, and so the flip (9-14) can prove determinism.
 *
 * DETERMINISM CONTRACT:
 *   - commitHash + dateMap are arguments, never read from the environment here.
 *   - The single ordering comparator (importance desc → dateMap desc → name asc)
 *     is shared with the loader (9-09 loader.mjs imports orderNotes), so both the
 *     written index and the read-time query resolve ties the same way.
 *   - LF line endings, UTF-8 no BOM, sparse by threshold (B9 — no cataloguing).
 *
 * Exports (imported by lint 9-08 MEM-REGEN, flip 9-14):
 *   - GENERATED_MARKER : the single header line carrying 'GENERATED' + the build
 *     command name + a {commit} placeholder + the do-not-hand-edit warning.
 *   - buildIndex({corpusDir, tagsPath, commitHash, dateMap, coreThreshold}) → string
 *   - computeDateMap({execGit}) → {path: last-commit-ISO} from ONE git log pass
 *
 * TWO SCHEMA VERSIONS, ONE INDEX: the corpus may hold v1 notes and schema-v2
 * records side by side, and both are read through the same parser. Where the two
 * grammars name the same thing differently, this module maps them onto one axis
 * rather than growing a second rendering path:
 *   description ~ claim · kind ~ (memory_type, truth_mode) · tags ~ retrieval.areas ·
 *   importance≥threshold ~ context_priority: always.
 * On top of that sits ONE filter that outranks all of it: a record whose status
 * names any of the four retirements (superseded · revoked · expired · archived)
 * never reaches CORE (see CORE_EXCLUDED_STATUSES).
 *
 * EPISODES ARE INVISIBLE HERE BY CONSTRUCTION. `.claude/memory/episodes/` is a
 * subdirectory, and the corpus listing below is FLAT (readdirSync + isFile), so
 * no episode can reach the always-load payload even if someone forgets it
 * exists. That is asserted positively in the suite: adding an episode leaves the
 * generated bytes identical. Do not "fix" the listing into a recursive walk.
 *
 * Corpus access is ONLY through frontmatter.mjs (parseNote + loadTagsRegistry) —
 * the single shared read path (9-04). Node built-ins only; zero npm deps.
 */

import { readFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'

import { parseNote, loadTagsRegistry, resolveAlias } from './frontmatter.mjs'
import { SENSITIVITY_CLASSES } from './schema-v2.mjs'

/** Importance at/above which a note is CORE (always loaded). Sparse by design (B9). */
export const CORE_THRESHOLD = 9

/**
 * Lifecycle states that can NEVER reach always-load context, whatever else the
 * record says about itself. A superseded rule and a revoked one are not merely
 * less important — they are known to be wrong, and an index that keeps quoting
 * them into every session is worse than one that never learned them. They stay
 * catalogued in their area index (findable, with the state named) and out of CORE.
 *
 * ALL FOUR RETIREMENTS, NOT TWO. This set held `{superseded, revoked}` until
 * 2026-08-04 while the WRITE path retired four states — `write-pipeline.mjs`
 * `LIFECYCLE_ACTIONS` and `migrate-v1-v2.mjs` `RETIRED_STATUSES` both name
 * `expired` and `archived` too — so a record the pipeline had archived was still
 * delivered, and `MEMORY-LIFECYCLE.md` §5.4's promise («removed from active
 * retrieval, kept for history») was not kept by any code. The gap was recorded
 * as D-11-DEFER-01 and closed by plan 11-14, which put the retirement states
 * behind a user-facing verb: `memory forget --archive` that leaves the record
 * quotable is a verb that lies about what it did.
 *
 * The word means «this record has been retired by a decision», so `expired`
 * belongs here on the record's own say-so, independently of the `valid_until`
 * window that `visibilityVerdict` checks separately — a record can be stamped
 * expired before its date, and the stamp is the newer statement.
 */
export const CORE_EXCLUDED_STATUSES = new Set(['superseded', 'revoked', 'expired', 'archived'])

/**
 * What a schema-v2 grade is worth on the shared weight axis.
 *
 * v2 has no `importance` number: the migration split it into `criticality` (what
 * does MISSING this memory cost) and `context_priority` (must it always load).
 * `context_priority` was already read back onto the axis; `criticality` was not,
 * so every on-demand v2 record weighed 0 — and a consumer that tiers by weight
 * (the reflex fatigue battery silences ≤ 3) heard nothing from migrated knowledge
 * at all. The grades are the missing half of that inverse, in ONE place: no
 * consumer gets its own table (the one-axis law of this module's header).
 *
 * The numbers are the owner's semantics, not a derivation, and they were approved
 * as such: high 8 — loud enough for the verbose tier; medium 5 — a one-liner;
 * low 2 — deliberately BELOW the silence threshold, because a record that says
 * missing it costs little has not earned an interruption. `critical` is the
 * fourth grade of the documented ladder (docs/MEMORY-MODEL.md §8) and is held at
 * the `high` value: the severest grade must never be quieter than `high`, and no
 * tier louder than the approved one is invented here.
 *
 * A grade outside the ladder contributes nothing — an unknown word must not
 * silently mint a weight.
 */
export const CRITICALITY_WEIGHTS = Object.freeze({ low: 2, medium: 5, high: 8, critical: 8 })

/**
 * The CORE membership question, asked ONCE for both schema versions:
 *   - a retired record is never CORE (the hard filter above);
 *   - a schema-v2 record states its own answer in `context_priority` — v2 has no
 *     `importance` field at all, so the threshold cannot speak for it;
 *   - everything else is the v1 law, unchanged: importance at/above threshold.
 *
 * Exported so a consumer sizing or trimming CORE asks the same question the
 * writer answered, instead of re-deriving membership from a field list.
 */
export function isCoreNote(n, coreThreshold = CORE_THRESHOLD) {
  if (CORE_EXCLUDED_STATUSES.has(n.status)) return false
  // A caller may raise the bar out of reach on purpose (`coreThreshold:
  // Infinity` — the reflex matcher's way of saying «there is no CORE here, route
  // every record through facet matching»). An unreachable bar means an EMPTY
  // core, so the v2 shortcut below must not smuggle records past it.
  if (!Number.isFinite(coreThreshold)) return n.importance >= coreThreshold
  if (n.contextPriority === 'always') return true
  if (n.contextPriority === 'on-demand') return false
  return n.importance >= coreThreshold
}

// ───────────────── read-time visibility (hard filters, docs §9.1) ────────────

/**
 * The sensitivity ceiling each named audience may be shown, as a class from the
 * schema's own closed vocabulary (no second dictionary is minted here).
 *
 *   owner    — the local human reading their own corpus: nothing is withheld.
 *              Filtering here would cost recall on one's own material while
 *              protecting nobody, so it is the default.
 *   subagent — a delegated agent: public + internal.
 *   export   — anything leaving the machine (a shared pack, a report): public only.
 *
 * An audience named directly as a sensitivity class reads as that ceiling. An
 * audience nobody registered is fail-CLOSED to the narrowest ceiling: an unknown
 * consumer is not a trusted one.
 */
export const AUDIENCE_SENSITIVITY_CEILING = Object.freeze({
  owner: null, // null = no ceiling
  subagent: 'internal',
  export: 'public',
})

/** The class an undeclared record is treated as: absence is never `public`. */
const UNDECLARED_SENSITIVITY = 'internal'

/** A date-only stamp (`YYYY-MM-DD`) — the corpus writes both this and full ISO. */
const DATE_ONLY = /^\d{4}-\d{2}-\d{2}$/

/**
 * A frontmatter time stamp as epoch ms, or null when absent/unparseable.
 * A date-only stamp is read as the WHOLE day: `valid_from` starts at its first
 * instant, `valid_until` runs through its last. That is the conservative reading —
 * a record stamped «valid until the 18th» is still valid ON the 18th, and hiding
 * knowledge is the expensive mistake here. An unparseable stamp yields null (a
 * schema finding the lint owns), never a silent removal from delivery.
 */
function instantOf(value, { endOfDay = false } = {}) {
  const raw = value instanceof Date ? value.toISOString() : String(value ?? '').trim()
  if (raw === '') return null
  const iso = DATE_ONLY.test(raw) ? `${raw}T${endOfDay ? '23:59:59.999' : '00:00:00.000'}Z` : raw
  const ms = Date.parse(iso)
  return Number.isFinite(ms) ? ms : null
}

/** Position of a sensitivity class in the schema's ordered vocabulary, or -1. */
function sensitivityRank(value) {
  return SENSITIVITY_CLASSES.indexOf(String(value ?? '').trim())
}

/** The ceiling for an audience, or null when the audience may see every class. */
function ceilingFor(audience) {
  const named = String(audience ?? '').trim()
  if (named === '' || named === 'owner') return null
  if (Object.hasOwn(AUDIENCE_SENSITIVITY_CEILING, named)) return AUDIENCE_SENSITIVITY_CEILING[named]
  if (SENSITIVITY_CLASSES.includes(named)) return named
  return SENSITIVITY_CLASSES[0] // fail-closed: an unregistered audience sees public only
}

/**
 * One dimension of `scope` (repos / environments): a record that names a world
 * it holds in is out of delivery in every OTHER world. A record that names none
 * constrains nothing, and a caller that states no world asks no question — the
 * filter only narrows when BOTH sides have something to say.
 *
 * Returns null when the dimension allows the record through, and the two sides of
 * the disagreement when it does not — because «withheld» without «by what, against
 * what» is the kind of answer that makes a retrieval layer unfalsifiable.
 */
function scopeDenial(scope, key, asked) {
  const value = String(asked ?? '').trim()
  if (value === '') return null
  const raw = scope?.[key]
  const declared = (Array.isArray(raw) ? raw : raw == null ? [] : [raw])
    .map((s) => String(s).trim())
    .filter((s) => s !== '')
  if (declared.length === 0 || declared.includes(value)) return null
  return { declared, asked: value }
}

/**
 * The reason names of the read-time filters, frozen and owned HERE — by the module
 * that runs them. Every consumer that reports why a record was withheld imports
 * these; a second copy of the vocabulary would be a second answer waiting to drift
 * from the code that actually decides.
 */
export const VISIBILITY_REASONS = Object.freeze({
  STATUS_RETIRED: 'status-retired',
  NOT_YET_VALID: 'not-yet-valid',
  EXPIRED: 'expired',
  SENSITIVITY_CEILING: 'sensitivity-ceiling',
  SCOPE_REPO: 'scope-repo',
  SCOPE_ENVIRONMENT: 'scope-environment',
})

/**
 * visibilityVerdict(note, opts) — the SAME four hard filters as isVisibleNow, with
 * their verdict spelled out: `null` when the record may be shown, otherwise the
 * reason code plus the field and value that decided it.
 *
 * This is the single implementation of read-time visibility; `isVisibleNow` is the
 * boolean question asked of it. Splitting them the other way round — a boolean
 * filter here and a «why» reconstructed elsewhere — is exactly how an explanation
 * starts describing a retrieval nobody runs.
 *
 * @param {object} note  a projected record (projectNoteAxis — the shared axis)
 * @param {{now?:string|Date, audience?:string, scope?:{repo?:string, environment?:string}}} [opts]
 * @returns {null|{reason:string, field:string, value:*}}
 */
export function visibilityVerdict(note, opts = {}) {
  const n = note ?? {}

  // 1. status — the filter that already ran at CORE membership, now on every path.
  if (CORE_EXCLUDED_STATUSES.has(n.status)) {
    return { reason: VISIBILITY_REASONS.STATUS_RETIRED, field: 'status', value: n.status }
  }

  // 2. valid time — the window the record itself declares (bi-temporal, B5).
  const now = instantOf(opts.now) ?? Date.now()
  const from = instantOf(n.validFrom)
  if (from != null && now < from) {
    return { reason: VISIBILITY_REASONS.NOT_YET_VALID, field: 'valid_from', value: n.validFrom }
  }
  const until = instantOf(n.validUntil, { endOfDay: true })
  if (until != null && now > until) {
    return { reason: VISIBILITY_REASONS.EXPIRED, field: 'valid_until', value: n.validUntil }
  }

  // 3. sensitivity — by AUDIENCE only. The local owner (default) is withheld nothing.
  const ceiling = ceilingFor(opts.audience)
  if (ceiling != null) {
    const declared = String(n.sensitivity ?? '').trim()
    const effective = declared === '' ? UNDECLARED_SENSITIVITY : declared
    const rank = sensitivityRank(effective)
    const base = { field: 'sensitivity', value: declared, effective, audience: String(opts.audience ?? ''), ceiling }
    // a class outside the vocabulary is fail-closed — an unreadable label is not a permit
    if (rank < 0) return { reason: VISIBILITY_REASONS.SENSITIVITY_CEILING, ...base, unknown_class: true }
    if (rank > sensitivityRank(ceiling)) return { reason: VISIBILITY_REASONS.SENSITIVITY_CEILING, ...base }
  }

  // 4. scope — the repo/environment world the claim is meant to hold in (§9.2).
  const scope = n.scope ?? {}
  const repoDenial = scopeDenial(scope, 'repos', opts.scope?.repo)
  if (repoDenial) return { reason: VISIBILITY_REASONS.SCOPE_REPO, field: 'scope.repos', value: repoDenial.declared, asked: repoDenial.asked }
  const envDenial = scopeDenial(scope, 'environments', opts.scope?.environment)
  if (envDenial) {
    return { reason: VISIBILITY_REASONS.SCOPE_ENVIRONMENT, field: 'scope.environments', value: envDenial.declared, asked: envDenial.asked }
  }

  return null
}

/**
 * isVisibleNow(note, opts) — MAY this record be shown right now, to this consumer.
 *
 * The read-time half of `docs/MEMORY-MODEL.md` §9.1: hard filters run BEFORE any
 * ranking — status, valid time, sensitivity by audience, repo/environment scope.
 * Structural only: it reads typed fields and never the note's body, so nothing a
 * record says in prose can argue its way into a payload.
 *
 * This is deliberately NOT the write-time approval ladder (`resolveApprovalPath`,
 * schema-v2): that answers «may this record EXIST», this answers «may it be SHOWN».
 * The two read some of the same fields and must not be collapsed into one function —
 * merging them would make a read path enforce write policy and vice versa.
 *
 * Nothing here mutates: an expired record keeps its `status`, and the lint's
 * advisory MEM-EXPIRE finding stays the human-facing consumer of the same field.
 *
 * @param {object} note  a projected record (projectNoteAxis — the shared axis)
 * @param {{now?:string|Date, audience?:string, scope?:{repo?:string, environment?:string}}} [opts]
 *        now      — injected for determinism; defaults to the current instant
 *        audience — the consumer class (default: the local owner, unfiltered)
 *        scope    — the world the caller is asking from (repo / environment)
 * @returns {boolean}
 */
export function isVisibleNow(note, opts = {}) {
  return visibilityVerdict(note, opts) === null
}

