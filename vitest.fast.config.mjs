import { defineConfig } from 'vitest/config'
import { RUN_MAX_WORKERS, stripShebang, unitSuites } from './vitest.config.mjs'

/**
 * БЫСТРЫЙ ЯРУС — набор, который гоняют ПО ХОДУ работы, а не перед сдачей.
 *
 * Полный набор — это 6000+ тестов, настоящие дочерние процессы, одноразовые репозитории и
 * десятки минут; он и должен быть таким — дефекты, ради которых он живёт, видно только на
 * настоящем процессе. Но гонять его после каждой правки незачем: он отвечает на вопрос
 * «войдёт ли работа», а по ходу работы вопрос другой — «не сломал ли я то, что только что
 * трогал». Ровно это и стоило дому времени: работа, сделанная за двадцать минут, ждала
 * полного набора трижды.
 *
 * Здесь ярус собран ПРАВИЛОМ, а не списком: `unitSuites()` берёт все тесты дерева и
 * выбрасывает последовательную группу и всё, что зовёт настоящий процесс, `mkdtemp` или
 * Postgres (см. LIVE_MARKERS в vitest.config.mjs). Новый живой тест уезжает из быстрого
 * яруса сам, в тот же день, когда его написали, — списку имён пришлось бы об этом
 * напоминать, а он напоминать не умеет.
 *
 * ЭТО НЕ ГЕЙТ И НИКОГДА ИМ НЕ БУДЕТ. Быстрый ярус — подмножество: он не может сказать
 * «работа готова», он говорит «пока не сломано». Гейт один — `npm test`, полный набор, один
 * раз перед сдачей, после свода с main. Ни один тест отсюда не выкинут и не помечен
 * пропуском: тот же файл, который здесь не запустился, в полном наборе запускается.
 *
 * Отдельный файл конфига, а не третий проект внутри основного, по измеренной причине: с
 * `extends: true` проекты СКЛАДЫВАЮТ свои `include`, и третий проект, пересекающийся с
 * параллельным, прогнал бы половину дерева дважды — ровно та ошибка, о которой предупреждает
 * комментарий в основном конфиге (263 файла вместо 134). Дверь: `npm run test:fast`.
 */
export default defineConfig({
  plugins: [stripShebang()],
  test: {
    globals: true,
    testTimeout: 30000,
    hookTimeout: 30000,
    // Тот же потолок, что и у полного набора: быстрый ярус тоже делит машину с соседями.
    maxWorkers: RUN_MAX_WORKERS,
    include: unitSuites(import.meta.dirname),
  },
})
