#!/usr/bin/env node
/**
 * contract-shown-check.mjs — ЗАМОК НА ПОСЛЕДНЕЕ ЗВЕНО: поле доехало до окна — значит либо
 * показано, либо названо непоказанным, либо названо синонимом того, что показано.
 *
 *     node tools/contract-shown-check.mjs           # список необъяснённых полей, код 0/1
 *     node tools/contract-shown-check.mjs --json
 *
 * ═══════════════════════ ЧЕМУ ЭТА ПРОВЕРКА ЗАМЕНА ═══════════════════════
 * За один день четыре разные работы вскрыли ОДИН класс — «посчитано и не подключено», — и у
 * всех четырёх форма обрыва была своя: числа считались внутри демона и до двери не доезжали;
 * значение доезжало и оставалось в типах; полоса была написана, но никто на неё не назначен;
 * у окна подписки провод был цел у читателя и оборван у писателя. Общего механизма нет —
 * значит это не дефект, а след ПРОБЕЛА В ПРОВЕРКАХ.
 *
 * Пробел: ни одна проверка не утверждала ПОСЛЕДНЕЕ ЗВЕНО. Тесты утверждают вычисление,
 * ворота — зелень сьюта и чистоту текстов. Вопрос «а человек это видит» задавал только живой
 * прогон окна — по сценарию, который пишет автор работы, и тогда, когда о нём вспомнили.
 *
 * ═══════════ И ЧЕГО ЭТА ПРОВЕРКА НЕ ИМЕЕТ ПРАВА СКАЗАТЬ ═══════════
 * «ИМЕНИ ПОЛЯ НЕТ В РИСУЮЩИХ ФАЙЛАХ» — ЭТО НЕ «ЧЕЛОВЕК ЭТОГО НЕ ВИДИТ». Одно и то же значение
 * ходит по договору под РАЗНЫМИ именами, и наивный поиск по имени на живой работе дал ложный
 * ответ дважды подряд: расход за сегодня объявлен «непоказанным», хотя человек читает его на
 * «Расходах» — то же число приезжает туда полем `todayUsd`; и та же ошибка вышла на статистике
 * работника. Замок, который умеет только искать имя, повторил бы эту ошибку в промышленном
 * масштабе — на каждом новом поле и уже без человека, который потом перепроверит.
 *
 * Поэтому у «не нарисовано под своим именем» ДВА разных ответа, и они не смешиваются:
 *   `NOT_SHOWN` — значения человеку не предъявляют вовсе, и вот почему (причина словами);
 *   `SHOWN_AS`  — то же значение человек видит, но под другим именем договора — вот каким.
 * Вторая половина НЕ верится на слово: названное имя обязано и существовать в договоре, и
 * действительно встречаться в рисующих файлах, иначе находка. Отговорка «оно показано где-то
 * там» так превращается из прозы в проверяемое утверждение.
 *
 * ПРАВИЛО ЦЕЛИКОМ. Каждое имя поля из ДОГОВОРА ОКНА (`spa/src/api/types.ts` — то, что демон
 * говорит окну) либо встречается в файлах, которые рисуют (`spa/src/screens/**`,
 * `spa/src/shell/**`), либо стоит в `NOT_SHOWN` с причиной, либо стоит в `SHOWN_AS` с именем
 * поля, под которым это значение доезжает до экрана.
 *
 * ГРАНИЦА, КОТОРУЮ ЭТА ПРОВЕРКА НЕ ПЕРЕХОДИТ. Всё, что демон считает у себя внутри, сюда не
 * входит: там законно много служебного. Речь ровно про договор окна — дошло до границы с
 * человеком, дойди или объясни, почему нет.
 *
 * ЧЕГО ЭТА ПРОВЕРКА НЕ УМЕЕТ, И ЭТО СКАЗАНО ВСЛУХ. «Встречается» — это ПОЛ, а не потолок:
 * упоминание имени в рисующем файле не доказывает, что число доехало до пикселя, и короткое
 * общее имя (`id`, `title`, `count`, `style`) сходится с чем угодно — раздел `style` договора
 * не рисует ни один экран, а проверку проходит по случайному совпадению слова. Значит замок
 * ловит не всякий обрыв, а ровно тот, который дешевле всего проглядеть: поле, объявленное в
 * договоре и не названное НИ ОДНИМ рисующим файлом. Что действительно видно человеку —
 * по-прежнему закрывается живым прогоном окна.
 *
 * ПОЧЕМУ СПИСКИ РУЧНЫЕ. Оба растут только руками человека и только с причиной: список, который
 * пополняет машина, за месяц становится списком всего на свете, и красный перестаёт что-либо
 * значить. Причина в одно слово не принимается — слово это ярлык, а не причина. «Не дошли
 * руки» причиной тоже не является: это задача, а не объяснение.
 */

