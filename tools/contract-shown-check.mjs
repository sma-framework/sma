/**
 * contractFields(text) → `[{name, line}]` — имена полей договора, каждое по первому объявлению.
 *
 * Разбор НАМЕРЕННО текстовый, а не через компилятор типов: поле объявляется одной строкой вида
 * `  имя?: тип`, и правило «строка с отступом, имя, двоеточие» ловит их все, не приводя в сьют
 * целый парсер TypeScript. Строки документации начинаются со звёздочки и под правило не
 * попадают, а вложенный объект в одну строку отдаёт своё внешнее имя — этого достаточно:
 * проверка спрашивает про ИМЕНА, а не про их устройство.
 */
export function contractFields(text) {
  const lines = String(text == null ? '' : text).split(/\r?\n/)
  const out = new Map()
  for (let i = 0; i < lines.length; i += 1) {
    const m = /^\s{2,}(?:readonly\s+)?([A-Za-z_$][A-Za-z0-9_$]*)\??\s*:/.exec(lines[i])
    if (m && !out.has(m[1])) out.set(m[1], { name: m[1], line: i + 1 })
  }
  return [...out.values()]
}

/** Названо ли имя хоть одним рисующим файлом. Целым словом — `id` не должен ловиться внутри `idleReason`. */
export function mentioned(name, renderText) {
  return new RegExp(`\\b${name}\\b`).test(renderText)
}

/** Причина словами: не пустая и не в одно слово. Ярлык объяснением не считается. */
export function reasonWords(reason) {
  return String(reason == null ? '' : reason)
    .trim()
    .split(/\s+/)
    .filter(Boolean).length
}

/**
 * checkShown({contract, render, notShown, shownAs}) → `{fields, shown, findings, ok}`.
 *
 * Чистая функция: ей дают ТЕКСТ договора, ТЕКСТ рисующих файлов и оба списка — и она ничего
 * не читает с диска сама. Поэтому сьют может прогнать её по выдуманному договору из трёх
 * строк и увидеть красный своими глазами, не трогая продукт.
 *
 * Находки, и все они красные:
 *   `not-shown`      — поле в договоре, не названо ни одним рисующим файлом и не объяснено;
 *   `reason-empty`   — объяснено пустой причиной или причиной в одно слово;
 *   `stale-shown`    — стоит в списке, а поле уже рисуют: запись врёт, её место в истории;
 *   `stale-unknown`  — стоит в списке, а такого поля в договоре больше нет;
 *   `alias-unknown`  — синоним указывает на имя, которого в договоре нет;
 *   `alias-not-shown`— синоним указывает на поле, которое само никто не рисует;
 *   `alias-self`     — поле объявлено синонимом самого себя;
 *   `listed-twice`   — поле стоит в обоих списках сразу: два разных ответа на один вопрос.
 */
export function checkShown({ contract, render, notShown = NOT_SHOWN, shownAs = SHOWN_AS } = {}) {
  const fields = contractFields(contract)
  const renderText = String(render == null ? '' : render)
  const silent = notShown && typeof notShown === 'object' ? notShown : {}
  const aliases = shownAs && typeof shownAs === 'object' ? shownAs : {}
  const byName = new Map(fields.map((f) => [f.name, f]))
  const has = (list, name) => Object.prototype.hasOwnProperty.call(list, name)
  const findings = []
  const shown = []

  const at = (name) => {
    const field = byName.get(name)
    return field ? `${CONTRACT_FILE}:${field.line}` : CONTRACT_FILE
  }

  for (const field of fields) {
    if (mentioned(field.name, renderText)) {
      shown.push(field.name)
      continue
    }
    const isSilent = has(silent, field.name)
    const isAlias = has(aliases, field.name)

    if (!isSilent && !isAlias) {
      findings.push({
        kind: 'not-shown',
        name: field.name,
        line: field.line,
        what: `поле «${field.name}» объявлено в договоре окна (${at(field.name)}) и не названо ни одним рисующим файлом — покажите его, объясните в NOT_SHOWN или назовите в SHOWN_AS имя, под которым человек это значение видит`,
      })
      continue
    }
    if (isSilent && isAlias) {
      findings.push({
        kind: 'listed-twice',
        name: field.name,
        line: field.line,
        what: `поле «${field.name}» стоит и в NOT_SHOWN, и в SHOWN_AS — это два разных ответа на один вопрос, оставьте один`,
      })
      continue
    }
    if (isSilent) {
      const words = reasonWords(silent[field.name])
      if (words < MIN_REASON_WORDS) {
        findings.push({
          kind: 'reason-empty',
          name: field.name,
          line: field.line,
          what: `поле «${field.name}» внесено в NOT_SHOWN ${words === 0 ? 'без причины' : `причиной в ${words} сл.`} — причина словами, не короче ${MIN_REASON_WORDS} слов`,
        })
      }
      continue
    }

    // ── синоним: утверждение о том, что человек это значение видит, — и оно проверяется ──
    const entry = aliases[field.name] || {}
    const as = typeof entry.as === 'string' ? entry.as : ''
    const words = reasonWords(entry.why)
    if (words < MIN_REASON_WORDS) {
      findings.push({
        kind: 'reason-empty',
        name: field.name,
        line: field.line,
        what: `поле «${field.name}» внесено в SHOWN_AS ${words === 0 ? 'без причины' : `причиной в ${words} сл.`} — причина словами, не короче ${MIN_REASON_WORDS} слов`,
      })
    }
    if (as === field.name) {
      findings.push({
        kind: 'alias-self',
        name: field.name,
        line: field.line,
        what: `поле «${field.name}» объявлено синонимом самого себя — назовите поле, под которым значение доезжает до экрана`,
      })
      continue
    }
    if (!byName.has(as)) {
      findings.push({
        kind: 'alias-unknown',
        name: field.name,
        line: field.line,
        what: `«${field.name}» объявлено синонимом «${as || '—'}», а такого поля в договоре окна нет`,
      })
      continue
    }
    if (!mentioned(as, renderText)) {
      findings.push({
        kind: 'alias-not-shown',
        name: field.name,
        line: field.line,
        what: `«${field.name}» объявлено синонимом «${as}», но «${as}» и сам не назван ни одним рисующим файлом — «показано вон там» не проверяется, значит не принято`,
      })
    }
  }

  for (const [list, label] of [
    [silent, 'NOT_SHOWN'],
    [aliases, 'SHOWN_AS'],
  ]) {
    for (const name of Object.keys(list)) {
      const field = byName.get(name)
      if (!field) {
        findings.push({
          kind: 'stale-unknown',
          name,
          line: null,
          what: `в ${label} стоит «${name}», а такого поля в договоре окна больше нет — уберите запись`,
        })
        continue
      }
      if (mentioned(name, renderText)) {
        findings.push({
          kind: 'stale-shown',
          name,
          line: field.line,
          what: `в ${label} стоит «${name}», а рисующие файлы его уже называют — уберите запись, она больше не правда`,
        })
      }
    }
  }

  return { fields, shown, findings, ok: findings.length === 0 }
}

/** Все `.ts`/`.tsx` под каталогом, в устойчивом порядке — один и тот же текст на любой машине. */
function collect(root, dir, fs, out) {
  let entries
  try {
    entries = fs.readdirSync(join(root, dir), { withFileTypes: true })
  } catch {
    return out
  }
  for (const e of [...entries].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
    const rel = `${dir}${sep}${e.name}`
    if (e.isDirectory()) collect(root, rel, fs, out)
    else if (/\.(ts|tsx)$/.test(e.name)) out.push(rel)
  }
  return out
}

/**
 * readTree(root, {fsImpl}) → `{contract, render, renderFiles}` — договор и весь рисующий текст
 * одной склейкой. Разделитель между файлами — перевод строки, чтобы имя в конце одного файла
 * и имя в начале другого не срослись в третье слово.
 */
export function readTree(root, { fsImpl } = {}) {
  const fs = {
    readdirSync: (fsImpl && fsImpl.readdirSync) || fsReaddirSync,
    readFileSync: (fsImpl && fsImpl.readFileSync) || fsReadFileSync,
  }
  const renderFiles = RENDER_DIRS.flatMap((dir) => collect(root, dir, fs, []))
  const render = renderFiles.map((rel) => fs.readFileSync(join(root, rel), 'utf8')).join('\n')
  return { contract: fs.readFileSync(join(root, CONTRACT_FILE), 'utf8'), render, renderFiles }
}

/** Корень репозитория от места этого файла — команда работает из любого каталога. */
export function repoRoot() {
  return fileURLToPath(new URL('..', import.meta.url))
}

/** Голос команды: находки построчно, последняя строка — их число; код 0 только на пустом наборе. */
export function renderReport(result) {
  const lines = [
    `договор окна: ${result.fields.length} полей · рисующих файлов: ${result.renderFiles ?? '—'} · названо: ${result.shown.length}`,
  ]
  for (const f of result.findings) lines.push(`  ${f.kind}: ${f.what}`)
  if (result.findings.length === 0) {
    lines.push('Каждое поле договора либо показано, либо объяснено, либо названо синонимом показанного.')
  }
  lines.push(String(result.findings.length))
  return lines.join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = repoRoot()
  const { contract, render, renderFiles } = readTree(root)
  const result = { ...checkShown({ contract, render }), renderFiles: renderFiles.length }
  if (process.argv.includes('--json')) {
    process.stdout.write(`${JSON.stringify(result.findings, null, 2)}\n${result.findings.length}\n`)
  } else {
    process.stdout.write(`${renderReport(result)}\n`)
  }
  process.exit(result.findings.length === 0 ? 0 : 1)
}
