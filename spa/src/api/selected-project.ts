/**
 * Какой проект человек сейчас смотрит — одно место правды на клиенте.
 *
 * Сам выбор — состояние СЕРВЕРНОЕ: его хранит конфиг демона (`activeProject`), меняет дверь
 * `POST /api/project/select`, и после смены демон переподписывает наблюдателя на другое дерево.
 * Этот модуль — не второй хозяин выбора, а его клиентское зеркало: единственное место, откуда
 * чтение состояния узнаёт, чем сузить вопрос к двери.
 *
 * Почему зеркало вообще нужно. Чтение картины — обычный запрос, который перезапускается сам
 * по расписанию и по инвалидации. В момент запуска у него нет доступа к React-состоянию экрана;
 * ему нужно откуда-то взять выбранный проект СЕЙЧАС. Отсюда и берёт.
 *
 * Почему это не реактивное хранилище и не ещё один ключ запроса. Ключ чтения намеренно один
 * (`STATE_KEY`): расщепление ключа по проекту раздуло бы кэш и потребовало бы реактивности от
 * этого модуля, а перечитывание после смены проекта уже заказано инвалидацией того же ключа —
 * запрос стартует заново и берёт отсюда новое значение. То есть реактивность здесь не нужна,
 * а лишняя — стоила бы второй версии правды.
 *
 * Значение `null` означает ровно одно: чем сузить, ещё неизвестно, — и тогда дверь спрашивают
 * без сужения. Оно НЕ означает «проект по умолчанию»: домысливать принадлежность в этой части
 * окна больше нельзя нигде.
 */

let current: string | null = null

/** Чем сузить чтение прямо сейчас; `null` — сужать нечем. */
export function selectedProject(): string | null {
  return current
}

/** Записать выбор — только там, где он уже подтверждён сервером или прочитан у него. */
export function setSelectedProject(id: string | null): void {
  current = id ?? null
}
