import type { QueryClient } from '@tanstack/react-query'
import { onFrame, TASK_EVENTS } from './hints'
import { taskKey } from './queries'
import type { EventFrame } from './types'

/**
 * task-live.ts — открытая карточка задачи перечитывает СЕБЯ, когда по этой задаче звонят.
 *
 * ═══════════════ ДЕФЕКТ, РАДИ КОТОРОГО ЭТОТ ФАЙЛ ЕСТЬ ═══════════════
 *
 * Живым кликом владельца 25.08: после «Одобрить» карточка оставалась в прежнем состоянии, и
 * «принято/слито» человек видел только после ручного обновления страницы. Действие уходило в
 * дверь, дверь отвечала, демон звонил `task.approved` — и никто на карточке этого не слушал.
 * Обновление картины после действия заказывалось на ОБЩЕЕ чтение (`state`), а карточка живёт
 * своим чтением (`task/:id`), и его никто не трогал.
 *
 * ═══════════════ ПОЧЕМУ ЗДЕСЬ ПЕРЕЧИТЫВАЮТ, ХОТЯ СОСЕДНИЙ ФАЙЛ ЭТО ЗАПРЕЩАЕТ ═══════════════
 *
 * `hints.ts` запрещает перечитывать по колоколу — и прав: там речь о картине ВСЕГО парка,
 * которую заплатка чинит бесплатно, а поток колоколов превратился бы в поток запросов. Здесь
 * другое: подписка живёт, только пока открыта ОДНА карточка, и сужена до колоколов ЭТОЙ
 * задачи. Заплатки же для карточки не существует в природе: колокол несёт имя и состояние, а
 * карточка показывает подходы, квитанцию, коммиты, ветку и журнал — то, чего в колоколе нет и
 * не будет. Либо перезапрос, либо F5 руками; F5 руками — это и есть дефект.
 *
 * ═══════════════ ПОЧЕМУ ЭТО НЕ ХУК ═══════════════
 *
 * React здесь не импортируется намеренно: провод «событие задачи → перезапрос состояния»
 * доказывается прогоном, который ведёт настоящий поток демона до настоящего подписчика, и
 * тащить в такой прогон дерево компонентов значило бы проверять что угодно, кроме провода.
 * Оболочка вызывает `watchTask` из своего эффекта — одна строка на стороне экрана.
 */

/** Кого слушает подписка: тот, кто раздаёт колокола (по умолчанию — единственный канал окна). */
export type FrameWatcher = (listener: (evt: EventFrame) => void) => () => void

/** Колокол ПРО ЭТУ задачу — и ни про какую другую. */
export function aboutTask(evt: EventFrame | null | undefined, taskId: string | null): boolean {
  if (!evt || !taskId) return false
  return TASK_EVENTS.has(evt.event) && evt.taskId === taskId
}

/**
 * watchTask(queryClient, taskId) — слушать колокола этой задачи и заказывать перечитывание её
 * карточки. Возвращает отписку, которая снимает ровно то, что повесила.
 *
 * Задача не названа — подписки нет вовсе: карточка, открытая ни с чем, слушать нечего.
 */
export function watchTask(
  queryClient: Pick<QueryClient, 'invalidateQueries'>,
  taskId: string | null,
  { subscribe = onFrame as FrameWatcher }: { subscribe?: FrameWatcher } = {},
): () => void {
  if (!taskId) return () => {}
  return subscribe((evt) => {
    if (!aboutTask(evt, taskId)) return
    void queryClient.invalidateQueries({ queryKey: taskKey(taskId) })
  })
}
