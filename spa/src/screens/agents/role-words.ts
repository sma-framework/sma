import type { StockTeamCard } from '../../api/types'

/**
 * role-words — ЧЕМ ВЫКЛЮЧЕННАЯ РОЛЬ ОБЪЯСНЯЕТ САМА СЕБЯ.
 *
 * ЧТО СЛУЧИЛОСЬ. Владелец открыл два окна и увидел в них противоположное. «Агенты» показывали
 * четвёртый десяток серых строк со словом «выключен» и одну кнопку «Включить команду (35)»;
 * «Команда» в то же время показывала живую доску, где работники ждут работы. Его слова 02.09:
 * «почему-то в агентах выключено, и я не понимаю вообще почему оно выключено, а в команде они
 * все ждут работы — либо понять, либо у нас в фронте ошибка». Ошибки в окне не было: это два
 * РАЗНЫХ вопроса — «кто приехал вместе с установкой» и «кто разбирает очередь», — но ни одно
 * из двух окон этого не говорило. Непонятый экран и сломанный экран для человека неотличимы.
 *
 * ЧТО ЭТОТ МОДУЛЬ ДЕЛАЕТ. Превращает ДВА ФАКТА, приехавшие с демона считанными (`role` и
 * `pipeline`), в две фразы на карточке: кто ставит этой роли задачи и что изменится, если её
 * включить. Оба факта решены на той стороне провода — тем же выражением, каким роль читает
 * маршрутизатор, и тем же словарём, каким выключатель конвейера отбирает, кого включать.
 * Здесь не решается НИЧЕГО: здесь только подбираются слова, и поэтому кнопка и подпись под ней
 * не могут однажды начать говорить о разных наборах.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ, А НЕ ВНУТРИ ЭКРАНА. Экран — компонент, и проверить его словами можно
 * было бы только подняв DOM. Это чистая функция над карточкой: её прогоняет обычный тест, и
 * «выключенная роль объясняет себя» перестаёт быть обещанием абзаца в разметке.
 */

/** Две фразы, которые карточка говорит о себе. */
export interface RoleWords {
  /** Кто даёт этой роли работу — очередь, сборка или фаза, поднимающая её изнутри себя. */
  assignedBy: string
  /** Что изменится, если её включить. Показывается на выключенной карточке. */
  onEnable: string
}

/**
 * roleWords(card) → чем эта роль занята и что даст её включение.
 *
 * Три ответа, потому что источников работы ровно три, и они разные:
 *   • ИСПОЛНИТЕЛЬ берёт из очереди — ему едет всё, о чьей роли никто ничего не сказал;
 *   • ПЛАНИРОВЩИКА зовёт сборка, когда работу надо разложить на ступени;
 *   • СПЕЦИАЛИСТА поднимает фаза изнутри своей работы или Вы — назвав его роль при постановке.
 * Последнее и есть ответ на «почему оно выключено»: специалист, включённый заранее, не берёт
 * из очереди ничего — ни при каком порядке строк, — поэтому включать его заранее незачем.
 */
export function roleWords(card: Pick<StockTeamCard, 'role' | 'pipeline'>): RoleWords {
  if (card.pipeline && card.role === 'planner') {
    return {
      assignedBy: 'Задачи ставит сборка: планировщика зовут, когда работу надо разложить на ступени.',
      onEnable: 'Включение: сборкам станет кому раскладывать работу на ступени.',
    }
  }
  if (card.pipeline) {
    return {
      assignedBy: 'Задачи ставит очередь: всё, о чьей роли Вы ничего не сказали, едет исполнителю.',
      onEnable: 'Включение: начнёт разбирать очередь — задачи поедут ему.',
    }
  }
  return {
    assignedBy: 'Задачи ставит фаза: этого специалиста поднимает работа изнутри себя, поимённо.',
    onEnable:
      'Включение: станет доступен фазам и Вашим постановкам, где Вы назовёте его роль. Из очереди он не берёт ничего.',
  }
}
