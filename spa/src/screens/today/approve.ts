/**
 * Состояние, из которого ходит дверь приёмки, — и единственное, в котором строка ленты несёт
 * кнопку. Это не «состояние, которое нам нравится»: дверь делает CAS `awaiting_approval →
 * approving` и на всяком другом статусе отвечает проигранной гонкой.
 */
export const APPROVABLE_STATUS = 'awaiting_approval'

/**
 * canApprove(row) → можно ли предложить человеку одобрить ЭТУ строку прямо в ленте.
 *
 * Тотальна: строка без статуса, `null` и что угодно незнакомое — «нельзя». Отсутствие ответа
 * читается как запрет, потому что нарисованная по неизвестности кнопка — это обещание.
 */
export function canApprove(row: { status?: string | null } | null | undefined): boolean {
  return !!row && row.status === APPROVABLE_STATUS
}

/**
 * Слово на кнопке. Пока приёмка идёт, кнопка говорит это — и говорит теми же словами, что и
 * та же кнопка в боковой панели.
 */
export function approveWord(pending: boolean): string {
  return pending ? 'Принимаю…' : 'Одобрить'
}

/**
 * refusalFor(problem, taskId) → слова отказа для ЭТОЙ строки, или `null`.
 *
 * Отказ принадлежит одной работе: он приехал от двери в ответ на одно нажатие. Строка, которую
 * не нажимали, о чужой беде молчит — иначе одно неудавшееся слияние покрасило бы всю ленту.
 */
export function refusalFor(
  problem: { taskId: string; text: string } | null | undefined,
  taskId: string,
): string | null {
  return problem && problem.taskId === taskId ? problem.text : null
}
