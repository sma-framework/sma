import type { FailureAction, FailureOffer, TurnKinds, TurnSpend } from '../../api/types'

/**
 * offer.ts — ЧТО ОКНО УМЕЕТ СДЕЛАТЬ С РАБОТОЙ, КОТОРАЯ НЕ ПОМЕСТИЛАСЬ В ХОДЫ.
 *
 * ═══════════════ ПОЧЕМУ ЭТО МОДУЛЬ, А НЕ ВЫРАЖЕНИЕ В РАЗМЕТКЕ ═══════════════
 *
 * Здесь два утверждения, и оба проверяются прогоном, а не глазом на живом экране:
 *
 *   1. У КАЖДОГО ПРЕДЛОЖЕННОГО ИМЕНИ ЕСТЬ ДЕЛО. Дверь называет человеку три действия; окно
 *      обязано знать, чем делается каждое. Кнопка, за которой ничего не произойдёт, хуже
 *      молчания: она обещает выход и не даёт его. Поэтому имя, которого нет в `ACT_OF`, не
 *      рисуется вовсе, а сьют сверяет два списка — дверин и здешний — между собой.
 *   2. ЧИСЛО СОЖЖЁННЫХ ХОДОВ И РАЗБИВКА ПО РОДУ — ЭТО ТЕКСТ, А НЕ УКРАШЕНИЕ. От него зависит
 *      выбор человека: сто ходов правок — работе не хватило места, сто ходов запусков
 *      оболочки — доказательство, которое не сходится, и просят они противоположного.
 *      Посчитанное внутри разметки утверждение расходится с правдой молча.
 *
 * ЧИСТЫЙ МОДУЛЬ: ни запросов, ни состояния, ни React. Дверь зовёт экран, экран зовёт эти
 * функции — и ни одна из них не знает, чем кончится нажатие.
 */

/**
 * ЧТО ОКНО ДЕЛАЕТ ПО КАЖДОМУ ИМЕНИ. Три слова, и каждое — уже существующая дверь:
 *
 *   requeue — та же работа ставится в очередь СНОВА, под тем же номером. Потолок поднимает не
 *             нажатие: он поднимается сам, потому что сгоревший записан на строке попытки, а
 *             следующий запуск обязан быть строго больше него. Номер здесь несущий — работа,
 *             поставленная заново под новым номером, начинает со дна.
 *   compose — окно уходит на «Задачи» с развёрнутой формой состава: человек называет части,
 *             система предлагает состав, он подтверждает. Ни одна часть не заводится нажатием
 *             на красной карточке — предложение и постановка это два действия, а не одно.
 *   cancel  — терминальная остановка: на эту работу больше не будет потрачено ни одной попытки.
 */
export type OfferAct = 'requeue' | 'compose' | 'cancel'

/** Имя действия двери → дело окна. Замкнутый словарь: четвёртого имени окно не знает. */
export const ACT_OF: Readonly<Record<string, OfferAct>> = Object.freeze({
  raise: 'requeue',
  split: 'compose',
  cancel: 'cancel',
})

/** Дело по имени, или `null` — «этого окно не умеет». Тотальна: что угодно незнакомое — `null`. */
export function actOf(actionId: string): OfferAct | null {
  return ACT_OF[actionId] ?? null
}

/**
 * Действия, которые можно нарисовать кнопками, — те, у которых есть дело.
 *
 * Отсев, а не отказ: дверь старше окна ровно настолько, насколько её обновляли отдельно, и
 * четвёртое имя, приехавшее от новой двери, лучше не показать, чем показать мёртвым.
 */
export function actableActions(actions: FailureAction[] | null | undefined): FailureAction[] {
  if (!Array.isArray(actions)) return []
  return actions.filter((a) => a && typeof a.id === 'string' && actOf(a.id) !== null)
}

/**
 * Числа предложения, а когда предложения нет — числа последней попытки.
 *
 * Карточка, за которой стоит повтор, тоже имеет право сказать, во что обошлась: разбивка по
 * роду приезжает у ВСЯКОЙ красной строки, а предложение — только у той, что ждёт человека.
 */
export function spentOf(offer: FailureOffer | null | undefined, spent: TurnSpend | null | undefined): TurnSpend | null {
  if (offer) return { cap: offer.cap, used: offer.turnsBurned, kinds: offer.kinds }
  return spent ?? null
}

/**
 * spentLine(spent) → одна строка о ходах, или `null`, когда мерить нечем.
 *
 * Прочерк вместо числа — то же самое «неизвестно», только занимающее строку, поэтому молчание
 * здесь полное. Порядок частей — от общего к разбору: сколько взяла из сколького, а потом на
 * что именно. `other` в строку не идёт: он — остаток, а не диагноз, и три названных рода уже
 * отвечают на весь вопрос «поднимать или дробить».
 */
export function spentLine(spent: TurnSpend | null | undefined): string | null {
  if (!spent) return null
  const parts: string[] = []
  const { used, cap, kinds } = spent
  if (used !== null && used !== undefined) {
    parts.push(cap !== null && cap !== undefined ? `сожжено ${used} из ${cap} ходов` : `сожжено ${used} ходов`)
  } else if (cap !== null && cap !== undefined) {
    parts.push(`потолок ${cap} ходов`)
  }
  if (kinds) parts.push(kindsLine(kinds))
  return parts.length > 0 ? parts.join(' · ') : null
}

/** Разбивка по роду одной фразой — в том порядке, в каком её читают, когда решают. */
export function kindsLine(kinds: TurnKinds): string {
  return `правок ${kinds.edits} · запусков ${kinds.runs} · чтений ${kinds.reads}`
}
