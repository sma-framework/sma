/**
 * orphans.ts — СИТО ОДНОГО ПРОЕКТА И ТО, О ЧЁМ ОНО ОБЯЗАНО СКАЗАТЬ ВСЛУХ.
 *
 * ═══════════════ ЧТО БЫЛО НЕ ТАК ═══════════════
 *
 * «Сегодня» — экран одного проекта, и это решение, а не случайность: сито ставит рядом работы,
 * которые человек и правда делает вместе. Но строка, родившаяся БЕЗ проекта, этим ситом не
 * проходит — и не проходит МОЛЧА. Замерено вечером 31.08: в `done[]` 46 строк, сито пропускало
 * 32, а 14 несли `project:null` и не были нарисованы нигде. Среди спрятанных лежали все
 * флагманы смены. Основатель сказал об этом словами: «почему-то до сих пор не вижу все готовые
 * задачи» — и был совершенно прав, потому что экран не сказал ему ни числа, ни направления.
 *
 * Работа, которую не рисует ни один экран, хуже честного «проект неизвестен»: по ней нельзя
 * ничего сделать и нельзя даже узнать, что она есть.
 *
 * ═══════════════ ЧТО ЗДЕСЬ РЕШЕНО ═══════════════
 *
 *   1. СИТО ОСТАЁТСЯ СИТОМ ОДНОГО ПРОЕКТА. Показать бесхозное вперемешку со своим значило бы
 *      отменить то самое решение, ради которого сито и существует.
 *   2. НО ОНО ПЕРЕСТАЁТ МОЛЧАТЬ. Отброшенное по причине «проекта нет» считается и называется
 *      числом со ссылкой туда, где эти строки видны целиком, — на экран «Задачи», чей фильтр
 *      (`inProject` в state.mjs) бесхозную строку как раз ОСТАВЛЯЕТ и подписывает «неизвестен».
 *   3. ЧУЖОЙ ПРОЕКТ — НЕ БЕСХОЗНОЕ. Строка, назвавшая другой проект, спрятана правильно: она
 *      видна там, куда человек за ней и пойдёт. Считаются только строки, не назвавшие никого.
 *
 * ЧИСЛО ЗДЕСЬ — ЛЕЧЕНИЕ СИМПТОМА, А НЕ ПРИЧИНЫ. Причина лечится на постановке: дверь, которая
 * знает, чей это BACKLOG.md, штампует проект строки (см. `toTask` в intake/backlog-scan.mjs), а
 * возврат и повтор наследуют его у прежних строк задачи (`inheritedProject` в front/server.mjs).
 * Эта строка-счёт — то, что остаётся правдой и после починки: строка без владельца возможна
 * всегда (внешняя постановка, старая запись в долговечной очереди), и молчать о ней нельзя.
 *
 * ЧИСТЫЙ МОДУЛЬ: ни запросов, ни состояния, ни React — ровно как `approve.ts` рядом. Поэтому
 * все три утверждения выше проверяются прогоном, а не глазом на живом экране.
 */

import { plural } from '../../shell/format'

/** Всё, что сито умеет спросить у строки, — чья она. */
export type Owned = { project?: string | null }

/**
 * Назвала ли строка владельца. Пустая строка — это не имя проекта, а та же неизвестность, что
 * и `null`: очередь пишет в это поле текст, и «» приезжает оттуда же, откуда приезжает пустота.
 */
function owned(row: Owned | null | undefined): boolean {
  return !!row && typeof row.project === 'string' && row.project !== ''
}

/**
 * ofProject(rows, activeProject) → строки ОДНОГО проекта, который сейчас смотрит окно.
 *
 * Проект не выбран (окно смотрит на всё) — сита нет вовсе, и списки едут целиком. Это то самое
 * `mine()`, что жило выражением в разметке экрана; здесь оно стоит рядом со своим счётом
 * отброшенного, потому что это две половины одного решения и расходиться им нельзя.
 */
export function ofProject<T extends Owned>(rows: T[] | null | undefined, activeProject: string | null): T[] {
  const all = Array.isArray(rows) ? rows : []
  if (!activeProject) return all
  return all.filter((r) => r && r.project === activeProject)
}

/**
 * orphansOf(rows, activeProject) → строки, которые сито выбросило ЗА ОТСУТСТВИЕ ВЛАДЕЛЬЦА.
 *
 * Не «всё, что не прошло»: строка чужого проекта спрятана по делу и видна на своём месте.
 * Сита нет (проект не выбран) — нет и отброшенного: скрывать нечем.
 */
export function orphansOf<T extends Owned>(rows: T[] | null | undefined, activeProject: string | null): T[] {
  if (!activeProject) return []
  return (Array.isArray(rows) ? rows : []).filter((r) => !!r && !owned(r))
}

/**
 * orphanNote(count) → строка-счёт для «Сегодня», или `null`, когда говорить не о чем.
 *
 * Ноль — это молчание по делу: фраза «ещё 0 готовых без проекта» сообщает о беде, которой нет.
 * Всё прочее (в том числе мусор вместо числа) молчит по тому же правилу, по какому молчит
 * кнопка, за которой ничего не произойдёт.
 */
export function orphanNote(count: number): string | null {
  if (!Number.isFinite(count) || count <= 0) return null
  return `ещё ${count} ${plural(count, 'готовая', 'готовые', 'готовых')} без проекта — экран «Задачи»`
}

/**
 * closedWords(finished, orphans) → ИТОГ НОЧИ ОДНОЙ ФРАЗОЙ, и он считает ВСЮ закрытую работу.
 *
 * Число в заголовке бралось из просеянного списка — то есть из того самого, откуда сито уже
 * выбросило бесхозных. Лента под заголовком к тому времени о них говорила, а заголовок молчал:
 * человек читал «команда закрыла 32 задачи» о ночи, в которой закрыто 46, и занижение было
 * ровно на число, названное строкой под ним. Одна ночь — одно число, иначе экран спорит сам с
 * собой в трёх сантиметрах по вертикали.
 *
 * СКОЛЬКО ИЗ НИХ БЕСХОЗНЫХ — СКАЗАНО ТУТ ЖЕ. Сумма без этой оговорки была бы вторым способом
 * соврать: работа посчитана, а карточек под ней нет, и человек ищет глазами три строки,
 * которых на этом экране не будет. Ноль — молчит по тому же правилу, что и строка-счёт: беды,
 * которой нет, экран не выдумывает, и фраза остаётся ровно прежней.
 *
 * Мусор вместо числа считается нулём: заголовок обязан сказать фразу всегда, а «NaN задач» —
 * это не отчёт о ночи.
 */
export function closedWords(finished: number, orphans: number): string {
  const own = Number.isFinite(finished) && finished > 0 ? Math.trunc(finished) : 0
  const bare = Number.isFinite(orphans) && orphans > 0 ? Math.trunc(orphans) : 0
  const all = own + bare
  const head = `Пока вас не было, команда закрыла ${all} ${plural(all, 'задачу', 'задачи', 'задач')}`
  return bare > 0 ? `${head}, из них ${bare} без проекта` : head
}
