/**
 * grid.ts — ГЕОМЕТРИЯ ТАБЛИЦЫ РАСХОДОВ, отделённая от разметки, чтобы её можно было ПРОГНАТЬ,
 * а не вычитать глазами.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Правило здесь одно и оно арифметическое: минимальная ширина, ниже
 * которой таблица не сжимается, а прокручивается внутри себя, считается ИЗ САМОЙ строки класса
 * сетки. Пока это жило в файле с разметкой, проверить его можно было только чтением исходника;
 * в собственном модуле без React и без JSX его вызывает сьют — и красный на забытой колонке
 * виден машине, а не только внимательному человеку.
 */

/** Одна колонка сетки на каждое число: источник, четыре счётчика, деньги, справочная цена. */
export const GRID = 'grid grid-cols-[minmax(0,1fr)_repeat(4,96px)_110px_128px] gap-3'

/**
 * Пол первой колонки — «Источник». Она гибкая (`minmax(0,1fr)`), то есть своей ширины не имеет
 * и в расчёт минимума сама не входит; но колонка с именем аккаунта, сжатая до нуля, — это не
 * прокрутка, а другой способ ничего не показать. Столько ей и оставляем.
 */
export const SPEND_LABEL_MIN_PX = 220

/**
 * gridMinPx(gridClass, labelMinPx) → сколько таблице нужно, чтобы НЕ сжиматься: сумма
 * фиксированных дорожек + зазоры между всеми + пол гибкой первой колонки.
 *
 * Считается ИЗ САМОЙ СТРОКИ КЛАССА, а не хранится рядом с ней вторым числом: два числа об
 * одном и том же расходятся на первой же правке сетки, и расходятся молча. Понимает ровно то,
 * чем эта таблица пользуется — `minmax(0,1fr)`, `repeat(N,Wpx)`, `Wpx` и `gap-N` в шаге 4px.
 */
export function gridMinPx(gridClass: string, labelMinPx: number = SPEND_LABEL_MIN_PX): number {
  const tracks = /grid-cols-\[([^\]]+)\]/.exec(gridClass)?.[1] ?? ''
  const gapStep = Number(/(?:^|\s)gap-(\d+(?:\.\d+)?)(?:\s|$)/.exec(gridClass)?.[1] ?? 0) * 4

  let fixed = 0
  let count = 0
  for (const track of tracks.split('_')) {
    const repeat = /^repeat\((\d+),(\d+)px\)$/.exec(track)
    if (repeat) {
      count += Number(repeat[1])
      fixed += Number(repeat[1]) * Number(repeat[2])
      continue
    }
    const px = /^(\d+)px$/.exec(track)
    if (px) {
      count += 1
      fixed += Number(px[1])
      continue
    }
    // всё остальное — гибкая дорожка: своей ширины нет, но зазор после неё есть
    count += 1
  }

  return fixed + Math.max(0, count - 1) * gapStep + labelMinPx
}

/** Ширина, ниже которой таблица не сжимается, а прокручивается внутри своей коробки. */
export const SPEND_GRID_MIN_PX = gridMinPx(GRID)
