/**
 * history.ts — ЧТО РАБОТНИК СДЕЛАЛ, СЛОВАМИ: перевод закрытого словаря демона и раскладка
 * его истории по роду работы.
 *
 * ═════════════ ПОЧЕМУ ЭТО МОДУЛЬ, А НЕ ВЁРСТКА ВНУТРИ КАРТОЧКИ ═════════════
 *
 * Ровно по той же причине, по какой из вёрстки уехали расход задачи (`task-card/spend.ts`) и
 * показатели фазы (`shell/stats.ts`): утверждение, собранное прямо в разметке, проверяется
 * одним человеческим глазом на живом экране и расходится с правдой МОЛЧА. А здесь каждая
 * строка — утверждение о чужой работе: «сорвалась» вместо «возвращена» — это обвинение,
 * поставленное экраном по ошибке, и заметить его некому.
 *
 * ═════════════ ЧИСЛА ЗДЕСЬ НЕ СЧИТАЮТСЯ. НИ ОДНОГО ═════════════
 *
 * «Сделано / не получилось» приходят посчитанными демоном из леджера попыток за названный
 * период — окно их только показывает. Второй счёт (например, по длине списка истории) был бы
 * ВТОРЫМ МНЕНИЕМ: он совпал бы с первым в день, когда его написали, и разошёлся бы в первый
 * же день, когда изменится окно, порог или свёртка на той стороне. Поэтому `statsWords`
 * принимает готовую пару и не умеет складывать.
 *
 * И ДЛИНА ИСТОРИИ НЕ ЕСТЬ ЭТИ ЧИСЛА. Числа считают ПОДХОДЫ (работа, сделанная со второго
 * раза, стоила двух), список считает РАБОТЫ (та же задача — одна строка). Они законно
 * различаются, и экран говорит это словами вместо того, чтобы предоставить человеку самому
 * выводить противоречие из двух чисел, которые ему не объяснили.
 */

import type { WorkerHistoryOutcome, WorkerHistoryRow } from '../../api/types'

/** Слово исхода — по одному на каждое значение закрытого словаря, и ни одного лишнего. */
export const OUTCOME_WORDS: Record<WorkerHistoryOutcome, string> = {
  approved: 'принята',
  returned: 'возвращена',
  failed: 'сорвалась',
  awaiting: 'ждёт вашего слова',
  running: 'снова в работе',
  completed: 'сделана',
}

/** Цвет исхода. «Сделана» намеренно НЕ зелёная: зелёное здесь значит «принято человеком». */
export const OUTCOME_TONE: Record<WorkerHistoryOutcome, string> = {
  approved: 'text-ok-tx',
  returned: 'text-warn-tx',
  failed: 'text-err-tx',
  awaiting: 'text-warn-tx',
  running: 'text-tx2',
  completed: 'text-tx2',
}

/** Когда числа не измерены вовсе — леджер не прочитался. Одно написание на весь экран. */
export const NO_STATS_WORDS = 'нет данных'

/** Читаемый период, названный ровно там же, где и числа: цифра без знаменателя — не статистика. */
export const STATS_PERIOD = 'за 30 дней'

/**
 * statsWords(stats) → строка «сделано: N · не получилось: M», или слова вместо неё.
 *
 * Три РАЗНЫХ ответа, и ни один из них не ноль по умолчанию:
 *   · пары нет вовсе (`null`) — леджер не прочитался, мерить было нечем: «нет данных»;
 *   · пара есть и обе половины нули — каталог открыли, за период ничего не завершилось. Это
 *     ИЗМЕРЕНИЕ, и оно говорится словами, потому что «0 · 0» человек читает как «этот ничего
 *     не умеет», а не как «за месяц ничего не закрылось»;
 *   · пара есть — числа те, что приехали.
 */
export function statsWords(stats: { done: number; failed: number } | null | undefined): {
  kind: 'unknown' | 'empty' | 'measured'
  text: string
  done: number | null
  failed: number | null
} {
  if (!stats) return { kind: 'unknown', text: NO_STATS_WORDS, done: null, failed: null }
  if (stats.done + stats.failed === 0) {
    return { kind: 'empty', text: 'завершённых попыток не было', done: 0, failed: 0 }
  }
  return {
    kind: 'measured',
    text: `сделано: ${stats.done} · не получилось: ${stats.failed}`,
    done: stats.done,
    failed: stats.failed,
  }
}

/** Одна группа истории: её заголовок и строки, свежие сверху. */
export interface HistoryGroup {
  key: 'phase' | 'task' | 'unknown'
  label: string
  rows: WorkerHistoryRow[]
}

/**
 * ЗАГОЛОВКИ ГРУПП. Владелец просил не смешивать фазы и инлайн-задачи — это разный род работы,
 * и «шесть работ» без этого деления отвечает не на тот вопрос, который задают.
 */
const GROUP_LABEL: Record<HistoryGroup['key'], string> = {
  phase: 'Фазы',
  task: 'Инлайн-задачи',
  unknown: 'Род работы не назван',
}

/**
 * splitHistory(rows) → группы по роду работы, в порядке «фазы, инлайн-задачи, безродные»;
 * пустые группы не возвращаются вовсе.
 *
 * ТРЕТЬЯ ГРУППА — НЕ УКРАШЕНИЕ. Строка, чью очередную запись чтение уже не несёт, рода не
 * называет; ссыпать такие к инлайн-задачам значило бы утверждать род, которого никто не
 * читал, — а именно фаза, чью строку очередь подрезала первой, так тихо и переехала бы не в
 * тот столбец.
 *
 * Порядок внутри группы — свежие сверху, по моменту окончания последнего подхода. Демон уже
 * отдаёт список в этом порядке; сортировка повторена здесь потому, что порядок — это
 * утверждение экрана, и оно должно держаться на своём собственном правиле, а не на чужой
 * любезности.
 */
export function splitHistory(rows: readonly WorkerHistoryRow[] | null | undefined): HistoryGroup[] {
  const buckets: Record<HistoryGroup['key'], WorkerHistoryRow[]> = { phase: [], task: [], unknown: [] }
  for (const row of rows ?? []) buckets[row.kind ?? 'unknown'].push(row)
  const order: HistoryGroup['key'][] = ['phase', 'task', 'unknown']
  return order
    .filter((key) => buckets[key].length > 0)
    .map((key) => ({
      key,
      label: GROUP_LABEL[key],
      rows: [...buckets[key]].sort((a, b) => b.endedAt - a.endedAt),
    }))
}

/** Название работы для строки списка: слово очереди, а где его нет — сам идентификатор. */
export function historyTitle(row: WorkerHistoryRow): string {
  if (row.title) return row.title
  return row.taskId
}
