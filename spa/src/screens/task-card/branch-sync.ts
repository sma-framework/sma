/**
 * СВЕДЕНА ЛИ ВЕТКА ПОДХОДА С ВЕРШИНОЙ — слова, которые приёмщик читает ДО того, как нажмёт
 * «принять».
 *
 * ЗАМЕР, РАДИ КОТОРОГО ЭТОТ ФАЙЛ ЕСТЬ (31.08.2026): за один вечер пять готовых работ из шести
 * не слились с первого раза. Очередь отводит работы веером от ОДНОЙ вершины, а вершина живёт
 * минут двадцать. Дверь сдачи сводит ветку в копии работника и кладёт ответ на строку попытки —
 * но до этого модуля ответ никуда не ехал: человек узнавал о споре ПОСЛЕ нажатия «принять», из
 * отказа слияния, и шёл выяснять состав конфликта руками в чужой копии, которую вот-вот
 * выметут. Вычислено и записано — не то же самое, что предъявлено.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ МОДУЛЕМ, А НЕ ФУНКЦИЕЙ В РАЗМЕТКЕ. Соседи по карточке (`flow`, `spend`,
 * `turn-plan`) лежат так же и по той же причине: слова, которые человек прочтёт перед решением,
 * обязаны иметь свой сьют, а функция внутри `.tsx` его не имеет — ни один тест в этом дереве
 * не импортирует разметку.
 *
 * ЗАКОН ЭТОГО МОДУЛЯ: ничего не выдумывать. `null`/отсутствие поля — «попытка об этом молчит»
 * (сдана до появления поля, либо сводить было нечего), и молчание НЕ рисуется как «сведена»:
 * зелёное вместо неизвестности здесь стоило бы ровно того ручного развода, который тут и
 * чинится.
 */

import type { TaskAttempt } from '../../api/types'

/**
 * Сколько букв причины уезжает на карточку. Первая строка отказа git бывает длинной, а строка
 * карточки — одна; обрезка здесь того же рода, что и потолок имён файлов у самого ритуала:
 * названное коротко читается, названное на пол-экрана — нет.
 */
const DETAIL_CAP = 200

/**
 * syncLine(attempt) → строки о сведении ветки. Пустой массив — сказать нечего, и тогда блока
 * на карточке нет вовсе.
 *
 * ЧТО ИМЕННО ГОВОРИТСЯ. Свелась — сказано, на сколько отставала и что при этом развелось без
 * человека: молчаливый автоматический развод неотличим от слияния, где спора не было вовсе, и
 * именно так чужая свежая починка исчезает незамеченной. Не свелась — названы ЧИСЛО и ИМЕНА
 * оставшихся файлов, потому что «слияние не прошло: Command failed» без имён и есть та строка,
 * из-за которой приёмщик каждый раз выяснял состав сам.
 */
export function syncLine(attempt: TaskAttempt): string[] {
  const sync = attempt.sync
  if (!sync || typeof sync !== 'object' || typeof sync.trunk !== 'string') return []
  const resolved = Array.isArray(sync.resolved) ? sync.resolved : []
  const names = resolved.map((r) => `${r.file} (${r.how})`).join(', ')
  const settled = names ? ` · механически развелось: ${names}` : ''
  // ТА ЖЕ ФРАЗА ПОД НЕСВЕДЁННОЙ ВЕТКОЙ ОЗНАЧАЛА БЫ ДРУГОЕ, И НЕПРАВДУ. Сведение, у которого
  // остался хоть один неразведённый файл, дверь сдачи откатывает ЦЕЛИКОМ — вместе с уже
  // сделанным механическим разводом. «Механически развелось: README.md» рядом со словами «ветка
  // НЕ сведена» читается как работа, которую приёмщик унаследует; он её не унаследует, и, увидев
  // README.md в споре при следующей попытке, пойдёт разводить руками ровно тот файл, который
  // разводится сам. Здесь говорится то, что верно при любом исходе отката.
  const settledOnConflict = names ? ` · механическое разводится САМО и рук не требует: ${names}` : ''

  if (sync.synced) {
    const behind =
      typeof sync.behind === 'number' && Number.isFinite(sync.behind) && sync.behind > 0
        ? ` — отставала на ${sync.behind} коммит(ов)`
        : ''
    return [`Ветка сведена с ${sync.trunk}${behind}${settled}`]
  }

  const un = sync.unmerged
  // СПОРА МОГЛО НЕ БЫТЬ ВОВСЕ, И ТОГДА СЛОВО «КОНФЛИКТ» — ВЫДУМКА КАРТОЧКИ, А НЕ ФАКТ ДВЕРИ.
  // Блок `unmerged` дверь сдачи кладёт ТОЛЬКО когда сведение отказало; при `synced:false` без
  // него сводить было НЕЧЕГО — ветка уже содержала вершину (обычный исход быстрой попытки в
  // тихий час) либо вершины в копии не нашлось. До этой ветки такая — здоровая — попытка
  // читалась с карточки как «конфликт в 0 файл(ах) (файлы не названы)», и приёмщик шёл искать
  // спор, которого нет, в копии, которую вот-вот выметут. Ровно та цена, ради которой всё
  // затевалось, только заплаченная за пустоту.
  if (!un) {
    return sync.behind === 0
      ? [`Сводить с ${sync.trunk} было нечего — ветка уже содержала вершину`]
      : [`Сведения с ${sync.trunk} не было, и спора дверь сдачи не называла`]
  }
  const files = Array.isArray(un.files) ? un.files : []
  const count = Number.isFinite(un.count) ? un.count : files.length
  // …А СВЕДЕНИЕ МОГЛО И НЕ ДОЙТИ ДО СПОРА: грязное дерево, исчезнувшая ветка, отказ самого git.
  // Верб сведения различает этот исход с самого начала (`conflict:false` и своя причина) и
  // кладёт причину рядом, в `detail`; эта строка её не печатала вовсе и объявляла спор в НУЛЕ
  // файлов — то есть выдавала человеку ту самую строку без имён, ради которой всё затевалось,
  // да ещё и с выдуманным конфликтом поверх настоящей причины, лежащей в двух шагах.
  const detail = typeof un.detail === 'string' && un.detail.trim() ? un.detail.trim().slice(0, DETAIL_CAP) : null
  if (count === 0 && files.length === 0) {
    return [
      `Ветка НЕ сведена с ${sync.trunk} — свести не удалось: ${detail ?? 'причина не названа'}${settledOnConflict}`,
    ]
  }
  // ЧИСЛО ВПЕРЕДИ ИМЁН — оно не врёт даже там, где имён нет. Пустой список при НЕНУЛЕВОМ числе
  // означает «git не назвал», и выдать это за «спорить не о чем» было бы тем самым ложным
  // успокоением, которое хуже молчания.
  const named = files.length > 0 ? `: ${files.join(', ')}` : ' (файлы не названы)'
  return [`Ветка НЕ сведена с ${sync.trunk} — конфликт в ${count} файл(ах)${named}${settledOnConflict}`]
}
