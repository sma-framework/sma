import { plural } from '../../shell/format'
import type { TurnPlan } from '../../api/types'

/**
 * turn-plan.ts — СКОЛЬКО ХОДОВ ЭТОЙ РАБОТЕ ДАДУТ, И ПОЧЕМУ СТОЛЬКО.
 *
 * ═══════════════ ПОЧЕМУ ЭТО ВООБЩЕ НА ЭКРАНЕ ═══════════════
 *
 * Потолок ходов считается от размера объявленной работы, и до сих пор это число не было видно
 * человеку НИГДЕ: оно доезжало до командной строки работника и до строки реестра, а человек
 * узнавал о нём после того, как работа сгорела. Из-за этого целый класс ошибки был невидим —
 * обещание, написанное строкой вместо списка, читалось одним пунктом, работа выходила
 * «мелкой» и получала базовые ходы. Ошибку формы нечем было заметить, пока она не стоила
 * попытки.
 *
 * ═══════════════ ПОЧЕМУ ЭТО МОДУЛЬ, А НЕ ВЫРАЖЕНИЕ В РАЗМЕТКЕ ═══════════════
 *
 * Строка «крупная · потолок 480 ходов» — это УТВЕРЖДЕНИЕ о цене работы, а не подпись. Слово
 * размера приезжает готовым от двери (`sizeLabel`): свой словарь на замкнутый список окно
 * заводить не вправе — он разошёлся бы с дверинным молча. Здесь только сборка фразы, и она
 * проверяется прогоном, а не глазом на живом экране.
 *
 * ЧИСТЫЙ МОДУЛЬ: ни запросов, ни состояния, ни React.
 */

/**
 * turnPlanLine(plan) → одна строка о потолке, или `null`, когда мерить нечего.
 *
 * `cap: null` — это НЕ ноль и не «потолок неизвестен»: это ответ «честного числа больше нет,
 * всё, что мы готовы оплатить, уже сгорело». Он и говорится словами, потому что число вместо
 * него читалось бы как обещание следующей попытки, которой не будет.
 */
export function turnPlanLine(plan: TurnPlan | null | undefined): string | null {
  if (!plan || typeof plan.sizeLabel !== 'string' || plan.sizeLabel === '') return null
  if (plan.cap === null || plan.cap === undefined) return `${plan.sizeLabel} · честного потолка больше нет`
  return `${plan.sizeLabel} · потолок ${plan.cap} ${plural(plan.cap, 'ход', 'хода', 'ходов')}`
}

/**
 * turnPlanWhy(plan) → по каким признакам размер получился таким, или `null`.
 *
 * Поднятый потолок без названных признаков читается как произвол демона, а НЕ поднятый — как
 * его скупость. Признаки те же три, по которым он и считается: оценка человека, число пунктов
 * обещания и его длина в знаках. Отсутствующая оценка не называется вовсе — «оценки нет» это
 * факт о задаче, и ноль на его месте был бы другим утверждением.
 */
export function turnPlanWhy(plan: TurnPlan | null | undefined): string | null {
  if (!plan || !plan.signals) return null
  const { storyPoints, criteria, promiseChars } = plan.signals
  const parts: string[] = []
  if (typeof storyPoints === 'number') parts.push(`оценка ${storyPoints}`)
  parts.push(`${criteria} ${plural(criteria, 'признак', 'признака', 'признаков')} обещания`)
  parts.push(`${promiseChars} ${plural(promiseChars, 'знак', 'знака', 'знаков')}`)
  if (typeof plan.escalatedFrom === 'number') parts.push(`прошлая попытка не поместилась в ${plan.escalatedFrom}`)
  return parts.join(' · ')
}
