import type { ClosingReason, TaskStatus } from '../../api/types'

/**
 * close — «ЗАКРЫТЬ СЛОВАМИ»: чем человек отвечает строке, которая стоит на нём и делаться
 * больше не будет.
 *
 * ═══════════════════ ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ РАЗМЕТКА ═══════════════════
 *
 * Две вещи здесь — решения, а не рисование: КОГДА действие вообще предлагается и КАКИЕ у него
 * исходы. Обе проверяются прогоном, а разметка карточки — нет (проверять её нечем: DOM в этом
 * дереве не запускается ни одним тестом). Поэтому правило живёт здесь, кнопка его спрашивает,
 * и «дверь берёт, а окно не показывает» перестаёт быть возможным незаметно.
 *
 * ═══════════════════ КОГДА ПРЕДЛАГАЕТСЯ ═══════════════════
 *
 * Ровно тогда, когда дверь примет. Работа, которая ИДЁТ или ждёт работника, закрывается не
 * словами, а остановкой: под ней живой процесс, и слово, написанное мимо него, оставило бы
 * работника трудиться над закрытой карточкой. Идущая приёмка (`approving`) — тоже не «стоит»:
 * ритуал слияния сам допишет свой исход, и слово поверх него решило бы за него. Всё остальное
 * — сделанное и ждущее решения, сорвавшееся, принятое, возвращённое — человек вправе закрыть.
 *
 * ═══════════════════ ТРИ ИСХОДА, И ИХ РОВНО ТРИ ═══════════════════
 *
 * Список — зеркало закрытого словаря двери (`CLOSING_REASONS` в очереди), и прогон сверяет
 * пару буква-в-букву: кнопка, слова которой дверь не знает, — это 400 в лицо человеку, а
 * исход, о котором знает дверь и не знает окно, — выход, которым нельзя воспользоваться.
 */

/** Один исход: слово двери, подпись кнопки и то, что человек об этом исходе должен знать. */
export interface ClosingOption {
  id: ClosingReason
  label: string
  detail: string
  /** Требует ли исход слов человека. Дверь отказывает без них — кнопка обязана сказать это до нажатия. */
  needsWords: boolean
}

export const CLOSING_OPTIONS: readonly ClosingOption[] = [
  {
    id: 'obsolete',
    label: 'Устарело',
    detail: 'работа была нужна раньше; сейчас предмет изменился, и делать её незачем',
    needsWords: false,
  },
  {
    id: 'no_subject',
    label: 'Предмета нет',
    detail: 'делать нечего: жалоба закрыта, ошибка не воспроизводится, файл давно переписан',
    needsWords: false,
  },
  {
    id: 'done_otherwise',
    label: 'Сделано иначе',
    detail: 'результат уже получен другим путём — назовите sha или причину, иначе это нечем перепроверить',
    needsWords: true,
  },
]

/** Требует ли этот исход слов. Незнакомый исход слов не требует — судит всё равно дверь. */
export function closingNeedsWords(reason: ClosingReason | null): boolean {
  return CLOSING_OPTIONS.some((o) => o.id === reason && o.needsWords)
}

/**
 * canCloseWithWords(status) → предлагать ли действие над этой строкой. PURE, тотальна:
 * состояние, которого окно не знает, действия не получает — предлагать выход строке, о
 * которой ничего не известно, значит обещать то, чего дверь может не сделать.
 */
export function canCloseWithWords(status: TaskStatus | null): boolean {
  if (status === null) return false
  return status !== 'queued' && status !== 'claimed' && status !== 'running' && status !== 'approving'
}
