import type { StatePayload, TaskDetail } from '../../api/types'

/**
 * taskProjectOf({detail, state, taskId}) → В КАКОМ ПРОЕКТЕ ЛЕЖИТ ЭТА ЗАДАЧА, или `null`,
 * когда своего проекта она не называет.
 *
 * ═══════════ ЗАЧЕМ У ЭТОГО ВОПРОСА ОДИН ОТВЕТЧИК ═══════════
 * На карточке этот ответ — не подпись, а ЗНАЧЕНИЕ ПЕРЕКЛЮЧАТЕЛЯ: переставляя задачу в другое
 * дерево, человек читает отсюда, ОТКУДА он её переставляет. Промах с проектом замечают не при
 * постановке, а когда работа уже пошла и уткнулась в дерево, где нужного кода нет, — то есть
 * ровно тогда, когда задача ЗАНЯТА. А занятой строки нет ни в очереди, ни у ждущих человека,
 * ни в сделанном: общая картина держит её в СОСТАВЕ, у работника, который её держит. Розыск по
 * трём спискам поэтому отвечал «проект не назван» о задаче со штампом, и выбор между двумя
 * деревьями делался вслепую — то же пересоздание, только с лишним нажатием.
 *
 * ПЕРВОЕ СЛОВО — ЗА САМОЙ ЗАДАЧЕЙ. Дверь карточки называет штамп строки тем же правилом, каким
 * его читает общая картина, и сказанное ею `null` — это ИЗМЕРЕНИЕ («строка своего проекта не
 * называет»), а не повод искать ответ где-то ещё. Розыск по картине остаётся ровно для одного
 * случая: демон постарше поля не отдаёт вовсе — и тогда спрашиваются все четыре места, где
 * живая строка может лежать, состав в том числе.
 *
 * ВЫДУМЫВАТЬ НЕЧЕГО. Ни один путь не подставляет сюда активный проект окна: за строкой, о
 * которой никто ничего не измерял, это записало бы принадлежность, которой нет, — и отличить
 * такую уверенную неправду от правды человеку было бы нечем.
 */
export function taskProjectOf({
  detail,
  state,
  taskId,
}: {
  detail?: TaskDetail | null
  state?: StatePayload | null
  taskId: string | null
}): string | null {
  if (!taskId) return null

  const stated = detail?.task?.project
  if (stated !== undefined) return stated ?? null

  const rows = [...(state?.queue ?? []), ...(state?.awaiting ?? []), ...(state?.done ?? [])]
  const row = rows.find((r) => r.id === taskId)
  if (row) return row.project ?? null

  // ЗАНЯТАЯ СТРОКА ЛЕЖИТ У ТОГО, КТО ЕЁ ДЕРЖИТ — и это единственный список картины, который
  // о работе в работе вообще говорит.
  const holder = (state?.workers ?? []).find((w) => w.taskId === taskId)
  return holder?.project ?? null
}
