import type { TaskAttempt } from '../../api/types'

/**
 * session-return.ts — ЧЕМ ВЕРНУТЬСЯ В СЕССИЮ РАБОТНИКА: одна строка, готовая к вставке.
 *
 * ═══════════════ ПОЧЕМУ ЭТО ВООБЩЕ НА ЭКРАНЕ ═══════════════
 *
 * Продолжение попытки давно поднимает ТУ ЖЕ сессию, а не начинает с нуля: демон хранит
 * идентификатор сессии в строке попытки и передаёт его командной строке. Человеку этой
 * дороги не было НИГДЕ. Он читал на карточке, что подход сорвался, и не мог войти туда, где
 * это случилось: спросить работника, досмотреть его ход, продолжить с того же места. Знание
 * было — доступа не было, и разница между ними стоила отдельного разбора после каждой
 * сорванной попытки.
 *
 * ═══════════════ ПОЧЕМУ СТРОКА СОБИРАЕТСЯ ЗДЕСЬ, А НЕ НА ДВЕРИ ═══════════════
 *
 * Дверь отдаёт ФАКТЫ попытки — сессию, копию, аккаунт, — и ни один из них не зависит от того,
 * в какой оболочке их будут набирать. Сборка же зависит целиком: одна и та же переменная
 * пишется в PowerShell и в POSIX-оболочке по-разному. Ровно так это уже решено на экране
 * добавления аккаунта: дверь называет части, окно складывает их под систему, о которой демон
 * ЕЙ И СКАЗАЛ. Второе место сборки означало бы два расходящихся ответа на один вопрос.
 *
 * ═══════════════ ЗАКОН ЭТОГО МОДУЛЯ ═══════════════
 *
 * НИЧЕГО НЕ ВЫДУМЫВАТЬ. Нет сессии — нет панели. Неизвестна система — нет панели: оболочку не
 * угадывают, а строка, собранная под чужую, не сработает и будет выглядеть работающей. Чужая
 * полоса — нет панели: продолжение там зовётся другой командой, и предложить её, не зная, чем
 * там записан идентификатор, значит соврать уверенно.
 *
 * То, чего не хватает для успеха, но что не отменяет команду, говорится СЛОВАМИ рядом —
 * убранная копия и неназванный аккаунт не подменяют строку, а объясняют, почему она может не
 * найти сессию.
 *
 * ЧИСТЫЙ МОДУЛЬ: ни запросов, ни состояния, ни React.
 */

/** Копии, в которой шла сессия, на диске больше нет — команде некуда встать. */
export const RETURN_COPY_GONE =
  'копию этой попытки уже убрали — команда встанет только в вернувшийся каталог'

/** Аккаунт не назван: сессия лежит в НЁМ, и чужой терминал её не увидит. */
export const RETURN_NO_ACCOUNT =
  'аккаунт работника в записи не назван — из своего терминала эту сессию можно и не найти'

/** Готовая строка и то, что о ней честно сказать. `notes` пуст, когда добавить нечего. */
export interface SessionReturn {
  command: string
  notes: string[]
}

/**
 * sessionReturn(attempt, platform) → строка возврата и примечания к ней, либо `null`.
 *
 * `sessionId` приходит от двери уже ПРИГОДНЫМ к продолжению — форму проверяет она, тем же
 * предикатом, каким её проверяет сборщик аргументов запуска. Здесь второго мнения о форме нет
 * намеренно: два написания одного правила расходятся молча.
 *
 * @param attempt   подход в той форме, в какой его отдаёт дверь задачи
 * @param platform  система, о которой сказал демон (`win32`, `darwin`, `linux`); `null` — не сказал
 */
export function sessionReturn(attempt: TaskAttempt, platform: string | null): SessionReturn | null {
  const session = attempt.sessionId
  if (!session) return null
  if (!platform) return null
  // Полоса Codex продолжается собственной командой (`codex resume`), и идентификатор её нити
  // записан не здесь. Молчание честнее команды, которая выглядит готовой и не работает.
  if (attempt.provider === 'codex') return null

  const dir = attempt.worktreePath ?? null
  const account = attempt.accountDir ?? null
  const resume = `claude --resume ${session}`

  const command =
    platform === 'win32'
      ? [dir ? `cd "${dir}"` : null, account ? `$env:CLAUDE_CONFIG_DIR="${account}"` : null, resume]
          .filter(Boolean)
          .join('; ')
      : [dir ? `cd "${dir}" &&` : null, account ? `CLAUDE_CONFIG_DIR="${account}"` : null, resume]
          .filter(Boolean)
          .join(' ')

  const notes: string[] = []
  if (attempt.cleanup && attempt.cleanup.ok) notes.push(RETURN_COPY_GONE)
  if (!account) notes.push(RETURN_NO_ACCOUNT)

  return { command, notes }
}
