import type { ChatTurn } from '../../api/types'

/**
 * НИТЬ РАЗГОВОРА — ОДНА НА ПРОЕКТ, И ЕЁ ВЫБИРАЕТ КНИГА, А НЕ ПАМЯТЬ ОКНА.
 *
 * Слово владельца: «разговор по разным проектам тоже разный должен быть». Половина этого
 * решения живёт за дверью (ход записан вместе со своим проектом, чтение по нему сужается);
 * вторая половина — здесь, и она ровно в одном правиле: какую беседу окно ПРОДОЛЖАЕТ, когда
 * книга прочитана.
 *
 * Правило: последняя беседа ЭТОЙ книги — а книга уже сужена дверью до одного проекта. Значит:
 *   - переключили проект → книга другая → продолжается другая нить;
 *   - у нового проекта разговора ещё не было → книга пуста → нити нет, и следующий ход
 *     начинает НОВУЮ (`undefined` — это «беседы нет», а не «беседа неизвестна»);
 *   - перезагрузили окно → поднимается последняя нить именно этого проекта, потому что другой
 *     в книге и не лежит.
 *
 * Функция отдельным файлом, а не строкой внутри экрана, по той же причине, по которой отдельно
 * живут провода чтения: правило выбора нити проверяется ПРОГОНОМ. Прочитанное глазами внутри
 * эффекта, оно уже однажды и молча продолжило чужую беседу.
 *
 * `bookOf` — то же сито на стороне окна, каким сужает дверь, и стоит оно здесь ровно по той же
 * причине, по которой «Сегодня» ещё раз отбирает свои строки: ответ, приехавший до того, как
 * окно узнало выбранный проект, иначе на секунду показал бы чужую беседу. Ход БЕЗ проекта под
 * выбранным проектом не показывается никогда — он не пропал, его видно там, где сужать нечем.
 */
export function bookOf(turns: readonly ChatTurn[] | undefined, project: string | null): ChatTurn[] {
  const book = Array.isArray(turns) ? turns : []
  if (!project) return [...book] // сужать нечем — книга целиком, включая ходы без проекта
  return book.filter((t) => t && t.project === project)
}

/** Нить, которую окно продолжает: последняя беседа книги, или `undefined` — «беседы нет». */
export function threadOf(turns: readonly ChatTurn[] | undefined): string | undefined {
  const book = Array.isArray(turns) ? turns : []
  for (let i = book.length - 1; i >= 0; i -= 1) {
    const id = book[i] && book[i].conversationId
    if (id) return id
  }
  return undefined
}
