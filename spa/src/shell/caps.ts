/**
 * caps.ts — потолки очереди, названные в окне ЧИСЛОМ, чтобы счётчик под полем был правдой.
 *
 * ═════════ ПОЧЕМУ ЭТИ ЧИСЛА ВООБЩЕ ЖИВУТ В ОКНЕ ═════════
 * Решает, что влезло, ДВЕРЬ — и это не меняется ни на строку: форма ничего не проверяет за неё
 * и ничего не отправляет «на всякий случай» короче. Но счётчику под полем нужно число, а
 * человеку — знать про стену ДО того, как он в неё упрётся. Замерено 31.08: описание в ~2100
 * знаков молча резалось полем до 2000 (браузерный `maxLength`), а поставленное мимо окна —
 * получало отказ, в котором не было ни поля, ни длины, ни потолка. В обоих случаях человек
 * узнавал о потолке последним.
 *
 * ═════════ ДВЕ КОПИИ ОДНОГО ПОТОЛКА — ЭТО ДВА ПОТОЛКА ═════════
 * Окно и демон собираются порознь и общего модуля иметь не могут, поэтому числа здесь —
 * ЗЕРКАЛО, а не второй источник. Разъехаться молча им не даёт сьют
 * `daemon/__tests__/cap-words.test.ts`: он импортирует и эти константы, и `CAP_TEXT`,
 * `CAP_ACCEPTANCE_ITEMS`, `TASK_CONTEXT_CAP` очереди и краснеет, как только пара разошлась.
 * Набирать эти числа руками в разметке нельзя ровно поэтому — только отсюда.
 */

/** Потолок описания и каждого отдельного признака успеха. */
export const CAP_TEXT = 2000

/** Сколько признаков успеха дверь примет списком. */
export const CAP_ACCEPTANCE_ITEMS = 12

/** Потолок снимка контекста — своего поля у окна пока нет, число держится ради сверки. */
export const TASK_CONTEXT_CAP = 8000
