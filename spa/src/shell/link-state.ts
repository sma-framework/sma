import { ApiError } from '../api/client'

/**
 * link-state.ts — КОГДА ОКНО ОБЯЗАНО СКАЗАТЬ, ЧТО ОНО БОЛЬШЕ НИЧЕГО НЕ ЗНАЕТ.
 *
 * ═══════════════ ПОЧЕМУ ЭТО ВООБЩЕ НУЖНО ═══════════════════════════════════════════
 *
 * Окно — веб-морда самого демона, и опрос телеграма ведёт тот же процесс. Значит одна смерть
 * гасит СРАЗУ ОБА канала. Страница при этом остаётся на экране целой: последняя прочитанная
 * картина никуда не девается, таймеры тикают, кнопки нажимаются. Человек видит рабочее окно —
 * и не видит, что оно показывает вчерашний день. Телефон в этот момент тоже молчит, и молчание
 * бота неотличимо от «сегодня нечего сказать».
 *
 * Это самая дорогая форма отказа: она выглядит как «тихо», а не как «сломано». Поэтому окно
 * говорит вслух — и говорит обе половины, включая ту, которой на экране нет: что бот молчит по
 * той же причине.
 *
 * ═══════════════ ОТВЕТ «НЕТ» — ЭТО НЕ МОЛЧАНИЕ ════════════════════════════════════
 *
 * Ровно одна вещь называется потерей связи: НИКТО НЕ ОТВЕТИЛ. Дверь, ответившая 401, 404 или
 * 500, — живая: демон стоит, слушает и имеет мнение, а у экрана, который спрашивал, уже есть
 * свои слова на этот случай. Поэтому решение принимается не по факту ошибки, а по её ПОРОДЕ:
 * `ApiError` несёт статус, то есть ответ; всё остальное — оборванный сокет, отказ соединения,
 * истёкшее ожидание — это тишина. Полоса, зажигающаяся на 404, обесценила бы себя за неделю.
 *
 * ═══════════════ И НЕ ПО ПОДОЗРЕНИЮ ═══════════════════════════════════════════════
 *
 * Одна неудачная посылка — не потеря связи. Слово говорится только тогда, когда чтение картины
 * ИСЧЕРПАЛО свои повторы и объявило себя неудавшимся (`isError`), — то же правило, по которому
 * полоса о недоступном хабе не пугает раньше времени.
 *
 * ЭТОТ МОДУЛЬ НИЧЕГО НЕ ИМПОРТИРУЕТ, КРОМЕ ФОРМЫ ОШИБКИ. Ни React, ни query-клиента: решение и
 * слова проверяются сьютом демона напрямую, без DOM.
 */

/** То немногое от чтения картины, что здесь читается. Ровно поля, а не хук: их даёт и тест. */
export interface LinkReading {
  /** Чтение исчерпало повторы и объявило себя неудавшимся. */
  isError: boolean
  /** Чем именно оно кончилось — по породе этой ошибки и принимается решение. */
  error: unknown
  /** Когда картина в последний раз была прочитана успешно (0 — ни разу). */
  dataUpdatedAt: number
}

/**
 * doorSilent(err) — никто не ответил?
 *
 * `ApiError` — это ОТВЕТ: у него есть статус, за ним стоит живой демон, и говорить о потере
 * связи в этом случае значило бы врать. Всё прочее — обрыв, отказ соединения, истёкший срок
 * ожидания — тишина.
 */
export function doorSilent(err: unknown): boolean {
  if (err === null || err === undefined) return false
  return !(err instanceof ApiError)
}

/** linkLost(reading) — окно обязано сказать, что связь потеряна. */
export function linkLost(reading: LinkReading): boolean {
  return reading.isError === true && doorSilent(reading.error)
}

/** «14:07:12» местными часами: человеку нужен его час, а не строка ISO. */
function hhmmss(at: number): string {
  const d = new Date(at)
  const p = (n: number) => String(n).padStart(2, '0')
  return `${p(d.getHours())}:${p(d.getMinutes())}:${p(d.getSeconds())}`
}

/**
 * linkWords(reading) — что именно человек читает. Четыре предложения, и каждое зарабатывает
 * своё место:
 *
 *  1. связь потеряна — окно больше не читает картину, а не «медленно»;
 *  2. то, что на экране, — прошлое, и названо, насколько давнее;
 *  3. бот молчит ПО ЭТОЙ ЖЕ ПРИЧИНЕ — иначе тишина в телефоне читается как спокойная ночь;
 *  4. что произойдёт дальше — и здесь окно не обещает того, чего не знает: сторож либо
 *     запущен, либо нет, и окно, у которого нет связи, спросить об этом не у кого.
 */
export function linkWords(reading: LinkReading): string[] {
  const seen =
    reading.dataUpdatedAt > 0
      ? `На экране — последнее, что окно успело прочитать в ${hhmmss(reading.dataUpdatedAt)}; с тех пор оно не знает ничего.`
      : 'Окно не успело прочитать картину ни разу — всё, что здесь показано, пусто, а не тихо.'
  return [
    'Связь с демоном потеряна: дверь не отвечает.',
    seen,
    'Бота ведёт тот же процесс, так что в телеграме сейчас тоже тишина — это то же самое падение, а не «нечего сказать».',
    'Если рядом работает сторож (npm run daemon:watch), он поднимет демона сам и пришлёт в телеграм два сообщения — о падении и о подъёме. Если сторожа нет, демона придётся вернуть из терминала: npm run daemon:restart.',
  ]
}
