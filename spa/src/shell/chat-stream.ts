import type { EventFrame } from '../api/types'

/**
 * chat-stream — как окно собирает ЖИВОЙ ход разговора из кадров потока.
 *
 * ═══════════════════ ЧТО ПРИЕЗЖАЕТ ПО ПРОВОДУ ══════════════════════════════════════
 *
 * Не ответ. Кадр `chat.stage` несёт имя хода, короткое имя ЭТАПА и его номер — и больше
 * ничего: слова разговора в кадр не входят, потому что поток пишется всем открытым клиентам
 * разом, а вопрос владельца принадлежит тому, кто его задал. Слова ответа приезжают ответом
 * того самого запроса, который их спросил.
 *
 * ═══════════════════ ПОЧЕМУ СЛОВА ЭТАПОВ ЖИВУТ ЗДЕСЬ ═══════════════════════════════
 *
 * По проводу едет ИМЯ из закрытого списка, а по-русски его произносит окно — тем же
 * порядком, каким окно произносит статусы задач. Имени, которого в словаре ниже нет, окно не
 * покажет вовсе: строка, пришедшая с провода и напечатанная как есть, — это ровно тот путь,
 * которым текст из кадра однажды окажется на стекле.
 *
 * ═══════════════════ ЭТО ЧИСТАЯ ФУНКЦИЯ, И ЭТО НАРОЧНО ════════════════════════════
 *
 * Свёртка вынесена из окна, чтобы «кусок из потока → пузырь пополняется» доказывалось
 * прогоном, а не рассматриванием экрана. Модуль не тянет ни React, ни запросов — его читает
 * тест демона, у которого нет ни того, ни другого.
 */

/** Этапы, которые окно умеет произнести. Ключи — закрытый словарь демона (`CHAT_STAGES`). */
export const CHAT_STAGE_WORDS: Record<string, string> = {
  accepted: 'получено',
  context: 'читаю контекст…',
  writing: 'пишу ответ…',
  done: 'ответ готов',
}

/** Ход, как окно его держит, пока ответа ещё нет. */
export interface TurnStream {
  /** Чей это ход. Кадр с чужим именем — не про этот пузырь. */
  turnId: string
  /** Номер последнего применённого кадра: кадр не старше уже применённого не применяется. */
  seq: number
  /** Слова этапов в порядке прихода — это и есть содержимое пузыря «думает…». */
  stages: string[]
}

/** Пустой ход: имя есть, сказать пока нечего. */
export function emptyStream(turnId: string): TurnStream {
  return { turnId, seq: 0, stages: [] }
}

/**
 * foldStream(prev, frame) → ход с учтённым кадром, или ТОТ ЖЕ объект, если учитывать нечего.
 *
 * Отбрасывается всё, что не про этот пузырь: чужое имя события, чужой ход, кадр не по
 * порядку (поток может доставить дважды или не в том порядке — номер расставляет их сам), и
 * имя этапа, которого окно не знает. Возврат ТОГО ЖЕ объекта важен: окно перерисовывается по
 * смене ссылки, и кадр, который ничего не изменил, не должен выглядеть как изменение.
 */
export function foldStream(prev: TurnStream, frame: EventFrame): TurnStream {
  if (!prev || !frame) return prev
  if (frame.event !== 'chat.stage') return prev
  if (!frame.turnId || frame.turnId !== prev.turnId) return prev
  const seq = typeof frame.seq === 'number' ? frame.seq : 0
  if (seq <= prev.seq) return prev
  const word = frame.stage ? CHAT_STAGE_WORDS[frame.stage] : undefined
  if (!word) return prev
  return { turnId: prev.turnId, seq, stages: [...prev.stages, word] }
}
