import { useSyncExternalStore } from 'react'

import type { ScreenId } from '../../screens/registry'

/**
 * narrow.ts — ЕДИНСТВЕННОЕ место, где записано, что такое «узко» и что узкая полоса умеет.
 *
 * ═══════════════════ УЗКАЯ ПОЛОСА — ОТДЕЛЬНАЯ РАБОТА, А НЕ БРЕЙКПОИНТ ═══════════════════
 *
 * В шапке рамы окна автором заявлено прямо: окно сделано для рабочего экрана — широкого, по
 * одному делу за раз, без складывания и сжатия; экран поменьше — отдельная работа, которую
 * берут на её условиях, а не протаскивают точкой перелома. Эта папка и есть та отдельная
 * работа. Здесь не появляется ни одного медиа-запроса поверх экранов стола: экраны стола не
 * трогаются вовсе, у узкой полосы свой короткий состав и свои строки.
 *
 * ═══════════════════════ ПОРОГ НЕ СНЯТ, А ПЕРЕНЕСЁН ═══════════════════════
 *
 * Минимум в 1360 px нужен раме широкого стола: без него на узком экране вбок уезжала вся
 * страница целиком — ровно та болезнь, ради которой минимум когда-то и поставили. Поэтому
 * решение принимается НЕ «на окне целиком», а на уровне того, ЧТО показано: широкой раме
 * минимум по-прежнему нужен, узкой работе — нет. Число живёт здесь, одно, и рама сверяется с
 * ним машиной (тест проводов читает исходник рамы), а не глазом.
 *
 * Побочное следствие порога, названное вслух: узкую полосу получает и планшет — 768 px
 * меньше 1360, значит планшет тоже «узко». Это осознанно: планшету широкая рама так же не
 * помещается, и половинчатая вёрстка на нём была бы той же кашей, что на телефоне.
 */

/** Минимум, при котором рама широкого стола помещается целиком. Он же стоит на самой раме. */
export const WIDE_MIN_PX = 1360

/**
 * Медиа-запрос широкой ширины — построенный ИЗ константы, чтобы число оставалось одно.
 * «Узко» — это отрицание этого запроса, а не второе число рядом с первым.
 */
export function wideMediaQuery(): string {
  return `(min-width: ${WIDE_MIN_PX}px)`
}

/**
 * СОСТАВ УЗКОЙ ПОЛОСЫ, ОБЪЯВЛЕННЫЙ СПИСКОМ.
 *
 * Телефон умеет ровно одно дело целиком: увидеть, что от тебя ждут, открыть задачу и принять
 * её. Это экран задач и всё, что из него растёт (полоса «ждут вас» → список → карточка →
 * приёмка). Остальные экраны на узкой ширине честно отдаются столу и говорят об этом словами.
 *
 * Это РЕШЕНИЕ, а не недоделка: экран памяти, живого потока или машин, сжатый в 375 px, стал бы
 * кашей, в которой не работает ни он, ни соседи, — а честная надпись сообщает человеку, что
 * вещь цела и открывается с компьютера.
 */
const NARROW_CAPABLE_IDS = ['tasks'] as const

/** Тот же состав множеством — по нему и спрашивают. */
export const NARROW_CAPABLE: ReadonlySet<ScreenId> = new Set<ScreenId>(NARROW_CAPABLE_IDS)

/** Умеет ли узкая полоса показать этот экран сама. Ответ есть у КАЖДОГО экрана окна. */
export function isNarrowCapable(id: ScreenId): boolean {
  return NARROW_CAPABLE.has(id)
}

/**
 * ПОЛ ДОСТУПНОСТИ УЗКОЙ ПОЛОСЫ — числами, а не пожеланием в прозе.
 *
 * Телефон — ровно то место, где размер цели и размер текста решают, работает вещь или нет:
 * промах пальцем мимо приёмки стоит человеку захода заново, а текст мельче читаемого он не
 * прочитает вовсе. Поэтому числа названы здесь, а тест проводов сверяет их с тем, что реально
 * написано в разметке узких файлов. Пункт, живущий только в прозе задачи, не переживёт
 * первого же рефакторинга — этот переживёт: его уронит прогон.
 *
 * В самой разметке классы пишутся ЛИТЕРАЛАМИ (`min-h-[44px]`, `text-[13px]`), а не собираются
 * из этих констант в строку: сборщик стилей ищет имена классов по тексту исходника, и класс,
 * склеенный на ходу, до готового стиля не доезжает вовсе. Отсюда и нужен тест: он сверяет
 * литерал с константой машиной.
 */
export const TAP_MIN_PX = 44
export const TEXT_MIN_PX = 13

/**
 * Шире ли окно порога ПРЯМО СЕЙЧАС.
 *
 * Там, где спросить не у кого (окна нет или браузер старее `matchMedia`), ответ — «широко»:
 * широкая рама существует и работает, а узкая полоса показывает только часть состава. Из двух
 * ответов наугад безопаснее тот, который ничего не прячет.
 */
function isWideNow(): boolean {
  if (typeof window === 'undefined' || typeof window.matchMedia !== 'function') return true
  return window.matchMedia(wideMediaQuery()).matches
}

/** Подписка на переход через порог. Слушатель снимается — иначе он переживёт само окно. */
function subscribeToWidth(onChange: () => void): () => void {
  if (typeof window === 'undefined' || typeof window.matchMedia !== 'function') return () => {}
  const query = window.matchMedia(wideMediaQuery())
  query.addEventListener('change', onChange)
  return () => query.removeEventListener('change', onChange)
}

/**
 * Узко ли сейчас — признак, на который смотрит рама, решая, какую работу показать.
 *
 * Читается через внешнее хранилище, а не через `useEffect` с состоянием: ширина живёт вне
 * окна, и первый кадр обязан знать её сразу, а не после первой перерисовки. Иначе на телефоне
 * успевала бы мелькнуть широкая рама — то самое уезжающее вбок окно, от которого уходим.
 */
export function useIsNarrow(): boolean {
  const wide = useSyncExternalStore(subscribeToWidth, isWideNow, () => true)
  return !wide
}
