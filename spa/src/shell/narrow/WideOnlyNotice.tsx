/**
 * WideOnlyNotice — честная надпись вместо сломанной вёрстки.
 *
 * ═══════════════ ПОЧЕМУ НАДПИСЬ ЛУЧШЕ СЖАТОГО ЭКРАНА ═══════════════
 *
 * Экран памяти, машин или живого потока, втиснутый в 375 px, — это каша, в которой не
 * работает ни он, ни соседи: колонки наезжают друг на друга, кнопки уезжают за край, и
 * человек решает, что вещь сломана. Надпись говорит ровно обратное: вещь цела, она сделана
 * для широкого рабочего экрана, и это РЕШЕНИЕ, а не недоделка. Человек, прочитавший
 * решение, знает, что делать дальше; человек, увидевший кашу, не знает ничего.
 *
 * Поэтому здесь нет ни «скоро будет», ни «в разработке»: обещаний, которых никто не давал,
 * эта надпись не раздаёт. Она называет экран по имени, говорит, где он открывается, и
 * возвращает туда, где телефон работает целиком.
 */
export function WideOnlyNotice({ title, onBack }: { title: string; onBack: () => void }) {
  return (
    <section className="flex flex-col gap-4 px-4 py-6">
      <div className="flex flex-col gap-3 rounded-[10px] border border-bd bg-card px-4 py-5">
        <span className="text-[15px] leading-[1.35] font-semibold text-tx">{title}</span>
        <p className="m-0 text-[13px] leading-[1.55] text-tx2">
          Этот экран сделан для широкого рабочего экрана, и его открывают с компьютера. На телефоне
          он не показывается не потому, что сломан, а потому, что так решено: сжатый до ширины
          ладони, он стал бы нечитаемым — и работать в нём всё равно было бы нельзя.
        </p>
        <p className="m-0 text-[13px] leading-[1.55] text-tx3">
          Телефон умеет одно дело целиком: увидеть, что от вас ждут, открыть задачу и принять её.
          Остальное — работа стола.
        </p>
      </div>

      <button
        type="button"
        onClick={onBack}
        className="flex min-h-[44px] w-full items-center justify-center rounded-[10px] bg-blue px-4 text-[14px] font-semibold text-white focus-visible:outline-2 focus-visible:outline-blue"
      >
        К задачам
      </button>
    </section>
  )
}
