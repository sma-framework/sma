/**
 * live-timer.ts — ЖИВОЙ ТАЙМЕР СУЩНОСТИ: «момент + состояние → вид чипа», и ничего больше.
 *
 * ═══════════════ ПОЧЕМУ ЭТО ЧИСТАЯ ФУНКЦИЯ, А НЕ ВЫЧИСЛЕНИЕ ВНУТРИ КОМПОНЕНТА ═══════════════
 *
 * Таймер — единственное на экране, что меняется само, без нового ответа двери. Именно поэтому
 * посчитанный прямо в разметке он врёт молча: «идёт 2 ч» на встав­шей задаче и «ждёт вас 4 ч» на
 * той, которую уже одобрили, выглядят ровно так же убедительно, как правда. Проверить это
 * глазом нельзя — на живом экране число всегда правдоподобно.
 *
 * Поэтому решение «какой чип показать» принимается ЗДЕСЬ, по двум входам, и утверждается
 * прогоном; компонент только заводит секундный интервал и рисует то, что здесь решено. Та же
 * граница, что у окошка показателей (`stats.ts`), и по той же причине.
 *
 * ═══════════════════════ «СЕЙЧАС» ПРИХОДИТ СНАРУЖИ ═══════════════════════
 *
 * Часы дёргает тот, кто рисует. Функция, читающая `Date.now()` сама, недоказуема прогоном —
 * а расхождение таймера с правдой никто потом и не заметит.
 *
 * ═══════════════════ НЕТ МОМЕНТА — НЕТ ЧИПА, И ЭТО УТВЕРЖДЕНИЕ ═══════════════════
 *
 * Момент приезжает от двери и у старых сущностей отсутствует честно: попытка старше поля,
 * сборка старше отметки о просьбе, за задачи фазы ещё никто не брался. Ноль на этом месте
 * нарисовал бы «идёт 0 с» — работу, которой нет; `new Date(undefined)` нарисовал бы «NaN с».
 * Оба написания уже случались в этом дереве. Здесь неизвестное возвращается `null`, и шапка
 * просто не рисует чип: молчание честнее выдуманного числа.
 */

/**
 * СОСТОЯНИЕ СУЩНОСТИ ГЛАЗАМИ ТАЙМЕРА — четыре слова, к которым сводятся все словари экранов.
 *
 * `idle` — таймеру нечего показывать: работа закрыта, отменена или ещё не начиналась. Тикающее
 * время на закрытой сущности растёт вечно и утверждает, что она всё ещё в работе.
 */
export type TimerState = 'running' | 'waiting' | 'failed' | 'idle'

/** Момент, как его отдают двери: миллисекунды эпохи или ISO-строка попытки. */
export type Moment = number | string | null | undefined

export interface TimerChip {
  /** Состояние, ради которого чип и нарисован; `idle` сюда не доезжает — вместо него `null`. */
  state: 'running' | 'waiting' | 'failed'
  /** Крутится ли колечко. Крутится только то, что действительно идёт прямо сейчас. */
  spinning: boolean
  /** Слово состояния: «идёт» / «ждёт вас» / «встала». */
  word: string
  /** Что человек читает целиком: «ждёт вас 2 м 14 с». */
  text: string
  /** Сколько секунд прошло — числом, чтобы прогон утверждал время, а не его написание. */
  seconds: number
  /** Классы оболочки чипа из палитры темы: синий / янтарный / красный. */
  tone: string
}

/** Слова состояний. Названы один раз — экран их только показывает. */
const WORD: Record<TimerChip['state'], string> = {
  running: 'идёт',
  waiting: 'ждёт вас',
  failed: 'встала',
}

/**
 * Цвета — токенами темы, не хексами: чип обязан выглядеть одинаково на светлой и тёмной.
 * Синий — работа идёт, янтарный — ждут человека, красный — встала.
 */
const TONE: Record<TimerChip['state'], string> = {
  running: 'border-blue-s bg-blue-s text-blue-d',
  waiting: 'border-warn-s bg-warn-s text-warn-tx',
  failed: 'border-err-bd bg-err-s text-err-tx',
}

/**
 * Момент в миллисекунды — или `null`, если момента нет ВОВСЕ.
 *
 * Отдельная функция потому, что «нет момента» приезжает четырьмя разными написаниями: поля нет,
 * поле `null`, строка непарсится, число не число. Все четыре обязаны кончиться одним и тем же
 * молчанием, а не четырьмя разными видами чипа.
 */
export function momentMs(value: Moment): number | null {
  if (typeof value === 'number') return Number.isFinite(value) ? value : null
  if (typeof value !== 'string' || value.trim() === '') return null
  const ms = new Date(value).getTime()
  return Number.isNaN(ms) ? null : ms
}

/**
 * Длительность вслух: «2 ч 40 м 14 с», «49 м 3 с», «7 с».
 *
 * Секунды стоят всегда — ими таймер и отличается от подписи «идёт 49 м» в окошке показателей:
 * человек смотрит на чип, чтобы увидеть, что система ЖИВА, и неподвижное число этого не говорит.
 */
export function durationWords(seconds: number): string {
  const s = Math.max(0, Math.floor(seconds))
  const h = Math.floor(s / 3600)
  const m = Math.floor((s % 3600) / 60)
  const x = s % 60
  return `${h > 0 ? `${h} ч ` : ''}${h > 0 || m > 0 ? `${m} м ` : ''}${x} с`
}

/**
 * timerChip(state, since, now) → чип шапки, или `null`, когда показывать нечего.
 *
 * `null` возвращается по двум РАЗНЫМ поводам, и оба — правда, а не ошибка: сущности нечего
 * отсчитывать (`idle`) или момента никто не записал. Разницу между ними знает вызывающий, а
 * рисуется она одинаково — пустым местом.
 *
 * Момент из будущего (часы машины ушли вперёд, ответ двери отстал) даёт ноль секунд, а не
 * пропавший чип: секунда расхождения не повод молчать о живой работе.
 */
export function timerChip(state: TimerState, since: Moment, now: number): TimerChip | null {
  if (state === 'idle') return null
  const from = momentMs(since)
  if (from === null || !Number.isFinite(now)) return null

  const seconds = Math.max(0, Math.floor((now - from) / 1000))
  return {
    state,
    // Колечко крутится только у работы, которая идёт. У ждущей и вставшей оно стоит — время
    // растёт, а движения нет, и это ровно то, что с ними происходит.
    spinning: state === 'running',
    word: WORD[state],
    text: `${WORD[state]} ${durationWords(seconds)}`,
    seconds,
    tone: TONE[state],
  }
}
