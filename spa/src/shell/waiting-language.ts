/**
 * waiting-language.ts — ЕДИНЫЙ ЯЗЫК ОЖИДАНИЯ: чем окно занято, пока на месте содержимого ещё пусто.
 *
 * ═══════════════════ ПОЧЕМУ ЭТО ВООБЩЕ ЕСТЬ ═══════════════════
 *
 * Переключение проекта чинили уже один раз — и починили ПЕРЕКЛЮЧАТЕЛЬ: он называет, куда идёт,
 * и не принимает второго нажатия. Область справа в этот момент остаётся пустой: экраны
 * пересобираются, данных ещё нет, и человек смотрит на белое место, где через секунду появится
 * ответ. Жалоба владельца была именно про это место, а не про кнопку.
 *
 * Поэтому ожидание перестаёт быть делом каждого экрана и становится ОДНИМ языком: пока
 * содержимого нет, на его месте стоит полоса-горизонт, а через пару секунд рядом появляются
 * слова. Экран не решает, как выглядит ожидание, — он только называет, чего ждёт.
 *
 * ═══════════════════ ТРИ ПРАВКИ К ОБРАЗЦУ, И ВСЕ ТРИ ЗДЕСЬ ═══════════════════
 *
 * Формы гребней взяты из образца владельца (пять отдельных путей, каждый прижат к низу, слои
 * уже разделены — параллакс достаётся даром). Изменено три вещи, и каждая изменена по причине:
 *
 *  1. ЦВЕТ — НЕ ИЗ ФАЙЛА, А ИЗ ТОКЕНОВ. В исходном образце красно-оранжевая палитра, а в этом
 *     окне красный означает ОШИБКУ (`--color-err*`): экран ожидания в цветах провала учит
 *     человека, что каждое переключение проекта — авария. Ни одного хекса здесь нет вовсе:
 *     слои названы токенами, и потому одинаково честны в светлой теме и в тёмной.
 *  2. МАСШТАБ — ПОЛОСА, А НЕ ЗАСТАВКА. Образец 1920×1080 занимает весь экран; заставка во весь
 *     экран решает другую задачу и создаёт новую — на неё смотрят ВМЕСТО места, где появится
 *     ответ. Полоса стоит внизу той области, куда приедет содержимое.
 *  3. КРАСИВОЕ ОЖИДАНИЕ ПРЯЧЕТ ЗАВИСАНИЕ. Если движение хорошо, сломанное выглядит как
 *     задуманное. Поэтому движение обещает, а СЛОВА говорят правду: через `WORDS_AFTER_MS`
 *     рядом появляется, что именно идёт и сколько уже. Ровно этого не хватало белому экрану —
 *     не картинки, а признания, что ответа всё ещё нет.
 *
 * ═══════════════════ ПОЧЕМУ РЕШЕНИЕ ЖИВЁТ ЗДЕСЬ, А НЕ В КОМПОНЕНТЕ ═══════════════════
 *
 * «Ждать или показывать экран» — это правило про ЧЕТЫРЕ входа сразу (идёт ли переключение,
 * приехала ли картина вообще, про тот ли она проект, и читается ли она прямо сейчас). Написанное
 * прямо в разметке, оно врёт молча: лишний `true` вешает полосу поверх живого экрана на каждом
 * опросе, лишний `false` возвращает белое место. Проверить это глазом нельзя — на живом окне обе
 * ошибки выглядят правдоподобно. Поэтому решение принимается ЗДЕСЬ и утверждается прогоном, а
 * компонент только рисует. Та же граница, что у таймера (`live-timer.ts`), и по той же причине.
 */

