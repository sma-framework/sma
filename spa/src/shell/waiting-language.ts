/**
 * Один слой горизонта: форма из образца, цвет из токена, своя скорость.
 *
 * `drift` — насколько слой уезжает вбок за один проход, в процентах собственной ширины. Числа
 * убывают от дальнего слоя к ближнему и чередуются знаком: разная скорость и разные стороны —
 * это и есть глубина, ради которой образец брали слоями, а не одной картинкой.
 */
export interface WaitLayer {
  /** Имя слоя — только для ключа в разметке и для прогона. */
  id: string
  /** Путь-гребень: та же форма, что в образце, прижатая к низу кадра. */
  d: string
  /** Цвет — ИМЯ ТОКЕНА, а не хекс: тема решает, каким он окажется. */
  fill: string
  /** Смещение за проход, в процентах ширины слоя. */
  drift: string
  /** Длительность одного прохода. Дальний слой медленнее ближнего. */
  seconds: number
}

