/**
 * waiting-language.ts — ЕДИНЫЙ ЯЗЫК ОЖИДАНИЯ: чем окно занято, пока на месте содержимого ещё пусто.
 *
 * ═══════════════════ ПОЧЕМУ ЭТО ВООБЩЕ ЕСТЬ ═══════════════════
 *
 * Переключение проекта чинили уже один раз — и починили ПЕРЕКЛЮЧАТЕЛЬ: он называет, куда идёт,
 * и не принимает второго нажатия. Область справа в этот момент остаётся пустой: экраны
 * пересобираются, данных ещё нет, и человек смотрит на белое место, где через секунду появится
 * ответ. Жалоба владельца была именно про это место, а не про кнопку.
 *
 * Поэтому ожидание перестаёт быть делом каждого экрана и становится ОДНИМ языком: пока
 * содержимого нет, на его месте стоит карточка с полем колец, а через пару секунд поверх колец
 * появляются слова. Экран не решает, как выглядит ожидание, — он только называет, чего ждёт.
 *
 * ═══════════════════ ЧЕТЫРЕ ПРАВКИ К ОБРАЗЦУ, И ВСЕ ЧЕТЫРЕ ЗДЕСЬ ═══════════════════
 *
 * Образец владельца — поле концентрических КОЛЕЦ: шесть тонких окружностей, расходящихся от
 * общего центра, с лёгким шумом на линии. Взяты у образца ЧИСЛА (сколько колец, с какого
 * радиуса, с каким шагом, толщина линии, пауза между вспышками, время нарастания и угасания);
 * код здесь свой — обычный SVG и обычные кадры CSS, без единой новой зависимости. Изменено
 * четыре вещи, и каждая изменена по причине:
 *
 *  1. ЦВЕТ — НЕ ИЗ ОБРАЗЦА, А ИЗ ТОКЕНОВ. В образце розово-голубая пара (#fc42ff/#42fcff) —
 *     ни один из этих цветов в окне не значит ничего. Кольца названы токенами, и потому
 *     одинаково честны в светлой теме и в тёмной. Красных среди них нет намеренно: красный в
 *     этом окне означает ОШИБКУ (`--color-err*`), и экран ожидания в цветах провала учил бы
 *     человека, что всякое переключение проекта — авария.
 *  2. МАСШТАБ — КАРТОЧКА, А НЕ ЗАСТАВКА. Образец занимает экран целиком; заставка во весь
 *     экран решает другую задачу и создаёт новую — на неё смотрят ВМЕСТО места, где появится
 *     ответ. Поле колец стоит ровно в той карточке, куда приедет содержимое.
 *  3. РУКИ У ОЖИДАНИЯ НЕТ. В образце кольца тянутся за мышью и вспыхивают по клику. Ожидание
 *     не интерфейс: отвечать на руку значит обещать, что здесь есть чем управлять, — а здесь
 *     нечем, здесь ждут ответа двери. `followMouse` и `clickBurst` выключены не настройкой, а
 *     отсутствием кода: ни одного обработчика указателя в этом ожидании нет.
 *  4. КРАСИВОЕ ОЖИДАНИЕ ПРЯЧЕТ ЗАВИСАНИЕ. Если движение хорошо, сломанное выглядит как
 *     задуманное. Поэтому движение обещает, а СЛОВА говорят правду: через `WORDS_AFTER_MS`
 *     поверх колец появляется, что именно идёт и сколько уже. Ровно этого не хватало белому
 *     экрану — не картинки, а признания, что ответа всё ещё нет.
 *
 * ═══════════════════ ПОЧЕМУ РЕШЕНИЕ ЖИВЁТ ЗДЕСЬ, А НЕ В КОМПОНЕНТЕ ═══════════════════
 *
 * «Ждать или показывать экран» — это правило про ЧЕТЫРЕ входа сразу (идёт ли переключение,
 * приехала ли картина вообще, про тот ли она проект, и читается ли она прямо сейчас). Написанное
 * прямо в разметке, оно врёт молча: лишний `true` вешает ожидание поверх живого экрана на
 * каждом опросе, лишний `false` возвращает белое место. Проверить это глазом нельзя — на живом окне обе
 * ошибки выглядят правдоподобно. Поэтому решение принимается ЗДЕСЬ и утверждается прогоном, а
 * компонент только рисует. Та же граница, что у таймера (`live-timer.ts`), и по той же причине.
 */

import { durationWords } from './live-timer'

/**
 * Одно кольцо поля: радиус из чисел образца, цвет из токена, своя очередь вспыхнуть.
 */
export interface WaitRing {
  /** Имя кольца — только для ключа в разметке и для прогона. */
  id: string
  /** Радиус в единицах кадра. Растёт от внутреннего кольца к внешнему. */
  radius: number
  /** Цвет — ИМЯ ТОКЕНА, а не хекс: тема решает, каким он окажется. */
  stroke: string
  /**
   * Сдвиг начала, секунды, и он ОТРИЦАТЕЛЬНЫЙ намеренно: положительная задержка означала бы,
   * что первые секунды ожидания часть колец стоит невспыхнувшей — то есть ровно в тот момент,
   * когда на экран смотрят внимательнее всего, поле выглядит недорисованным. Отрицательная
   * задержка ставит кольцо в СЕРЕДИНУ его цикла: волна идёт от центра наружу с первого кадра.
   */
  delay: number
  /** Непрозрачность в покое: внешние кольца тише внутренних — это и есть глубина. */
  rest: number
}

/** Кадр колец — квадрат: круг, растянутый по ширине области, кольцом уже не является. */
export const WAIT_VIEWBOX = '0 0 400 400'

/** Сторона кадра и центр поля: все кольца концентрические, центр у них один. */
export const WAIT_FRAME = 400
export const WAIT_CENTER = WAIT_FRAME / 2

/** Поле за кольцами — тоже токен, а не хекс. */
export const WAIT_SKY = '--color-wait-sky'

/* ─────────── ЧИСЛА ОБРАЗЦА. Каждое названо здесь и больше нигде не повторяется. ─────────── */

/** Сколько колец. */
export const RING_COUNT = 6
/** Радиус внутреннего кольца — доля кадра. */
export const RING_BASE_RADIUS = 0.35
/** Насколько каждое следующее кольцо шире предыдущего — доля кадра. */
export const RING_RADIUS_STEP = 0.1
/** Толщина линии, ЭКРАННЫЕ пиксели: кольцо тонкое в любом масштабе карточки. */
export const RING_LINE_PX = 2
/** Пауза между вспышками соседних колец, секунды. */
export const RING_GAP_S = 1.5
/** Сколько кольцо разгорается. */
export const RING_FADE_IN_S = 0.7
/** …и сколько гаснет обратно в покой. */
export const RING_FADE_OUT_S = 0.5
/** Сила шума на линии: 0 — идеальная окружность, 1 — рваная. */
export const RING_NOISE = 0.1
/** Общая скорость. Единица — темп образца; здесь он и остаётся. */
export const RING_SPEED = 1

/**
 * Длительность полного круга волны: каждое кольцо вспыхивает раз за цикл, соседи — через
 * `RING_GAP_S`. Отсюда же берутся проценты кадров в CSS, и потому число здесь ОДНО.
 */
export const RING_CYCLE_S = (RING_COUNT * RING_GAP_S) / RING_SPEED

/** Доля цикла, на которой кольцо разгорелось, — в процентах кадров CSS. */
export const RING_PEAK_PCT = Math.round((1000 * RING_FADE_IN_S) / RING_CYCLE_S) / 10

/** …и доля, на которой оно вернулось в покой. */
export const RING_SETTLE_PCT =
  Math.round((1000 * (RING_FADE_IN_S + RING_FADE_OUT_S)) / RING_CYCLE_S) / 10

/**
 * НАБУХАНИЕ НА ВСПЫШКЕ — пять процентов, и это не скромность ради скромности.
 *
 * Кольцо, расходящееся широко, читается как ДЕЙСТВИЕ: что-то произошло, что-то отправлено.
 * Здесь не происходит ничего — здесь ждут ответа, — и движение обязано об этом не врать.
 */
export const RING_SWELL = 1.05

/**
 * ИМЕНА ЦВЕТОВ ВЫПИСАНЫ ЦЕЛИКОМ, И ЭТО НЕ МНОГОСЛОВИЕ, А ТРЕБОВАНИЕ СБОРКИ.
 *
 * Сборщик тем оставляет в готовом CSS только те переменные темы, ИМЯ которых он нашёл в
 * исходниках; всё остальное он считает неиспользованным и выбрасывает. Собранное
 * `--color-wait-${i + 1}` именем не является ни для одного сканера — и это не догадка: первая
 * сборка этой правки потеряла все шесть светлых значений разом, кольца пропали, а тёмная тема
 * уцелела только потому, что её значения объявлены обычным правилом, а не темой. Хуже всего,
 * что молча: и сборка, и типы были зелёными.
 */
const RING_STROKES = [
  '--color-wait-1',
  '--color-wait-2',
  '--color-wait-3',
  '--color-wait-4',
  '--color-wait-5',
  '--color-wait-6',
] as const

/**
 * ПОЛЕ КОЛЕЦ: от внутреннего к внешнему.
 *
 * Порядок в списке — порядок рисования и он же порядок волны: вспыхивает первым внутреннее,
 * последним внешнее, и потому волна идёт ОТ центра, а не к нему.
 */
export const WAIT_RINGS: readonly WaitRing[] = RING_STROKES.slice(0, RING_COUNT).map((stroke, i) => ({
  id: `ring-${i + 1}`,
  radius: Math.round((RING_BASE_RADIUS + i * RING_RADIUS_STEP) * WAIT_FRAME),
  stroke,
  delay: -(RING_COUNT - i) * RING_GAP_S,
  rest: Math.round((0.55 - i * 0.05) * 100) / 100,
}))

/**
 * ГРАНИЦА ПЕРЕХОДА — 300 мс, и она не про фон.
 *
 * Переход — это ПОЯВЛЕНИЕ и ИСЧЕЗНОВЕНИЕ: карточка проступает, слова проступают, содержимое
 * сменяет карточку. Всё это человек ЖДЁТ, и всё это обязано уложиться в треть секунды: переход,
 * который длится дольше, перестаёт быть отзывчивостью и становится задержкой.
 *
 * Постоянный ход колец (`RING_CYCLE_S`) переходом НЕ является и под эту границу не идёт: это
 * фон, который ничего не начинает и ничего не заканчивает, — он просто показывает, что окно
 * живо, пока ответа нет. Мерить его той же линейкой значило бы требовать, чтобы волна обходила
 * шесть колец за 300 мс, то есть мигала — ровно то, от чего признак «уменьшить движение» и
 * защищает.
 */
export const TRANSITION_CAP_MS = 300

/** Карточка проступает, а не возникает: подмена содержимого рывком читается как перерисовка. */
export const APPEAR_MS = 200

/** Слова проступают отдельно и позже — см. `WORDS_AFTER_MS`. */
export const WORDS_MS = 220

/** Содержимое сменяет карточку мягко: «данные приехали» — это ответ, а не вспышка. */
export const SETTLE_MS = 260

/**
 * КОГДА ДВИЖЕНИЕ ЗАМИРАЕТ. Признак системы, а не наша настройка: от пульсирующего фона у части
 * людей кружится голова. С ним кольца стоят на своих радиусах и в своей покойной яркости —
 * поле то же, движения нет. Само правило живёт в CSS (`theme/tokens.css`), здесь — только его
 * имя, чтобы прогон мог потребовать это правило по имени, а не по описанию.
 */
export const REDUCED_MOTION = 'prefers-reduced-motion: reduce'

/** Через сколько рядом с движением появляются слова. Число — из образца владельца. */
export const WORDS_AFTER_MS = 2400

/** Что окно открывает, когда проект ещё не назван: само окно. */
export const WAIT_WINDOW = 'Открываю окно'

/** …и когда названо переключение проекта. */
export const WAIT_PROJECT = 'Открываю проект'

/**
 * Чего именно ждём — одной строкой, которую увидит человек.
 *
 * Имя проекта в кавычках, потому что оно чужое: «Открываю проект «sma»» читается как одно
 * действие, а «Открываю проект sma» — как два слова подряд. Имени нет (переключение началось
 * раньше, чем приехал список) — говорим про проект без имени, а не выдумываем его.
 */
export function waitingLabel(projectName: string | null, switching: boolean): string {
  if (!switching) return WAIT_WINDOW
  const name = (projectName ?? '').trim()
  return name ? `${WAIT_PROJECT} «${name}»` : WAIT_PROJECT
}

/**
 * Слова ожидания: что идёт и сколько уже.
 *
 * `shown` отдельно от `text` нарочно: до порога слова не пустые, а НЕ ПОКАЗАННЫЕ. Пустая строка
 * на их месте перестроила бы разметку в момент появления — человек увидел бы прыжок как раз
 * тогда, когда начал читать.
 *
 * Длительность считает `durationWords` из таймера: «идёт 3 с», «идёт 1 м 4 с» — одно написание
 * времени на всё окно, а не второе, похожее.
 */
export function waitingWords(what: string, elapsedMs: number): { shown: boolean; text: string } {
  const ms = Number.isFinite(elapsedMs) ? Math.max(0, elapsedMs) : 0
  return { shown: ms >= WORDS_AFTER_MS, text: `${what}… идёт ${durationWords(ms / 1000)}` }
}

/**
 * Что окно знает о картине в тот момент, когда решает, ждать или показывать экран.
 */
export interface WaitInput {
  /** Идёт ли смена проекта прямо сейчас (дверь ещё не ответила). */
  switching: boolean
  /** Приехала ли картина хоть раз. */
  hasPicture: boolean
  /** Про какой проект приехавшая картина. */
  answeredFor: string | null
  /** Про какой проект её спрашивают сейчас. */
  askedFor: string | null
  /** Читается ли картина прямо сейчас. */
  fetching: boolean
}

/**
 * screenWaits(...) → показывать ли ожидание вместо экрана.
 *
 * Три повода, и все три — про ОДНО: на месте содержимого сейчас нечего показать.
 *
 *  1. Идёт переключение — дверь ещё не согласилась, и всё, что на экране, про прежний проект.
 *  2. Картина не приезжала ни разу — это первое открытие окна, показывать нечего вовсе.
 *  3. Картина есть, но она про ДРУГОЙ проект, и новая уже в пути. Ровно это и было белым
 *     экраном: зеркало выбора уже переставлено, экраны фильтруют по новому проекту, а строк
 *     нового проекта в старом ответе нет — и не будет до следующего ответа.
 *
 * И один повод, которого здесь НЕТ намеренно: обычный опрос раз в три секунды. Картина при нём
 * про тот же проект, `fetching` истинно — и если бы этого хватало, ожидание всплывало бы поверх
 * живого экрана каждые три секунды. Ждут не тогда, когда окно спрашивает, а тогда, когда
 * показать нечего.
 */
export function screenWaits(input: WaitInput): boolean {
  if (input.switching) return true
  if (!input.hasPicture) return true
  return input.fetching && input.askedFor !== null && input.askedFor !== input.answeredFor
}
