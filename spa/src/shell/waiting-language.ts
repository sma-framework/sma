/**
 * ГРАНИЦА ПЕРЕХОДА — 300 мс, и она не про фон.
 *
 * Переход — это ПОЯВЛЕНИЕ и ИСЧЕЗНОВЕНИЕ: полоса проступает, слова проступают, содержимое
 * сменяет полосу. Всё это человек ЖДЁТ, и всё это обязано уложиться в треть секунды: переход,
 * который длится дольше, перестаёт быть отзывчивостью и становится задержкой.
 *
 * Постоянный ход слоёв (`WaitLayer.seconds`) переходом НЕ является и под эту границу не идёт:
 * это фон, который ничего не начинает и ничего не заканчивает, — он просто показывает, что
 * окно живо, пока ответа нет. Мерить его той же линейкой значило бы требовать, чтобы горизонт
 * проезжал свой путь за 300 мс, то есть дёргался — ровно то, от чего признак «уменьшить
 * движение» и защищает.
 */
export const TRANSITION_CAP_MS = 300

