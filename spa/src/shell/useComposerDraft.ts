import { useCallback, useEffect, useState } from 'react'

/**
 * useComposerDraft — НАБРАННЫЙ, НО НЕ ОТПРАВЛЕННЫЙ ТЕКСТ ПЕРЕЖИВАЕТ УХОД С ЭКРАНА И ОБРЫВ.
 *
 * ═══════════════ ЧТО ЭТО НЕ ЕСТЬ ═══════════════════════════════════════════════════════
 *
 * Это НЕ «черновик» в том смысле, в каком слово живёт в остальном продукте. Там черновик —
 * предложение системы, приехавшее ответом на разговор: черновик задачи, черновик заметки
 * памяти, черновик агента. У него есть автор (не человек), он лежит на диске у демона, его
 * принимают кнопкой, и он бывает применён. Здесь — ровно наоборот: НЕ ОТПРАВЛЕННЫЕ СЛОВА
 * САМОГО ЧЕЛОВЕКА, которые никто не видел, никуда не поехали и ничего не значат ни для
 * какой двери. Они не покидают браузер. Отсюда и имя: черновик НАБОРА, а не черновик
 * системы, — два разных понятия, которые одним словом путались бы навсегда.
 *
 * ═══════════════ ПОЧЕМУ ЭТО ВООБЩЕ ПОНАДОБИЛОСЬ ═══════════════════════════════════════
 *
 * Оболочка окна размонтирует экран при уходе с него. Полсотни слов, набранных в руле живой
 * задачи, исчезали от одного нажатия на соседний пункт меню — а руль тем и живёт, что в
 * него пишут ПОКА работа идёт, то есть отвлекаясь. Перезагрузка страницы стоила того же.
 * Ни то, ни другое человек не считает своим действием: он не удалял текст.
 *
 * ═══════════════ ФОРМА ВЗЯТА ГОТОВАЯ, А НЕ ПРИДУМАНА ══════════════════════════════════
 *
 * Браузерное хранилище в этом окне уже держит две вещи — включённые уведомления и выбранную
 * тему, — и обе сделаны одинаково: чтение в обёртке try, запись в обёртке try, отказ
 * хранилища никогда не является поводом чему-то сломаться. Тот же приём повторён здесь, а
 * не изобретён второй раз.
 *
 * ХРАНИЛИЩЕ, КОТОРОЕ ОТКАЗАЛО, ЗНАЧИТ «ЧЕРНОВИК НЕ ПЕРЕЖИВЁТ» — И РОВНО ЭТО. Приватный
 * режим, запрет на сайт, переполненная квота от чужой вкладки: во всех этих случаях окно
 * работает как работало, просто набранное не доживёт до следующего открытия. Уронить окно
 * ради сохранности того, что человек ещё даже не отправил, было бы обменом наоборот.
 *
 * ПУСТОЙ ТЕКСТ СТИРАЕТ КЛЮЧ, а не хранится пустой строкой. Поэтому отдельной функции
 * «очистить» здесь нет и не заводится: успешная отправка на всех трёх поверхностях и так
 * заканчивается `setText('')`, и это ЕДИНСТВЕННЫЙ способ, которым черновик перестаёт быть
 * нужным. Экспортировать вторую дорогу к тому же результату значило бы завести помощника,
 * которого никто не зовёт, — тот самый класс, за который этот продукт уже платил.
 *
 * ═══════════════ КЛЮЧ ПРИВЯЗАН К ПОВЕРХНОСТИ, И ПОВЕРХНОСТЬ УМЕЕТ СМЕНИТЬСЯ ═══════════
 *
 * `surface` — это имя места, где набирают, вместе с тем, ПРО ЧТО набирают: руль конкретной
 * задачи, конкретный разговор, системная консоль. Разные задачи не делят один черновик, и
 * это не мелочь: поправка, написанная одной работе и всплывшая в поле другой, — способ
 * отправить не туда.
 *
 * У разговора имя поверхности МЕНЯЕТСЯ по ходу жизни экрана: пока разговора нет, набирают
 * «в новый», а после первого ответа у него появляется собственный идентификатор. Смена
 * улажена подстройкой состояния прямо в отрисовке (документированный приём React для
 * «состояние зависит от пропса»), а не эффектом. Причина точная: два эффекта — «перечитать
 * под новый ключ» и «записать текст» — в одном проходе выполняются по порядку объявления, и
 * второй унёс бы СТАРЫЙ текст под НОВЫЙ ключ, затерев то, что там лежало с прошлого раза.
 * Здесь текст и его ключ лежат в состоянии ОДНОЙ парой и записываются тоже парой, поэтому
 * записать текст не под своим ключом технически невозможно.
 */

/** Общая приставка всех ключей набора — чтобы их было видно и легко отличить в хранилище. */
const PREFIX = 'sma.draft.'

function read(surface: string): string {
  try {
    return window.localStorage.getItem(PREFIX + surface) ?? ''
  } catch {
    return '' // хранилище недоступно — черновика просто нет, и это нормальное состояние
  }
}

function write(surface: string, text: string): void {
  try {
    if (text === '') window.localStorage.removeItem(PREFIX + surface)
    else window.localStorage.setItem(PREFIX + surface, text)
  } catch {
    /* браузер, отказавшийся помнить, — не повод переставать работать */
  }
}

/**
 * Замена `useState('')` для поля ввода: то же самое на вид, но пережившее уход с экрана.
 *
 * @param surface имя поверхности набора, вместе с тем, про что набирают
 *                (`steer.<задача>`, `chat.<разговор>`, `console`)
 */
export function useComposerDraft(surface: string): [string, (next: string) => void] {
  // Текст И КЛЮЧ, ПОД КОТОРЫМ ОН ЛЕЖИТ, — одной парой: см. шапку, это и есть замок от
  // записи текста не под своим ключом.
  const [draft, setDraft] = useState(() => ({ surface, text: read(surface) }))

  if (draft.surface !== surface) {
    // Поверхность сменилась — перечитываем под новую ПРЯМО СЕЙЧАС, до отрисовки и до
    // эффектов. Условие обязательно: без него это был бы вечный цикл.
    setDraft({ surface, text: read(surface) })
  }

  useEffect(() => {
    write(draft.surface, draft.text)
  }, [draft])

  const setText = useCallback((next: string) => setDraft({ surface, text: next }), [surface])

  return [draft.surface === surface ? draft.text : '', setText]
}
