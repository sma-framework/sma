const RECEIPT_BODY = `---
name: sma-receipt
description: Чем закрывается клейм «сделано» — воспроизводимой проверкой, а не словами.
---

# Квитанция

Слова «готово», «работает», «тесты зелёные» ничего не закрывают: их нельзя перепроверить
через неделю, и человек, который их читает, обязан верить на слово. Клейм о сделанной работе
несёт ВОСПРОИЗВОДИМУЮ ПРОВЕРКУ — команду, которую можно запустить снова и получить тот же
ответ.

Квитанция снимается одной командой:

\`\`\`
node scripts/sma/cli.mjs receipt-hash "<команда, которая проверяет вашу работу>"
\`\`\`

Команда выполняется, и последней строкой печатается отпечаток: он связывает саму команду, её
код выхода и её вывод. Этот отпечаток и есть квитанция — его вписывают в отчёт о работе.

Перепроверяет квитанции другой верб, и запускает его уже не работник:

\`\`\`
node scripts/sma/cli.mjs reverify
\`\`\`

Что стоит помнить, работая:

- Квитанция — это ПУТЬ и ВЕРДИКТ, а не пересказ. «Прогнал, всё хорошо» квитанцией не является.
- Проверка, которой не было, никогда не считается пройденной. Не смогли прогнать — так и
  скажите, назвав команду, которая осталась непрогнанной; выдуманный зелёный дороже честного
  «не проверял».
- Верб отказывается выполнять команду вне своего списка безопасных — это не поломка, а замок.
  Возьмите ту проверку, которая в списке есть, или назовите нужную человеку словами.
- Вывод, который честно меняется от запуска к запуску (время, пути во временных каталогах),
  связывают только кодом выхода: \`--exit-only\`. Иначе квитанция будет краснеть на ровном месте
  и перестанет что-либо значить.
`

const LESSON_BODY = `---
name: sma-lesson
description: Как оставить урок, который переживёт задачу, — одной командой конвейера памяти.
---

# Урок

Попытка иногда учит чему-то, что переживёт саму задачу: грабли в этом проекте, неочевидное
поведение инструмента, решение, которое стоило часа и не выводится из кода. Такое знание
записывают в корпус памяти проекта — иначе следующая попытка (и следующий человек) заплатят
за него второй раз.

Урок пишется ОДНОЙ командой. Плоский файл, положенный мимо конвейера, уроком не считается —
проверяется, что заметка пришла именно оттуда:

\`\`\`
node scripts/sma/cli.mjs memory write --corpus .claude/memory \\
  --type procedural --truth inferred --authority self-observed \\
  --id lesson-<короткий-слаг-латиницей> \\
  --claim "<чему научила эта задача, одной фразой>" \\
  --body "<что было, что сделано, чего избегать в следующий раз>" \\
  --areas <тема,тема> --language ru --json
\`\`\`

Команда неинтерактивна и отвечает JSON. Обычный исход — черновик, который ждёт человека: так
ни один факт не входит в память случайно. Это НОРМА, а не отказ.

Что важно:

- \`--corpus .claude/memory\` обязателен. Без него конвейер пишет в основное дерево проекта —
  мимо вашей ветки и мимо приёмки, и урок не увидит никто.
- \`--id\` — только латиница и дефисы: из кириллического текста идентификатор не выводится.
- Один урок — один плоский файл с шапкой. Не пересказывайте то, чему память проекта уже учит:
  вторая копия знания устаревает первой.
- Урок, который можно перепроверить командой, объявляют наблюдением и называют эту команду
  (\`--verification "<команда>"\` и \`--truth observed\`). Перепроверяемое заявление без своей
  проверки тихо устареет, и никто об этом не узнает.
- Индекс памяти пересобирать не нужно — это делает приёмка в основном дереве.

Последней строкой ответа выводят одно из двух:

\`\`\`
${LESSON_MARKERS.written} .claude/memory/drafts/<id>.md
${LESSON_MARKERS.none} <причина одной строкой, почему урока нет>
\`\`\`

«Урока нет» — законный ответ. «Урока нет» без причины — нет.
`

const ASK_BODY = `---
name: sma-ask
description: Что делать с вопросом к человеку — какие каналы есть сегодня, и чего нет.
---

# Вопрос

Сначала честно о главном: **середина работы ответа не даёт**. Человека, который читает ваш
ход в ту секунду, когда вы пишете, — нет. Вопрос, оставленный в надежде на ответ по ходу,
просто остановит попытку и сожжёт её впустую.

Поэтому с вопросом поступают так:

1. **Принимают наименее необратимое решение.** Из двух путей выбирают тот, который человеку
   дешевле отменить: правку легче откатить, чем удаление; добавленное — чем переписанное;
   узкое — чем широкое. Необратимого без человека не делают вовсе.
2. **Записывают сам вопрос — в записку о подходе.** Это то, что человек читает первым, когда
   попытка вернётся к нему:

\`\`\`
${APPROACH_MARKERS.approach} какой подход выбран (одной строкой)
${APPROACH_MARKERS.rejected} какая альтернатива отвергнута и почему
${APPROACH_MARKERS.influences} какое правило или заметка на это повлияли
\`\`\`

   Вопрос и сомнение пишут в отвергнутую альтернативу и в подход: «выбрал А, потому что
   про Б не знаю вот этого — если Б, то переделывать вот здесь». Такую записку человек
   читает как вопрос и отвечает на неё.
3. **Ответ приходит следующей попыткой.** Человек возвращает задачу с замечанием, и его
   замечание приезжает в задание следующего захода вместе с конспектом того, что делал
   предыдущий. Это и есть канал ответа, который существует сегодня.

Чего делать не надо:

- Не задавайте вопрос и не ждите: ждать нечего, ход завершится сам.
- Не молчите о сомнении, «чтобы выглядело чисто». Невысказанное сомнение обходится дороже
  всего: работу примут, а потом переделают.
- Не делайте необратимого «на всякий случай», чтобы не спрашивать.
`

const BROWSER_BODY = `---
name: sma-browser
description: Как открыть окно браузера, войти по учётным данным из окружения, снять экран — и как честно сказать «не смог».
---

# Окно браузера

Экран проверяют, ОТКРЫВ его. Читать обработчик и делать вывод о том, что видит человек, —
не проверка: работает разметка, а сломан запрос за ней, и по коду это не видно.

Ломиться в окно вслепую при этом не надо. Открывает окно команда продукта: она сама
поднимает страницу, ходит по ней вашими шагами, снимает экраны, ловит ошибки страницы и
упавшие запросы и пишет квитанцию.

\`\`\`
node scripts/sma/ui-drive.mjs <адрес> [шаг ...] [--no-sweep]
\`\`\`

Шаги: \`goto:<путь>\` · \`click:<видимый текст>\` · \`type:<селектор>=<текст>\` ·
\`key:<клавиша>\` · \`wait:<мс>\` · \`shot:<имя>\` · \`expect:<видимый текст>\`.

Последней строкой печатается путь к каталогу прогона — там квитанция, журнал и снимки. В
отчёт забирают ЭТОТ путь, а не пересказ увиденного.

## Учётные данные берут из окружения — и только оттуда

Квитанция печатает пройденный путь шагами КАК ОНИ НАПИСАНЫ. Значит, пароль, набранный в
шаге текстом, окажется записанным на диск — в файле, который прикладывают к отчёту. Поэтому
у шага есть вторая форма: она называет ПЕРЕМЕННУЮ вместо значения.

\`\`\`
type:<селектор>=env:<ИМЯ_ПЕРЕМЕННОЙ>
\`\`\`

Значение читается из окружения в момент прогона; на диск уезжает имя. Вход целиком выглядит
так:

\`\`\`
node scripts/sma/ui-drive.mjs http://localhost:5173 --no-sweep \\
  'type:#login=env:APP_LOGIN' 'type:#password=env:APP_PASSWORD' \\
  click:Войти 'expect:Панель' shot:after-login
\`\`\`

Правила, у которых нет исключений:

- **Учётные данные не пишут в файлы** — ни в код, ни в дело, ни в отчёт, ни в сообщение
  коммита, ни в записку о подходе. Ветку с паролем не «поправить»: он остаётся в истории.
- **Переменной нет — шаг честно падает и называет её имя.** Это не повод подставить
  угаданное значение и не повод набрать пустую строку: попросите переменную у человека
  словами, назвав имя, которого не хватило.
- **Учётные данные не выдумывают.** Пары вида «имя-администратора и такой же пароль» — это
  попытка подобрать чужой доступ, а не вход. Не знаете, где взять доступ, — так и скажите.
- Снимок делают ПОСЛЕ входа. Экран с открытым полем ввода — это снимок ваших же учётных
  данных, если поле показывает набранное.

## Снять экран

\`shot:<имя>\` кладёт снимок в каталог прогона и вписывает его в квитанцию. Снимок доказывает,
что экран нарисовался, и ровно ничего больше: панель отлично фотографируется, когда каждый
запрос за ней падает. Что она РАБОТАЕТ, доказывает пустой блокирующий список квитанции.

## Драйвера может не быть — и это говорится вслух

У продукта ноль зависимостей: браузерный драйвер вместе с ним не ставится. Нет драйвера —
команда выходит с кодом 3 и печатает \`NOT RUN\`: окно не открывали, смотреть не на что.

Код 3 — не поломка и не ваша вина. Это единственный честный ответ, и молчать о нём нельзя:
непрогнанная проверка никогда не считается пройденной. Так и пишите — «живой прогон не
делался: драйвера нет», назвав команду, которая осталась непрогнанной.

Драйвер, который стоит в другом дереве, подключают переменной — без установки:

\`\`\`
SMA_UI_DRIVER=<путь к каталогу драйвера> node scripts/sma/ui-drive.mjs <адрес> ...
\`\`\`

Коды выхода: \`0\` — прошло (возможно, с предупреждениями), \`1\` — есть блокирующее,
\`2\` — плохие аргументы, \`3\` — НЕ ЗАПУСКАЛОСЬ.

Чего делать нельзя:

- ставить драйвер в рабочую копию: её \`node_modules\` — ссылка на дерево, в котором работает
  человек, и установка достаёт до него;
- называть работу проверенной, если прогон вышел с кодом 3;
- заменять квитанцию пересказом того, что вы увидели на снимке.
`

