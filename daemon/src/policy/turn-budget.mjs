/**
 * turn-budget.mjs — HOW BIG THE TURN CEILING IS, AND WHERE THE TURNS WENT.
 *
 * ═══════ ОДНО ЧИСЛО НА ВСЮ РАБОТУ — ЭТО НЕ ПОТОЛОК, А ЛОТЕРЕЯ ══════════════════════════════
 *
 * Пока потолок был одной настройкой, он был одинаков для правки одной строки и для работы,
 * которая трогает несколько файлов и обязана доказать себя живым прогоном. Вторая в это число
 * не помещается ФИЗИЧЕСКИ: код пишется за десяток ходов, а доказательство — это запуски
 * оболочки, чтение их вывода и починка того, что вывод показал. Две ночи подряд работа так и
 * сгорала: сначала на умолчании, потом на удвоенном числе, — и оба раза человек видел красную
 * карточку без единого слова о том, что делать дальше.
 *
 * Здесь потолок перестаёт быть одним числом. Настройка человека (`pipeline.maxTurns`) остаётся
 * тем, чем была, — БАЗОЙ, потолком для маленькой работы; всё остальное множится от неё по
 * размеру самой работы.
 *
 * ═══════ ПРИЗНАК РАЗМЕРА — ИЗМЕРЯЕМЫЙ, А НЕ УГАДАННЫЙ ══════════════════════════════════════
 *
 * ЧЕГО ЗДЕСЬ НЕТ И НИКОГДА НЕ БУДЕТ: поиска слов по описанию. Соблазн очевиден — «если в
 * тексте сказано „живой прогон“, дай побольше», — и он же делает потолок управляемым чужой
 * формулировкой: работа получала бы запас за фразу, а не за объём, а тот, кто фразу не
 * написал, платил бы за чужой стиль. Читаются только СТРУКТУРНЫЕ поля задачи, те, что очередь
 * уже проверяет на входе и хранит в строке:
 *
 *   1. `storyPoints` — оценка по Фибоначчи, которую `validateTask` не пропускает в другом
 *      виде, а для работы из бэклога ТРЕБУЕТ. Самый честный признак: его поставил человек,
 *      знавший работу, и поставил числом.
 *   2. Сколько обещано — `acceptanceItems(...).length`, число признаков успеха. Очередь
 *      ограничивает его двенадцатью, так что это ограниченное, считаемое число.
 *   3. Сколько обещано БУКВАМИ — длина того же обещания. Это не поиск по описанию, а мера:
 *      обещание на две тысячи знаков закрывается не тем же числом ходов, что «зелёные тесты».
 *      Именно этот признак единственный отличает роестровую работу, которая и сгорала: у неё
 *      нет оценки, у неё один пункт приёмки — и он на страницу.
 *
 * ПОБЕЖДАЕТ СТАРШИЙ, А НЕ СУММА. Работа, крупная ХОТЬ ПО ОДНОМУ честному признаку, крупная:
 * требовать согласия всех трёх значило бы, что большое обещание без оценки читается как
 * мелочь — ровно тот случай, который сгорел дважды.
 *
 * ═══════ ВТОРАЯ ПОПЫТКА С ТЕМ ЖЕ ПОТОЛКОМ — ОПЛАЧЕННЫЙ ПОВТОР ИЗВЕСТНОГО ИСХОДА ════════════
 *
 * Если попытка уже упёрлась в потолок N, то следующая попытка ТОЙ ЖЕ работы с потолком N
 * упрётся в ту же стену на том же шаге. Поэтому `taskTurnCap` смотрит на потолки, которые
 * УЖЕ сгорели (их несёт реестр попыток), и выдаёт строго больший — либо не выдаёт ничего.
 * Третьего не дано: `null` означает «эта работа не помещается ни в какой потолок, который мы
 * готовы оплатить», и вызывающий обязан остановиться и позвать человека, а не запускать
 * процесс с числом, которое уже проиграло.
 *
 * ПОТОЛОК ПОТОЛКА берётся от той же базы (`TURN_CAP_MAX_MULTIPLIER`), потому что база — это
 * то единственное число, которое человек в этом продукте правит руками. Абсолютная константа
 * рядом с настраиваемой базой означала бы, что у поднятой настройки есть невидимый предел,
 * о котором знает только этот файл.
 *
 * ═══════ И КУДА ХОДЫ УШЛИ ══════════════════════════════════════════════════════════════════
 *
 * Число сожжённых ходов само по себе не говорит, поднимать потолок или дробить работу. Сто
 * ходов правок — это работа, которой не хватило места; сто ходов запусков оболочки — это
 * доказательство, которое не сходится, и его надо резать отдельной задачей. Поэтому род хода
 * читается по ИМЕНИ инструмента в кадре потока (`turnKindOf`), а разбивка едет на карточку.
 *
 * ЧИСТЫЙ МОДУЛЬ. Ни файловой системы, ни часов, ни состояния между вызовами. Единственный
 * импорт — `acceptanceItems` из словаря очереди: это объявленная единственная читающая тропа
 * к полю `acceptance` на весь продукт, и второй её экземпляр разошёлся бы с первым молча.
 */

import { acceptanceItems } from '../queue/adapter.mjs'

// ── РАЗМЕР РАБОТЫ ──────────────────────────────────────────────────────────────────────────

/** Три размера, от которых считается потолок. Замкнутый словарь: четвёртый — правка здесь. */
export const TURN_SIZES = Object.freeze(['small', 'standard', 'large'])

/**
 * Во сколько раз потолок больше базы для каждого размера.
 *
 * `small` — РОВНО база, ни на ход больше: настройка человека обязана остаться тем, что он
 * поставил, для работы того масштаба, на который он её ставил. Умножать здесь значило бы
 * тихо переписать его число.
 */
export const TURN_SIZE_MULTIPLIER = Object.freeze({ small: 1, standard: 2, large: 3 })

/**
 * ГРАНИЦЫ ПРИЗНАКОВ. Выписаны, а не выведены: каждая — решение про чужую подписку, и менять
 * её надо руками, в одном месте, где рядом написано, почему она такая.
 *
 * `storyPoints` — по ряду Фибоначчи, который очередь и так требует: 1–2 это мелочь, 3–5
 * обычная работа, 8 и 13 — то, что человек сам назвал крупным.
 *
 * `criteria` — сколько отдельных обещаний надо закрыть. Одно — правка; четыре и больше —
 * список дел, у каждого из которых своя проверка.
 *
 * `promiseChars` — длина обещания. Четыреста знаков это абзац, тысяча двести — страница
 * условий, которую нельзя закрыть, не сходив в код и обратно несколько раз.
 */
export const TURN_SIZE_THRESHOLDS = Object.freeze({
  storyPoints: Object.freeze({ standard: 3, large: 8 }),
  criteria: Object.freeze({ standard: 2, large: 4 }),
  promiseChars: Object.freeze({ standard: 400, large: 1200 }),
})

/** Старший из двух размеров — порядок берётся из `TURN_SIZES`, а не из сравнения строк. */
function louder(a, b) {
  return TURN_SIZES.indexOf(a) >= TURN_SIZES.indexOf(b) ? a : b
}

/** Размер по одному признаку и его двум границам. Отсутствующее число не голосует вовсе. */
function tierOf(value, { standard, large }) {
  if (!Number.isFinite(value)) return 'small'
  if (value >= large) return 'large'
  if (value >= standard) return 'standard'
  return 'small'
}

/**
 * workSizeOf(task) → `{size, signals}` — насколько крупна ОБЪЯВЛЕННАЯ работа.
 *
 * `signals` возвращается рядом с ответом нарочно: карточка и журнал должны показывать, ПО
 * ЧЕМУ размер получился таким, иначе поднятый потолок читается как произвол демона.
 *
 * Тотальна: задача без единого признака (без оценки, без обещания) — `small`. Это правильное
 * направление ошибки для потолка: неизвестная работа получает ровно то число, которое человек
 * поставил сам, а не запас, который никто не просил.
 *
 * @param {object|null|undefined} task
 * @returns {{size:string, signals:{storyPoints:number|null, criteria:number, promiseChars:number}}}
 */
export function workSizeOf(task) {
  const t = task && typeof task === 'object' ? task : {}
  const items = acceptanceItems(t.acceptance)
  const storyPoints = typeof t.storyPoints === 'number' && Number.isFinite(t.storyPoints) ? t.storyPoints : null
  const criteria = items.length
  const promiseChars = items.reduce((sum, s) => sum + s.length, 0)

  const size = [
    tierOf(storyPoints ?? Number.NaN, TURN_SIZE_THRESHOLDS.storyPoints),
    tierOf(criteria, TURN_SIZE_THRESHOLDS.criteria),
    tierOf(promiseChars, TURN_SIZE_THRESHOLDS.promiseChars),
  ].reduce(louder, 'small')

  return { size, signals: { storyPoints, criteria, promiseChars } }
}

// ── ПОТОЛОК ────────────────────────────────────────────────────────────────────────────────

/**
 * Во сколько раз следующая попытка обязана превзойти потолок, который уже сгорел. Ровно два:
 * прибавка в десяток ходов повторила бы ту же стену на десять шагов дальше и стоила бы такой
 * же оплаченной попытки, а прибавка втрое сжигала бы окно подписки за один заход.
 */
export const TURN_CAP_ESCALATION = 2

/**
 * ПРЕДЕЛ ВСЕХ ПОДЪЁМОВ, в базах. Шесть — это работа, которой дали вшестеро больше, чем человек
 * счёл нормой, и она всё равно не поместилась. Дальше поднимать нечего: такая работа не
 * велика, она неверно поставлена, и следующий ход принадлежит человеку — разрезать её.
 */
export const TURN_CAP_MAX_MULTIPLIER = 6

/**
 * taskTurnCap({base, task, burnedCaps}) → `{cap, size, signals, escalatedFrom, ceiling}`.
 *
 * `cap` — число, которое поедет на командную строку, или `null`, когда честного числа больше
 * нет: всё, что не меньше предела, уже сгорело. `null` — это НЕ ошибка и не ноль; это ответ
 * «запускать нельзя», и вызывающий обязан отдать работу человеку.
 *
 * ПОЧЕМУ СГОРЕВШИЕ ПОТОЛКИ ПРИХОДЯТ СПИСКОМ, А НЕ ЧИСЛОМ. Их источник — реестр попыток, где
 * лежит одна строка на попытку; какая из них была самой щедрой, решает эта функция, а не
 * читатель реестра. Читатель, который сам выбирал бы максимум, был бы вторым местом, где
 * живёт то же правило.
 *
 * ЧИСТАЯ. Ни реестра, ни настроек, ни часов — только три входа.
 *
 * @param {{base:number, task?:object, burnedCaps?:number[]}} o
 * @returns {{cap:number|null, size:string, signals:object, escalatedFrom:number|null, ceiling:number}}
 */
export function taskTurnCap({ base, task, burnedCaps } = {}) {
  const b = Number.isSafeInteger(base) && base > 0 ? base : 0
  const { size, signals } = workSizeOf(task)
  const ceiling = b * TURN_CAP_MAX_MULTIPLIER
  const sized = Math.min(ceiling, b * TURN_SIZE_MULTIPLIER[size])

  const burned = (Array.isArray(burnedCaps) ? burnedCaps : [])
    .map((n) => Number(n))
    .filter((n) => Number.isSafeInteger(n) && n > 0)
  const worst = burned.length ? Math.max(...burned) : null

  // Ничего ещё не горело — потолок ровно по размеру.
  if (worst === null) return { cap: sized, size, signals, escalatedFrom: null, ceiling }

  const raised = Math.min(ceiling, Math.max(sized, worst * TURN_CAP_ESCALATION))
  // СТРОГО БОЛЬШЕ, ИНАЧЕ НИЧЕГО. Равный потолок — это оплаченный повтор известного исхода, и
  // разница между «поднять» и «повторить» здесь ровно в этом знаке.
  if (raised <= worst) return { cap: null, size, signals, escalatedFrom: worst, ceiling }
  return { cap: raised, size, signals, escalatedFrom: worst, ceiling }
}

/**
 * burnedTurnCapsOf(rows) → потолки тех попыток, что кончились упором в потолок.
 *
 * Читает СТРОКИ РЕЕСТРА и ничего больше. Берутся только попытки с причиной `turns_exhausted`:
 * попытка, оборванная провайдером или сторожем, ни во что не упиралась, и поднимать после неё
 * потолок значило бы платить за чужую аварию щедростью, которой работа не просила.
 *
 * @param {object[]|null|undefined} rows — строки реестра попыток этой задачи
 * @returns {number[]}
 */
export function burnedTurnCapsOf(rows) {
  if (!Array.isArray(rows)) return []
  const out = []
  for (const r of rows) {
    if (!r || typeof r !== 'object') continue
    if (r.failureReason !== 'turns_exhausted') continue
    const n = Number(r.turnCap)
    if (Number.isSafeInteger(n) && n > 0) out.push(n)
  }
  return out
}

// ── НА ЧТО УШЛИ ХОДЫ ───────────────────────────────────────────────────────────────────────

/**
 * РОД ХОДА — ЧЕТЫРЕ СЛОВА, И КАЖДОЕ ЧИНИТСЯ ПО-РАЗНОМУ.
 *
 *   edits — правки файлов: работа, которой не хватило места. Лечится потолком.
 *   runs  — запуски оболочки: доказательство, которое не сходится. Лечится отдельной задачей.
 *   reads — чтение и поиск: работник искал, а не делал. Лечится точнее поставленной задачей.
 *   other — всё прочее, включая ходы без единого инструмента (размышление, ответ).
 *
 * СОПОСТАВЛЯЮТСЯ ИМЕНА ИНСТРУМЕНТОВ, а не тексты команд: имя приходит в кадре потока полем,
 * и разбор команды здесь был бы догадкой о том, что она делает.
 */
export const TURN_KINDS = Object.freeze(['edits', 'runs', 'reads', 'other'])

/** Имя инструмента → род хода. Неизвестное имя — `other`: незнакомое не притворяется знакомым. */
export const TURN_KIND_TOOLS = Object.freeze({
  Edit: 'edits',
  MultiEdit: 'edits',
  Write: 'edits',
  NotebookEdit: 'edits',
  Bash: 'runs',
  BashOutput: 'runs',
  KillShell: 'runs',
  Read: 'reads',
  Grep: 'reads',
  Glob: 'reads',
})

/**
 * turnKindOf(toolName) → род хода. Тотальна: что угодно незнакомое — `other`.
 * @param {string} toolName
 * @returns {string}
 */
export function turnKindOf(toolName) {
  return (typeof toolName === 'string' && TURN_KIND_TOOLS[toolName]) || 'other'
}

/**
 * emptyTurnKinds() → счётчик со всеми четырьмя словами и нулями.
 *
 * ВСЕ ЧЕТЫРЕ ВСЕГДА ПРИСУТСТВУЮТ. Отсутствующий ключ на карточке читается как «неизвестно», а
 * ноль — как «не было»; это разные утверждения, и второе здесь всегда правда.
 */
export function emptyTurnKinds() {
  return { edits: 0, runs: 0, reads: 0, other: 0 }
}
