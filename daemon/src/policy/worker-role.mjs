/**
 * worker-role.mjs — КТО ЭТОТ РАБОТНИК ПО РОЛИ, И КОГО ЗАДАЧА ПРОСИТ.
 *
 * ЧТО СЛУЧИЛОСЬ. Владелец открыл доску и увидел, что над задачей, не связанной с починкой
 * кода, работает `sma-code-fixer`. Разбор показал, что это не сбой, а УСТРОЙСТВО: маршрутизатор
 * брал `candidates[0]` — первого свободного В ПОРЯДКЕ СТРОК КОНФИГА, — и роль не смотрел вовсе.
 * Значит инлайн-задачи разбирали первые шесть по алфавиту: исследователь, аналитик допущений,
 * ревьюер. Код продукта писали те, кто для этого не заведён, причём часть из них стояла на
 * младшей модели. Рукой это лечили выключением тридцати восьми строк из очереди — лекарство,
 * которое держится ровно до следующей правки конфига.
 *
 * РАЗДЕЛЕНИЕ, КОТОРОЕ ЭТОТ МОДУЛЬ ЗАКРЕПЛЯЕТ (решение владельца 28.08):
 *
 *   • РАБОТНИКИ — исполнители. Они разбирают инлайн-задачи и куски сборок: пишут код и
 *     исправляют баги. Это и есть пул очереди.
 *   • АГЕНТЫ — рой, который включается ВНУТРИ фазы. Их поднимает не демон, а сама работа
 *     (`Agent(subagent_type=…)` внутри процесса CLI), и берутся они из описаний в
 *     `.claude/agents/`. Очередь их не раздаёт и раздавать не должна.
 *
 * ПОЭТОМУ У ЗАДАЧИ ЕСТЬ РОЛЬ, И ПО УМОЛЧАНИЮ ОНА ОДНА. Инлайн-задача, о роли которой никто
 * ничего не сказал, едет ИСПОЛНИТЕЛЮ — не «первому свободному», а именно исполнителю. Редкий
 * случай, когда владельцу нужен исследователь на инлайн-задаче, становится ЯВНЫМ выбором при
 * постановке (`task.role`), а не побочным эффектом алфавита. Это ровно та разница, которой не
 * было: раньше выбор специалиста нельзя было ни сделать, ни отменить — он просто случался.
 *
 * ОТКУДА БЕРЁТСЯ РОЛЬ РАБОТНИКА — ДВА ИСТОЧНИКА, И НИ ОДНОГО УГАДАННОГО:
 *   1. поле `role` в профиле — то, что человек написал руками; главнее всего;
 *   2. `roleFile` — путь к описанию агента (`.claude/agents/<id>.md`), которым этот работник
 *      уже поднимается. Имя файла И ЕСТЬ имя роли: тем же именем его ищет `findAgentFile`,
 *      тем же именем его зовёт рой. Второй словарь ролей рядом с этим именем разъехался бы
 *      с ним при первом же переименовании файла.
 *   3. НИЧЕГО БОЛЬШЕ. Работник без описания — обычный исполнитель, и это не догадка, а то,
 *      чем такая строка всегда была: `max-1`, `pro-1`, `creator` из поставочного конфига
 *      никакого описания не носят и пишут код.
 *
 * ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ — И ЭТО СКАЗАНО ВСЛУХ. Он не ходит в файловую систему и не
 * проверяет, что описание с таким именем вообще существует: он чистый, его зовёт чистый
 * маршрутизатор, и проверка наличия файла сделала бы решение о маршруте зависящим от диска.
 * Отсюда одна честная дыра: профиль, чьё описание лежит в хранилище МАШИНЫ, поля `roleFile` не
 * несёт (оно репо-относительное) и прочитался бы здесь как исполнитель. Дыра закрыта у
 * ИСТОЧНИКА — `profileFromDefinition` пишет такому профилю явное поле `role`, — а не здесь
 * догадкой по идентификатору: идентификатор работника не обязан быть именем агента, и
 * `max-1` тому пример.
 *
 * ИМЯ РОЛИ НОРМАЛИЗУЕТСЯ ОДНОЙ ФУНКЦИЕЙ, И ОБЕ СТОРОНЫ ЗОВУТ ЕЁ. Владелец видит агентов под
 * их полными именами (`sma-ai-researcher`), а поставочный конфиг носит работников без всякого
 * префикса. Пока нормализация одна, «sma-executor» и «executor» — одна и та же роль, и вопрос
 * «как это писать» не существует. Две нормализации на двух концах сравнения — это способ, каким
 * совпадение однажды перестаёт быть совпадением.
 *
 * Без импортов, без часов, без process.env — чистый лист словаря, как policy/orchestrator.mjs.
 */

/**
 * РОЛЬ ПО УМОЛЧАНИЮ — ИСПОЛНИТЕЛЬ. Тот, кто пишет код и исправляет баги; тот, кем работник
 * является, пока про него не сказано иного. Это же значение получает задача, которая роли не
 * назвала, — и именно поэтому «специалист на инлайн-задаче» стал выбором, а не случайностью.
 */
export const EXECUTOR_ROLE = 'executor'

/**
 * Префикс, которым названы поставочные описания агентов. Снимается при нормализации, чтобы
 * `sma-executor` (как роль названа в `.claude/agents/`) и `executor` (как она названа в
 * поставочном конфиге) были ОДНОЙ ролью, а не двумя, которые никогда не совпадут.
 */
const STOCK_PREFIX = 'sma-'

/**
 * normalizeRole(value) → каноническое имя роли, или `null`, если имени нет вовсе.
 *
 * ОДНА НОРМАЛИЗАЦИЯ НА ОБЕ СТОРОНЫ СРАВНЕНИЯ (см. шапку). Регистр снимается, поставочный
 * префикс снимается, пробелы по краям снимаются. Всё, что не строка, — не имя.
 *
 * @param {unknown} value
 * @returns {string|null}
 */
export function normalizeRole(value) {
  if (typeof value !== 'string') return null
  const trimmed = value.trim().toLowerCase()
  if (trimmed === '') return null
  return trimmed.startsWith(STOCK_PREFIX) ? trimmed.slice(STOCK_PREFIX.length) || null : trimmed
}

/**
 * roleFromDefinitionPath(path) → имя роли, выведенное из пути к описанию агента.
 *
 * `.claude/agents/sma-ai-researcher.md` → `ai-researcher`. Разделитель считается обоим —
 * конфиг пишут и на Windows, и рядом с ним лежит тот же путь через косую черту.
 *
 * @param {unknown} path
 * @returns {string|null}
 */
export function roleFromDefinitionPath(path) {
  if (typeof path !== 'string' || path.trim() === '') return null
  const tail = path.split(/[\\/]/).pop() ?? ''
  return normalizeRole(tail.replace(/\.md$/i, ''))
}

/**
 * roleOf(profile) → роль, которую этот работник держит.
 *
 * Порядок источников — тот, что назван в шапке: рука человека, потом описание, которым он и
 * так поднимается, потом — исполнитель. Всё, что не объект, ролью не обладает и читается как
 * исполнитель: пул, в котором завелась не-строка, не должен ронять маршрут.
 *
 * @param {unknown} profile
 * @returns {string}
 */
export function roleOf(profile) {
  if (!profile || typeof profile !== 'object') return EXECUTOR_ROLE
  return normalizeRole(profile.role) ?? roleFromDefinitionPath(profile.roleFile) ?? EXECUTOR_ROLE
}

/**
 * roleWanted(task) → роль, которую эта задача просит.
 *
 * Названа явно — берётся названная. Не названа — ИСПОЛНИТЕЛЬ, и это главное правило всего
 * модуля: задача без слова о роли не «достаётся кому попало», она достаётся тому, кто для неё
 * заведён.
 *
 * @param {unknown} task
 * @returns {string}
 */
export function roleWanted(task) {
  if (!task || typeof task !== 'object') return EXECUTOR_ROLE
  return normalizeRole(task.role) ?? EXECUTOR_ROLE
}

/**
 * roleIsNamed(task) → сказал ли человек о роли ВСЛУХ.
 *
 * Отдельно от `roleWanted` потому, что это РАЗНЫЕ вопросы, и различие между ними стоит денег.
 * «Кого просит эта работа» отвечается всегда — без слова о роли это исполнитель. «Назвал ли
 * кто-то эту роль» отвечается только строкой на задаче, и от него зависит, чем машина отвечает
 * на выключенного специалиста: работу, названную поимённо, тихо подменить нельзя (маршрут
 * ответит `role_unavailable`), а безымянную — можно и нужно вести так, как она велась всегда.
 *
 * @param {unknown} task
 * @returns {boolean}
 */
export function roleIsNamed(task) {
  if (!task || typeof task !== 'object') return false
  return normalizeRole(task.role) !== null
}

/**
 * holdsRole(profile, role) → держит ли этот работник ровно эту роль.
 *
 * @param {unknown} profile
 * @param {string} role
 * @returns {boolean}
 */
export function holdsRole(profile, role) {
  return roleOf(profile) === (normalizeRole(role) ?? EXECUTOR_ROLE)
}

/**
 * isExecutor(profile) → исполнитель ли это, то есть работник в прямом смысле слова.
 *
 * Экраны спрашивают именно это: «Работники» рисуют исполнителей, всё остальное — специалисты,
 * которых зовут поимённо. Отдельное имя, а не `roleOf(w) === EXECUTOR_ROLE` по месту вызова:
 * сравнение, повторённое в трёх экранах, — это три места, где однажды сравнят по-разному.
 *
 * @param {unknown} profile
 * @returns {boolean}
 */
export function isExecutor(profile) {
  return roleOf(profile) === EXECUTOR_ROLE
}
