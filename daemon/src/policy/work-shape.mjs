/** Пути, добавленные ЭТОЙ работой. `A` — новый файл, `C` — копия: обоих в базе не было. */
function addedPaths(entries) {
  const out = []
  if (!Array.isArray(entries)) return out
  for (const e of entries) {
    if (!e || typeof e !== 'object') continue
    const status = String(e.status ?? '')
    const path = normalize(e.path)
    // Переименование (`R`) сюда НЕ попадает намеренно: файл существовал до работы под другим
    // именем, и тест о нём говорит о продукте, а не о себе.
    if (!path || (status[0] !== 'A' && status[0] !== 'C')) continue
    if (!out.includes(path)) out.push(path)
  }
  return out
}

/** Один вид пути на всю проверку: прямые слэши, без ведущего `./`, без кавычек. */
function normalize(value) {
  const s = typeof value === 'string' ? value.trim() : ''
  return s.replace(/\\/g, '/').replace(/^\.\//, '')
}

/** Тестовый ли это файл — по тем двум признакам, которыми их именует само дерево. */
function isTestFile(path) {
  return path.includes('/__tests__/') || path.startsWith('__tests__/') || /\.(?:test|spec)\.[A-Za-z0-9]+$/.test(path)
}

/**
 * Строки diff'а, которые ГОВОРЯТ о содержимом теста: файл после работы лежит на месте и его
 * можно прочесть. `A`/`C` — новый файл, `M`/`T` — правленый.
 *
 * `D` И `R` НЕ ГОВОРЯТ, и это не мелочь. Удалённого файла в копии нет вовсе: чтение бросает, а
 * распознаватель, принимающий нечитаемое за «правленый тест продукта», разоружался бы от ЛЮБОГО
 * удаления теста — заметка о себе плюс одно удаление, и работа проходит гейт. Переименование
 * говорит о том, что файл ПЕРЕЕХАЛ, а не о том, что работа заново проверила поведение: считать
 * переезд голосом значит очищать работу за механическую правку.
 */
const TESTS_THAT_SPEAK = Object.freeze(['A', 'C', 'M', 'T'])

/**
 * ВСЕ тесты работы, а не только новые: `{path, added}` по каждому тестовому файлу в diff.
 * Правленый тест продукта — такой же голос работы, как и добавленный, и судить работу
 * пофайлово значит не услышать его вовсе.
 */
function changedTests(entries, added) {
  const out = []
  if (!Array.isArray(entries)) return out
  for (const e of entries) {
    if (!e || typeof e !== 'object') continue
    const status = String(e.status ?? '')
    const path = normalize(e.path)
    if (!path || !isTestFile(path)) continue
    if (!TESTS_THAT_SPEAK.includes(status[0])) continue
    if (out.some((t) => t.path === path)) continue
    out.push({ path, added: added.includes(path) })
  }
  return out
}

/**
 * НОРМАЛИЗОВАННЫЙ ИСХОДНИК: то, что в файле СКАЗАНО, без того, КАК оно набрано. Один проход,
 * без разбора грамматики: пробелы и переводы строк схлопнуты до одного разделителя, комментарии
 * обеих форм выброшены, а строковые литералы взяты целиком и дословно — пробел ВНУТРИ строки
 * продукту виден, и стирать его значило бы объявить косметикой настоящую правку.
 *
 * Токены склеиваются через пробел, а не встык: иначе `a b` и `ab` дали бы одну строку, и
 * пропавшая граница между словами прошла бы за «ничего не изменилось».
 */
function normalizedSource(text) {
  const out = []
  let buf = ''
  const flush = () => {
    if (buf) out.push(buf)
    buf = ''
  }
  for (let i = 0; i < text.length; ) {
    const c = text[i]
    const next = text[i + 1]
    if (c === '/' && next === '/') {
      flush()
      while (i < text.length && text[i] !== '\n') i += 1
      continue
    }
    if (c === '/' && next === '*') {
      flush()
      i += 2
      while (i < text.length && !(text[i] === '*' && text[i + 1] === '/')) i += 1
      i += 2
      continue
    }
    if (c === '"' || c === "'" || c === '`') {
      flush()
      let lit = c
      i += 1
      while (i < text.length) {
        const ch = text[i]
        if (ch === '\\') {
          lit += ch + (text[i + 1] ?? '')
          i += 2
          continue
        }
        lit += ch
        i += 1
        if (ch === c) break
      }
      out.push(lit)
      continue
    }
    if (/\s/.test(c)) {
      flush()
      i += 1
      continue
    }
    buf += c
    i += 1
  }
  flush()
  return out.join(' ')
}

/**
 * СОДЕРЖАТЕЛЬНА ЛИ ПРАВКА ЭТОГО ТЕСТА — вопрос, без которого голос правленого теста стоил
 * одного пробела. Замерено на ревью 03.09.2026: любая работа, говорящая только о себе, проходила
 * гейт, если в довесок сдвинуть отступ в ЧУЖОМ существующем тесте, — правка была помечена `M`,
 * тест держался за продукт, и сторож умолкал. Правка, которой продукт не видит (пробелы,
 * переводы строк, комментарий), теперь голосом не считается.
 *
 * FAIL-OPEN: читателя базы нет, файл в базе не прочёлся или пуст — правка считается
 * содержательной. Обвинить работу в косметике на основании неспрошенного git было бы хуже той
 * дыры, которую этот вопрос закрывает. Никогда не бросает.
 */
function saysSomethingNew(path, text, readBase) {
  if (typeof readBase !== 'function') return true
  let before
  try {
    before = readBase(path)
  } catch {
    before = null
  }
  if (typeof before !== 'string' || !before) return true
  return normalizedSource(before) !== normalizedSource(text)
}

/**
 * Спецификаторы модулей, которые файл ПОДКЛЮЧАЕТ. Три формы, которыми их пишут:
 * `from '...'`, `require('...')` и голый `import '...'` (он же динамический `import('...')`).
 */
const IMPORT_RE = /(?:\bfrom\s*|\brequire\s*\(\s*|\bimport\s*\(?\s*)(['"])([^'"]+)\1/g

/** Строковые литералы файла — сырьё для вопроса «о каких файлах этот тест говорит». */
const LITERAL_RE = /(['"`])((?:[^'"`\\\r\n]|\\.)*)\1/g

/**
 * Похоже ли на путь в дереве. Намеренно узко: имя с расширением, возможно с каталогами.
 * `node:fs` отсекается двоеточием, `vitest` — отсутствием расширения, `utf8` — им же.
 */
const PATHISH_RE = /^(?:[\w.@~-]+\/)*[\w.@~-]+\.[A-Za-z0-9]{1,8}$/

/** Ссылается ли литерал на этот добавленный путь — с любой стороны, целиком или хвостом. */
function refersTo(literal, path) {
  return literal === path || literal.endsWith(`/${path}`) || path.endsWith(`/${literal}`)
}

/**
 * ЗАПУСК ФАЙЛА ПРОЦЕССОМ — второй способ подключить продукт, и до 02.09.2026 распознаватель
 * его не видел. Тест, который берёт настоящий скрипт дерева, запускает его дочерним процессом
 * с подставным окружением и читает stdout/stderr/файлы, — провод-тест высшей пробы: он краснеет
 * от любой поломки запускаемого. Ни одного `import` при этом в нём может не быть.
 */
const RUN_CALL_RE = /\b(?:spawnSync|spawn|execFileSync|execFile|execSync|exec|fork)\s*\(/

/** Что вообще можно запустить процессом: скрипт дерева, а не README и не снимок. */
const RUNNABLE_EXT_RE = /\.(?:mjs|cjs|js|jsx|ts|tsx|sh|bash|py)$/

/**
 * Каталоги, в которых лежит ЗАПУСКАЕМЫЙ код продукта. Якорь, без которого собранный из кусков
 * путь был бы догадкой: искать имя файла по всему дереву значит рано или поздно найти чужое —
 * зависимость, личный слой, снимок задачи, — и объявить связью с продуктом то, что ею не было.
 */
const PRODUCT_DIRS = Object.freeze(['bin', 'daemon', 'scripts', 'sma-core', 'supervisor', 'tools'])

/** Лежит ли путь внутри одного из каталогов запускаемого кода. Файл в корне — не лежит. */
function underProductDir(path) {
  const slash = path.indexOf('/')
  return slash > 0 && PRODUCT_DIRS.includes(path.slice(0, slash))
}

/** Кусок пути, каким его пишут в `join(...)`: имя каталога, а не `..`, не `node:fs` и не пакет. */
const SEGMENT_RE = /^[A-Za-z0-9_@][\w@.-]*$/

/** Сколько кусков перед именем файла собирать: `join(ROOT, 'a', 'b', 'c', 'file.mjs')` и хватит. */
const MAX_JOINED_SEGMENTS = 4

/** Строковые литералы файла по порядку — сырьё и для связей, и для слов отказа. */
function literalsOf(text) {
  const out = []
  LITERAL_RE.lastIndex = 0
  for (let m = LITERAL_RE.exec(text); m; m = LITERAL_RE.exec(text)) out.push(normalize(m[2]))
  return out
}

/**
 * runTarget(literals, i, exists) → путь запускаемого файла продукта или null.
 *
 * ПОЧЕМУ ЭТОГО НЕ ДЕЛАЕТ `locateInTree`. Тест из `daemon/__tests__`, запускающий
 * `join(ROOT, 'scripts', 'sma', 'ui-drive.mjs')`, оставляет в исходнике голое имя файла и
 * ОТДЕЛЬНЫЕ куски пути. Мерить это имя от каталога теста и его предков — значит искать
 * `daemon/ui-drive.mjs`, которого нет: цель лежит в другой ветке дерева. Поэтому имя собирается
 * обратно из соседних литералов слева и примеряется целиком.
 *
 * СБОРКА ПОЗВОЛЕНА ТОЛЬКО ЗАПУСКУ и только в каталоги продукта: собранный путь — догадка, и
 * подтверждает её ровно одно — файл с таким путём в копии ЕСТЬ и лежит там, где живёт
 * запускаемый код. Никогда не бросает.
 */
function runTarget(literals, i, exists) {
  const lit = literals[i]
  const candidates = [lit]
  const segments = []
  for (let j = i - 1; j >= 0 && segments.length < MAX_JOINED_SEGMENTS; j--) {
    const seg = literals[j]
    if (!seg || !SEGMENT_RE.test(seg)) break // `..`, `node:path`, конец цепочки кусков
    segments.unshift(seg)
    candidates.push(`${segments.join('/')}/${lit}`)
  }
  for (const candidate of candidates) {
    if (!underProductDir(candidate)) continue
    try {
      if (exists(candidate) === true) return candidate
    } catch {
      /* нечитаемое дерево не обвиняет */
    }
  }
  return null
}

/**
 * Где литерал лежит НА САМОМ ДЕЛЕ: сам по себе или рядом с тестом, который его назвал.
 *
 * Путь к запускаемому скрипту тест почти никогда не пишет одной строкой — он собирает его
 * `join(ROOT, 'scripts', 'sma', 'ui-drive.mjs')`, и в исходнике остаётся голое имя файла.
 * Мерить такое имя от корня копии значит не найти ничего и объявить работу самозамкнутой,
 * хотя она запускает соседний файл продукта. Поэтому имя примеряется к каталогу самого теста
 * и всем его предкам — ровно там, куда тест и целится. Возвращает НАЙДЕННЫЙ путь (он идёт в
 * слова отказа) или null. Никогда не бросает.
 */
function locateInTree(literal, from, exists) {
  const tries = [literal]
  let dir = from.includes('/') ? from.slice(0, from.lastIndexOf('/')) : ''
  while (dir) {
    tries.push(`${dir}/${literal}`)
    dir = dir.includes('/') ? dir.slice(0, dir.lastIndexOf('/')) : ''
  }
  for (const candidate of tries) {
    try {
      if (exists(candidate) === true) return candidate
    } catch {
      /* нечитаемое дерево не обвиняет */
    }
  }
  return null
}

/**
 * linksProduct(text, from, added, exists) → держится ли этот тест за продукт. Три способа, и
 * любого одного довольно:
 *   1. ПОДКЛЮЧАЕТ модуль дерева (относительный, абсолютный или `#`-спецификатор);
 *   2. ЗАПУСКАЕТ файл дерева процессом: в тексте есть вызов запуска, литерал похож на
 *      запускаемый файл, и собранный из соседних кусков путь ЕСТЬ в копии и лежит в каталогах
 *      продукта. Только этому способу позволена сборка пути из кусков — тем он и решает: без
 *      вызова запуска, без запускаемого расширения или мимо каталогов продукта тот же самый
 *      текст остаётся разговором о себе;
 *   3. НАЗЫВАЕТ путь, который в копии есть — сам по себе или рядом с назвавшим его тестом.
 * Ни один из трёх не может быть удовлетворён файлом, добавленным этой же работой.
 */
function linksProduct(text, from, added, exists) {
  IMPORT_RE.lastIndex = 0
  for (let m = IMPORT_RE.exec(text); m; m = IMPORT_RE.exec(text)) {
    const spec = String(m[2] || '')
    if (spec.startsWith('.') || spec.startsWith('/') || spec.startsWith('#')) return true
  }

  const runs = RUN_CALL_RE.test(text)
  const literals = literalsOf(text)
  for (let i = 0; i < literals.length; i += 1) {
    const lit = literals[i]
    if (!lit || !PATHISH_RE.test(lit)) continue
    if (added.some((a) => refersTo(lit, a))) continue // свой же файл продуктом не считается
    if (runs && RUNNABLE_EXT_RE.test(lit) && runTarget(literals, i, exists)) return true
    if (locateInTree(lit, from, exists)) return true
  }
  return false
}

/** Пути, добавленные этой же работой, на которые тест ссылается. Сырьё для слов отказа. */
function selfReferences(text, added) {
  const out = []
  for (const lit of literalsOf(text)) {
    if (!lit || !PATHISH_RE.test(lit)) continue
    const own = added.find((a) => refersTo(lit, a))
    if (own && !out.includes(own)) out.push(own)
  }
  return out
}

/**
 * selfReferentialTests({entries, readFile, pathExists}) → {files, detail} | null
 *
 * ГОВОРИТ ЛИ РАБОТА О ПРОДУКТЕ ИЛИ ТОЛЬКО О СЕБЕ. Вопрос задаётся РАБОТЕ ЦЕЛИКОМ, а не
 * каждому новому файлу по отдельности: тесты одной попытки — один голос, и хватает одного
 * теста, держащегося за продукт, чтобы работа перестала быть разговором о самой себе.
 *
 * ТРИ СПОСОБА ДЕРЖАТЬСЯ ЗА ПРОДУКТ, и любого одного довольно (`linksProduct`):
 *   1. ПОДКЛЮЧАЕТ модуль дерева — обычная работа: новый модуль со своим тестом импортирует то,
 *      что проверяет;
 *   2. ЗАПУСКАЕТ файл дерева процессом и читает, что тот напечатал и написал. Замерено
 *      02.09.2026: тест запускал настоящий скрипт продукта через `spawnSync` с подставным
 *      падающим драйвером и читал его stdout — провод-тест высшей пробы, — а распознаватель
 *      смотрел на одни `import`ы и отклонил готовую зелёную работу. Запуск и решает, где искать
 *      цель: путь, собранный из кусков `join(...)`, засчитывается ТОЛЬКО запуску и только если
 *      он есть в копии и лежит в каталогах продукта (`runTarget`);
 *   3. НАЗЫВАЕТ путь, который в копии есть и этой работой не добавлен: такой файл был до
 *      работы, и сломать его можно чем-то, кроме самого теста.
 *
 * КАКИЕ ТЕСТЫ СПРАШИВАЮТСЯ: тестовые файлы diff'а, которые после работы ЛЕЖАТ в копии —
 * добавленные и правленые (`changedTests`). Правленый тест продукта — тоже голос работы: правя
 * существующий тест, работа говорит о том, что было до неё.
 *
 * НО ТОЛЬКО ЕСЛИ ПРАВКА СОДЕРЖАТЕЛЬНА, и это цена того, что вопрос задаётся работе целиком.
 * Замерено на ревью 03.09.2026: сдвинутый отступ в ЧУЖОМ существующем тесте — правка, которой
 * продукт не видит, — разоружал сторожа для самозамкнутой пары «заметка + тест о ней». Голосом
 * считается правка, меняющая нормализованный исходник (`saysSomethingNew`): не пробел, не перевод
 * строки и не комментарий. ДОБАВЛЕННОГО теста это не касается — новый файл целиком новый.
 *
 * САМОЗАМКНУТЫМ называется ДОБАВЛЕННЫЙ тест, который не держится за продукт ни одним из трёх
 * способов и при этом называет хотя бы один путь — и каждый названный им путь добавлен этой же
 * работой. Тест, не назвавший ни одного файла и ничего не подключивший, не судится вовсе:
 * обвинять по молчанию нечем.
 *
 * ЧТО СЧИТАЕТСЯ НАЗВАННЫМ ПУТЁМ, и здесь проходит вся граница честности: литерал, который
 * либо совпал с добавленным путём, либо РЕАЛЬНО СУЩЕСТВУЕТ в копии — сам по себе или рядом с
 * тестом, который его назвал (`locateInTree`). Строка вроде `'1.0'` формально похожа на имя
 * файла, но ничему на диске не соответствует — и она не считается ни за, ни против. Иначе
 * случайная версия в строке разоружала бы весь распознаватель.
 *
 * FAIL-OPEN, НО НЕ ЗА СЧЁТ МОЛЧАНИЯ. Нечитаемый файл пропускается — он не улика ни в одну
 * сторону: обвинение всё равно строится на ПРОЧИТАННОМ добавленном тесте, а нечитаемое ничего
 * не удостоверяет и потому никого не оправдывает. Обратное правило стоило бы сторожу жизни:
 * пока нечитаемый правленый тест снимал вопрос целиком, любое удаление теста — путь, которого
 * в копии нет, — разоружало распознаватель на всю работу. Отсутствие читателя даёт пустой
 * ответ. Никогда не бросает.
 *
 * @param {{entries?:Array<{status:string,path:string}>, readFile?:(p:string)=>string|null, readBase?:(p:string)=>string|null, pathExists?:(p:string)=>boolean}} o
 * @returns {{files:string[], detail:string}|null}
 */
export function selfReferentialTests({ entries, readFile, readBase, pathExists } = {}) {
  const added = addedPaths(entries)
  if (!added.length || typeof readFile !== 'function') return null
  const exists = typeof pathExists === 'function' ? pathExists : () => false

  const suspects = []
  for (const test of changedTests(entries, added)) {
    let text
    try {
      text = readFile(test.path)
    } catch {
      text = null
    }
    if (typeof text !== 'string' || !text) continue // нечитаемый файл — не улика и не оправдание

    if (linksProduct(text, test.path, added, exists)) {
      // Добавленный тест — голос сразу; правленый — только если его правку видит продукт.
      if (test.added || saysSomethingNew(test.path, text, readBase)) return null
      continue // один пробел в чужом тесте работу не оправдывает
    }
    if (!test.added) continue // правленый тест ни за что не держится — но и не улика против

    const selfRefs = selfReferences(text, added)
    if (selfRefs.length) suspects.push({ path: test.path, selfRefs })
  }

  if (!suspects.length) return null
  return {
    files: suspects.map((s) => s.path),
    detail:
      `${suspects
        .map(
          (s) =>
            `${s.path}: все названные им пути добавлены этой же работой (${s.selfRefs.join(', ')}), ` +
            `ни одного модуля продукта он не подключает и ни одного файла продукта не запускает`,
        )
        .join(' · ')} — покраснеть такой тест может лишь от самого себя. ` +
      `ВЫХОД: подключите проверяемое (import модуля продукта) ЛИБО запустите файл продукта процессом ` +
      `и проверьте его вывод; если предмета работы нет — закройте задачу словами и уликой, а не тестом`,
  }
}

/** Каталоги, которые в копию кладёт САМ демон: личный слой, состояние, ссылки, снимок задачи. */
const FURNISHED_TOP_LEVEL = Object.freeze(['.claude', '.sma', 'node_modules', '.git'])

/**
 * newTopLevelDirs({entries, baseTopLevel}) → string[] — каталоги ВЕРХНЕГО уровня, которых в
 * базе не было, а после работы они есть.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ВОПРОС, А НЕ ПОБОЧНЫЙ ЭФФЕКТ. Новый каталог верхнего уровня — это
 * заявление о том, из чего состоит продукт: он попадает в README, в упаковку, в чужие
 * относительные пути и в привычку всех следующих работников. Ни одна задача не выдаёт на него
 * мандата попутно, и в замеренном случае `notes/` завёлся именно так — чтобы было куда
 * положить файл, оправдывающий попытку.
 *
 * FAIL-OPEN: пустой или неизвестный список верхнего уровня базы даёт пустой ответ. Пока не
 * известно, чего в базе НЕ БЫЛО, обвинять нечем — молчание здесь не «всё хорошо», а «нечем
 * судить», и вызывающий говорит об этом вслух.
 *
 * @param {{entries?:Array<{status:string,path:string}>, baseTopLevel?:string[]}} o
 * @returns {string[]}
 */
export function newTopLevelDirs({ entries, baseTopLevel } = {}) {
  if (!Array.isArray(baseTopLevel) || !baseTopLevel.length) return []
  const known = baseTopLevel.map((n) => normalize(n).replace(/\/$/, '')).filter(Boolean)
  const out = []
  for (const path of addedPaths(entries)) {
    const slash = path.indexOf('/')
    if (slash <= 0) continue // файл в корне — это не новый каталог
    const top = path.slice(0, slash)
    if (known.includes(top) || FURNISHED_TOP_LEVEL.includes(top) || out.includes(top)) continue
    out.push(top)
  }
  return out.sort()
}
