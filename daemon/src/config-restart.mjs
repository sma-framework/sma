/**
 * config-restart.mjs — НАСТРОЙКИ, КОТОРЫЕ ПРИМЕНЯЮТСЯ ТОЛЬКО С НОВОГО ЗАПУСКА, и
 * расхождение между тем, что стоит в файле, и тем, по чему демон живёт прямо сейчас.
 *
 * ═══ ПОВОД: ДВА КЛАССА НАСТРОЕК, ОДИНАКОВЫХ НА ВИД ═══════════════════════════════
 *
 * Демон читает `config.json` РОВНО ОДИН РАЗ — на запуске (`loadConfig` вызывается из
 * `main.mjs` и больше ниоткуда). Дальше в процессе живёт КОПИЯ. Из этого следуют два
 * разных класса настроек, и человек их не различает, потому что выглядят они одинаково:
 *
 *   · те, у которых есть дверь в окне (тумблер конвейера, денежный стоп, реестры) —
 *     дверь двигает копию в памяти И файл, поэтому действуют они сразу;
 *   · те, которые правятся руками в файле — копия в памяти о правке не знает, и число
 *     на диске начинает означать «будет так ПОСЛЕ перезапуска», а не «так сейчас».
 *
 * Второй класс молчал о себе, и это молчание стоило двух неверных выводов подряд:
 *   28.08.2026 — владелец опустил потолок одновременных мест и увидел, что ничего не
 *     изменилось; настройка была записана, показана и не действовала;
 *   в ночь на 29.08 — потолок ходов подняли со 160 до 400, чтобы разорвать круг
 *     сгоравших работ, а через час в файле снова стояло 160: бегущий демон затёр правку
 *     своей устаревшей копией. Починка ЭТОЙ записи (запись по названным полям,
 *     `writeConfig({fields})`) к тому моменту уже была в стволе — но демон стартовал
 *     раньше неё и жил со старым кодом, и никто не сказал человеку, что в ЭТОМ процессе
 *     починки ещё нет.
 *
 * ═══ ЧТО ЗДЕСЬ ЕСТЬ, И ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ ══════════════════════════════════
 *
 * ЕСТЬ: список таких настроек — ОДИН, здесь, и растёт он осознанно (строчкой в
 * `RESTART_SCOPED`), а не выводится догадкой по коду. И есть сравнение двух значений:
 * того, что лежит на диске, с тем, по которому демон работает, — чтобы окно могло
 * сказать «в файле 4, работаю по 6, применится при следующем запуске».
 *
 * НЕТ: перечитывания конфига на лету. Половина настроек этого не переживёт — очередь
 * строится на `queueUrl` при запуске, дверь держит порт, дом идущих попыток раздаёт
 * места по потолку, с которым его создали. Речь о ЧЕСТНОСТИ, а не о горячей
 * перезагрузке: настройка второго класса обязана назвать себя такой и показать
 * расхождение, а не сделать вид, что применилась.
 *
 * ═══ ПОЧЕМУ СРАВНИВАЮТСЯ ЭФФЕКТИВНЫЕ ЗНАЧЕНИЯ, А НЕ СЫРЫЕ КЛЮЧИ ═════════════════
 *
 * Каждая настройка читается ТЕМ ЖЕ выражением, которым её читает машина (`read`), и с
 * диска, и из памяти. Это не аккуратность, а единственный способ не наврать: ключа в
 * файле может не быть вовсе (тогда действует умолчание), значение может быть мусорным
 * (тогда тоже действует умолчание), и «в файле нет ключа, работаю по 80» — расхождением
 * НЕ является, потому что перезапуск ничего не изменит. Расхождение — это «после
 * перезапуска будет другое число», и считается оно ровно так.
 *
 * Node built-ins + свои модули; собственного чтения настроек этот файл не изобретает.
 */

import { readJsonSafe } from '../../scripts/sma/lib/fs-atomics.mjs'
import { pipelineMaxTurns, resolveConfigPath } from './config.mjs'
// Потолок мест читается ТЕМ ЖЕ выражением, которым его читает тик перед отказом в месте.
// Своё чтение здесь означало бы вторую формулировку одной настройки — а именно из двух
// формулировок одного числа и рождается экран, объясняющий не ту машину.
import { concurrencyCap } from './queue/in-flight.mjs'

/**
 * СПИСОК НАСТРОЕК ВТОРОГО КЛАССА — ОДИН НА ВЕСЬ ПРОДУКТ, И ЭТО ЕГО ГЛАВНОЕ СВОЙСТВО.
 *
 * Не «вычислен по коду»: догадка о том, перечитывается ли настройка, — это ровно то
 * рассуждение, которое человек проделал дважды и дважды ошибся. Запись сюда делается
 * руками, вместе с настройкой, и стоит одну строку.
 *
 * КОГДА ДОБАВЛЯТЬ СТРОКУ. Если значение читается из копии настроек в памяти процесса и
 * ни одна дверь окна его не двигает — оно здесь. Если у настройки есть дверь (тумблер
 * конвейера, денежный стоп, реестры проектов и работников), она применяется сразу и ей
 * здесь не место: дверь двигает и файл, и память, расходиться им нечем.
 *
 * `id` — это ПУТЬ В ФАЙЛЕ, той же записью, какой человек видит его в `config.json`:
 * окно называет настройку так же, как она называется на диске, иначе «в файле 4»
 * отсылает к ключу, который человек у себя не найдёт.
 *
 * @type {ReadonlyArray<{id:string, label:string, read:(config:object)=>unknown, why:string}>}
 */
export const RESTART_SCOPED = Object.freeze([
  Object.freeze({
    id: 'maxConcurrentAttempts',
    label: 'Мест одновременной работы',
    read: concurrencyCap,
    why: 'Тик спрашивает потолок у дома идущих попыток, а дом живёт в памяти процесса и рождается вместе с ним.',
  }),
  Object.freeze({
    id: 'pipeline.maxTurns',
    label: 'Потолок ходов одной попытки',
    read: pipelineMaxTurns,
    why: 'Число уезжает в командную строку работника из копии настроек, прочитанной на запуске.',
  }),
])

/**
 * readConfigOnDisk({env, homedir, fsImpl}) → разобранный `config.json` С ДИСКА, или `null`.
 *
 * Тем же путём (`resolveConfigPath`), которым файл нашёл сам демон, — иначе сравнивались бы
 * два разных файла. Нечитаемый, отсутствующий или не-объектный файл — это `null`, а не
 * пустой объект: с пустым объектом каждая настройка «разошлась бы» на умолчание, и окно
 * начало бы кричать о расхождении там, где сказать нечего.
 *
 * @param {{env?:object, homedir?:Function, fsImpl?:object}} [opts]
 * @returns {object|null}
 */
export function readConfigOnDisk({ env = process.env, homedir, fsImpl } = {}) {
  const path = resolveConfigPath({ env, ...(typeof homedir === 'function' ? { homedir } : {}) })
  const readFn = fsImpl && typeof fsImpl.readFileSync === 'function' ? fsImpl.readFileSync : undefined
  const raw = readJsonSafe(path, readFn ? { readFn } : {})
  return raw && typeof raw === 'object' && !Array.isArray(raw) ? raw : null
}

/**
 * deriveRestartScoped(config, onDisk) → по строке на каждую настройку второго класса:
 * чем она объявлена, по какому значению демон работает и что об этом говорит диск.
 *
 * `applies: 'restart'` СТОИТ НА КАЖДОЙ СТРОКЕ, а не подразумевается именем списка: окно
 * рисует строку рядом с самой настройкой, и пометка обязана ехать вместе с ней, а не
 * оставаться свойством заголовка, под который её однажды перенесут.
 *
 * `onDisk === null` — файл прочитать не удалось (или его не передали). Тогда
 * `diverged:false`, и это не «всё совпадает», а «сравнивать не с чем»: расхождение —
 * утверждение о файле, и без файла его делать нельзя.
 *
 * @param {object} [config] копия настроек, по которой демон РАБОТАЕТ прямо сейчас
 * @param {object|null} [onDisk] разобранный файл настроек, как он лежит на диске
 * @returns {Array<{id:string,label:string,why:string,applies:'restart',running:unknown,onDisk:unknown,diverged:boolean}>}
 */
export function deriveRestartScoped(config, onDisk) {
  const running = config && typeof config === 'object' ? config : {}
  const file = onDisk && typeof onDisk === 'object' && !Array.isArray(onDisk) ? onDisk : null
  return RESTART_SCOPED.map((setting) => {
    const live = setting.read(running)
    const disk = file ? setting.read(file) : null
    return {
      id: setting.id,
      label: setting.label,
      why: setting.why,
      applies: 'restart',
      running: live,
      onDisk: disk,
      diverged: file ? disk !== live : false,
    }
  })
}
