/**
 * ЧТО ИЗМЕНИЛА ЗАДАЧА — одно вычисление на все поверхности, которые это показывают.
 *
 * ═══════════════ ДВА СЧЁТА ОДНОГО ЧИСЛА ОДНАЖДЫ РАЗОЙДУТСЯ ═══════════════
 *
 * На карточке задачи стоят две поверхности, и обе отвечают на вопрос «что изменено».
 * Панель «Изменения» считала по всей ветке — `git diff HEAD...wt/<id>`, то есть от точки,
 * где ветка задачи ушла из истории проекта, до её вершины. Дверь диффа (`GET /api/diff/:id`)
 * показывала `git show wt/<id>` — ОДИН последний коммит, — а окно выводит свои `+N −M`
 * из текста, который эта дверь отдала. На задаче с одним коммитом числа совпадали, и
 * расхождение не было видно; на задаче с тремя коммитами карточка перечисляла три коммита
 * рядом с изменениями ОДНОГО из них. Это не редкий случай, а конструкция: два способа
 * прочитать одну задачу однажды скажут человеку разное.
 *
 * Поэтому диапазон здесь ровно один, и обе поверхности берут его отсюда. Форма ответа у них
 * разная — панели нужна строка со счётом, двери нужен патч целиком, — но вопрос, заданный
 * git, один и тот же, и задать его иначе можно только изменив ЭТОТ файл.
 *
 * ТРИ ТОЧКИ, А НЕ ДВЕ, И НИ ОДНОГО ИМЕНИ ВЕТКИ. `HEAD...<ветка>` просит git самого найти
 * точку расхождения, поэтому проект, чей ствол зовётся не `main` («master», релизная линия,
 * отсоединённая голова), не становится исключением на каждой карточке. Имя ствола, написанное
 * здесь словом, было бы допущением о чужом репозитории.
 */

/**
 * Начало имени всякой ветки задачи — одно написание на всех читателей. Его спрашивают
 * ДВА вопроса: «где работа этой задачи» (ниже) и «сколько веток задач ещё не в стволе»
 * (состояние проекта в state.mjs). Второе написание разошлось бы с тем, которым ветки
 * создаются, и счёт неслитого молча стал бы нулём.
 */
export const TASK_BRANCH_PREFIX = 'wt/'

/** Ветка, в которой живёт работа задачи, — одно написание на всех читателей. */
export function taskBranch(taskId) {
  return `${TASK_BRANCH_PREFIX}${taskId}`
}

/** Диапазон, означающий «что изменила эта задача»: от точки расхождения до вершины ветки. */
export function taskChangeRange(taskId) {
  return `HEAD...${taskBranch(taskId)}`
}

/**
 * Формы одного ответа: счёт для панели, патч для двери. Флаги перечислены здесь, а не у
 * вызывающих, чтобы «каким вопросом это меряется» оставалось свойством этого шва.
 */
const CHANGE_SHAPES = {
  count: ['--shortstat'],
  patch: ['--stat', '-p'],
}

/**
 * Прочитать изменения задачи через переданный шов git. Бросает ровно то, что бросил git:
 * «ветки нет» — это не пустой ответ, а другое обстоятельство, и решать, что о нём сказать
 * человеку, — дело вызывающей поверхности, а не этого места.
 *
 * @param {string} taskId
 * @param {(argv: string[], opts?: object) => string} execGit
 * @param {{cwd?: string, shape?: 'count'|'patch'}} [options]
 * @returns {string} вывод git как есть (пустая строка, когда менять было нечего)
 */
export function readTaskChanges(taskId, execGit, { cwd, shape = 'count' } = {}) {
  const flags = CHANGE_SHAPES[shape]
  if (!flags) throw new TypeError(`unknown change shape: ${shape}`)
  return String(execGit(['diff', ...flags, taskChangeRange(taskId)], cwd ? { cwd } : {}) || '')
}
