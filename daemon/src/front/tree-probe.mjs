/**
 * tree-probe.mjs — «а лежит ли в дереве этого проекта то, о чём говорит задача?»
 *
 * ═══════════════ ЗАЧЕМ ЭТО ЕСТЬ: ЛОВУШКА АКТИВНОГО ПРОЕКТА ══════════════════════
 * У человека может быть больше одного дерева, и штамп проекта ставится ПРИ СОЗДАНИИ
 * задачи (см. `doorProject` в server.mjs). Значит промах виден только потом — работник
 * получает копию не того дерева, не находит в ней исходников, о которых его спросили, и
 * честно возвращается с вопросом. Замерено: шесть работ, поставленных при не том активном
 * проекте, стоили полного круга «отменить и пересоздать» — переключение проекта задним
 * числом их не чинит.
 *
 * ═══════════════ ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ ════════════════════════════════════
 * ОН НЕ УГАДЫВАЕТ ПРОЕКТ ПО ТЕКСТУ ЗАДАЧИ. Догадка, которая ошибётся раз в двадцать, хуже
 * честного вопроса: человек перестанет её читать ровно к тому разу, когда она права.
 * Проект называет человек (или активный выбор), а здесь отвечают на ОДИН проверяемый
 * вопрос про НАЗВАННОЕ дерево: «этих путей в нём нет».
 *
 * ═══════════════ ПОЧЕМУ ТОЛЬКО ПУТИ СО СЛЭШЕМ ══════════════════════════════════
 * Предупреждение имеет право стоять на пути человека только пока оно ДЁШЕВО и ТОЧНО.
 * Путь с разделителем проверяется одним `existsSync(join(dir, path))` — без обхода дерева,
 * без индекса, без гадания. Голое имя файла (`server.mjs`) потребовало бы рекурсивного
 * обхода чужого дерева на каждое нажатие клавиши, а слово из прозы («импорт», «очередь»)
 * не проверяется вовсе. Поэтому здесь ровно один класс: то, что человек написал ПУТЁМ.
 *
 * Чистый модуль: ни одного импорта из node:fs — существование спрашивается через
 * ВПРЫСНУТЫЙ шов, поэтому правило проверяется тестом без единого файла на диске.
 */

import { join, resolve, sep } from 'node:path'

/**
 * Сколько путей вообще берётся в проверку. Заголовок задачи ограничен своим потолком, но
 * вставка из терминала может принести их десятки — а предупреждение из двадцати строк
 * никто не читает. Первые несколько по порядку упоминания: человек называет главное первым.
 */
export const NAMED_PATH_CAP = 5

/** Потолок длины одного пути. Всё длиннее — не путь, а строка, попавшая под выражение. */
export const NAMED_PATH_MAX = 200

/**
 * Из чего состоит сегмент пути ЗДЕСЬ: только ASCII. Это не про то, каких файлов не бывает,
 * а про то, какие имена мы готовы проверять НЕ ОШИБАЯСЬ: кириллическая проза со слэшем
 * («и/или», «сдал/не сдал») под это выражение не попадает вовсе, и предупреждения о
 * несуществующем файле «и/или» не будет.
 */
const SEGMENT = '[A-Za-z0-9_.@+-]+'
const PATH_RE = new RegExp(`${SEGMENT}(?:/${SEGMENT})+`, 'g')

/** Адрес в сети — не путь в дереве. Вырезается ДО поиска, иначе `example.com/x` пройдёт. */
const URL_RE = /[a-z][a-z0-9+.-]*:\/\/\S+/gi

/** Сегмент с расширением: точка и от одной до шести букв/цифр на конце сегмента. */
const HAS_EXT_RE = new RegExp(`(?:^|/)[A-Za-z0-9_.@+-]+\\.[A-Za-z0-9]{1,6}(?:/|$)`)

/**
 * namedPaths(text) → пути, НАЗВАННЫЕ в тексте, в порядке первого упоминания и без повторов.
 *
 * Путём считается то, что человек написал путём: сегменты через `/`, и при этом либо с
 * расширением (`daemon/src/front/server.mjs`), либо глубже одного слэша (`spa/src/screens`).
 * Это выражение и есть весь фильтр от прозы: `and/or` и `24/7` не имеют ни того, ни другого.
 *
 * Отбрасывается всё, чего нельзя проверить безопасно и однозначно:
 *   - абсолютное (`/etc/passwd`, `C:/…`) — это не «внутри проекта», а другое место;
 *   - с `..` в любом сегменте — проверка обязана оставаться внутри названного дерева;
 *   - длиннее NAMED_PATH_MAX — под выражение попала строка, а не путь.
 *
 * Чистая функция; ничего не бросает и ничего не читает.
 *
 * @param {string} text
 * @returns {string[]}
 */
export function namedPaths(text) {
  if (typeof text !== 'string' || text === '') return []
  const hay = text.replace(URL_RE, ' ')
  const out = []
  const seen = new Set()
  for (const raw of hay.match(PATH_RE) ?? []) {
    // Хвостовые знаки препинания — часть предложения, а не имени: «правь spa/src/api/types.ts,»
    const path = raw.replace(/[.,;:!?)\]}]+$/, '')
    if (path.length === 0 || path.length > NAMED_PATH_MAX) continue
    if (path.startsWith('/') || /^[A-Za-z]:/.test(path)) continue
    const segments = path.split('/')
    if (segments.some((s) => s === '..' || s === '' || s === '.')) continue
    if (segments.length < 3 && !HAS_EXT_RE.test(path)) continue
    if (seen.has(path)) continue
    seen.add(path)
    out.push(path)
    if (out.length >= NAMED_PATH_CAP) break
  }
  return out
}

/**
 * missingPaths({paths, projectDir, existsImpl}) → те из них, которых в этом дереве НЕТ.
 *
 * Существование спрашивается ровно один раз на путь и только через впрыснутый шов. Шов,
 * который бросил, читается как «не знаю» — а не как «нет»: предупреждение о файле, которого
 * мы не смогли посмотреть, — это выдуманный факт, и он дороже молчания.
 *
 * ВЫХОД ЗА ПРЕДЕЛЫ НАЗВАННОГО ДЕРЕВА НЕВОЗМОЖЕН ДВАЖДЫ: `namedPaths` уже не отдаёт ни
 * абсолютных путей, ни `..`, и всё же собранный путь сверяется с корнем ещё раз здесь.
 * Первая половина — про то, что мы ищем; вторая — про то, куда мы смотрим, и складывать их
 * в одну проверку значит потерять вторую, когда первую однажды ослабят.
 *
 * @param {{paths?:string[], projectDir?:string, existsImpl?:Function}} o
 * @returns {string[]}
 */
export function missingPaths({ paths, projectDir, existsImpl } = {}) {
  if (!Array.isArray(paths) || paths.length === 0) return []
  if (typeof projectDir !== 'string' || projectDir.trim() === '') return []
  if (typeof existsImpl !== 'function') return []
  const root = resolve(projectDir)
  const inside = root.endsWith(sep) ? root : root + sep
  const out = []
  for (const path of paths) {
    const full = resolve(join(root, path))
    if (full !== root && !full.startsWith(inside)) continue
    let there
    try {
      there = existsImpl(full)
    } catch {
      continue // шов не ответил — молчим, а не объявляем отсутствие
    }
    if (!there) out.push(path)
  }
  return out
}
