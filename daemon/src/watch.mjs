/**
 * watch.mjs — СТОРОЖ ДЕМОНА: тот, кто остаётся жив, когда всё остальное замолчало.
 *
 * ═════════════ ЗАЧЕМ ОН НУЖЕН ════════════════════════════════════════════════════
 * Окно — веб-морда демона, и телеграм опрашивает тот же процесс. Один упавший процесс уносит
 * оба канала сразу, и дверь назад остаётся ровно одна — командная строка. Пока терминал
 * открыт, это терпимо; для человека, который живёт в окне и в телефоне, это единственная
 * точка отказа всей системы, и узнаёт он о ней по тому, что всё молчит.
 *
 * Сторож — маленький процесс, который умеет только три вещи: стучать в дверь, сказать
 * человеку, что она замолчала, и поднять демона тем же подъёмом, что и супервизор. Он
 * НИЧЕГО не знает про очередь, про задачи и про модель; у него нет ни базы, ни своей двери.
 * Это сделано ради одного свойства: чем меньше он умеет, тем меньше поводов умереть у того,
 * кто сторожит остальных.
 *
 * ═════════════ ОДНО МОЛЧАНИЕ — ЕЩЁ НЕ ПАДЕНИЕ ════════════════════════════════════
 * Провал объявляется только после нескольких подряд неотвеченных стуков. Одна потерянная
 * посылка, одна секунда сборки мусора, один занятый цикл — это не смерть, а сообщение
 * «демон упал», отправленное на такую рябь, обесценивает все следующие. Час падения при
 * этом записывается по ПЕРВОМУ молчанию, а не по моменту решения (см. outage.mjs).
 *
 * ═════════════ «ЖИВ, НО ДВЕРЬ МОЛЧИТ» — ЭТО СМЕРТЬ, И ЛЕЧИТСЯ ОНА ГАШЕНИЕМ ═══════
 * Смерть процесса — не единственный способ замолчать, и даже не самый частый. 29.08 замерено:
 * процесс жив (56 МБ, CPU идёт), а `GET /` висит до таймаута три пробы подряд; клин держался
 * десять минут ПРИ РАБОТАЮЩЕМ стороже, и сторож не перезапустил ничего. Он не был сломан: он
 * объявил провал и трижды запустил подъём — но поднимать было некуда, порт держал тот самый
 * процесс, который перестал отвечать. Подъём над живым зависшим демоном — не второй шанс, а
 * проигранная гонка за один адрес.
 *
 * Отсюда две правки, и обе про порядок, а не про терпение:
 *   1. СНАЧАЛА ГАСИМ, ПОТОМ ПОДНИМАЕМ. Серия неответов при живом процессе называется смертью
 *      вслух, и лечится она как смерть (`killHung`). Вслепую при этом не сигналят: процесс
 *      ищется по своей записи, как у штатной остановки, и никогда по имени двоичного файла.
 *   2. ТЕРПЕНИЕ ОДНОГО СТУКА — КРАТНО БОЛЬШЕ ЗАМЕРЕННОЙ ЗАДЕРЖКИ. Замер живёт в коде
 *      (`MEASURED_DOOR_LATENCY_MS`), порог выводится из него, а приговор по-прежнему стоит на
 *      серии проб. Сторож, который убивает здоровых, хуже отсутствующего сторожа.
 *
 * ═════════════ И «ГРУЗИТСЯ» — ЭТО НЕ «ЗАКЛИНИЛО» ════════════════════════════════
 * После подъёма дверь честно молчит ~45 секунд (наблюдалось до ~2 минут), пока boot обходит
 * копии закрытых задач. Сторож, принявший это молчание за клин, поднимает второго демона
 * поверх ещё загружающегося первого — и это худший исход из возможных, потому что он выглядит
 * как лечение. Различие берётся из записанного часа старта, а не из чутья: см. STARTUP_GRACE_MS.
 *
 * ═════════════ ЧЕГО ОН НЕ ДЕЛАЕТ: НЕ ВОСКРЕШАЕТ ПОГАШЕННОЕ ══════════════════════
 * Штатная остановка (`npm run daemon:stop`) убирает запись о процессе — это её последний шаг.
 * Аварийная смерть запись ОСТАВЛЯЕТ: умерший процесс не успевает ничего убрать. Эта разница
 * уже существовала в продукте, и сторож читает именно её:
 *
 *     дверь молчит + запись на месте  → это падение     → сказать и поднять
 *     дверь молчит + записи нет       → это остановка   → сказать один раз в журнал и не лезть
 *
 * Сторож, который поднимает демона, только что осознанно погашенного человеком, — это не
 * страховка, а противник, с которым приходится драться. Поэтому такого поведения здесь нет.
 *
 * ═════════════ «ПОДНЯЛСЯ» ГОВОРИТ НЕ ОН ══════════════════════════════════════════
 * Сторож знает лишь то, что он ЗАПУСТИЛ подъём. Между запуском и живой дверью стоит целый
 * boot, который умеет падать. Поэтому о падении говорит сторож (больше некому — тот, кто мог
 * бы, и есть покойник), а о подъёме говорит сам поднявшийся демон, уже после того, как его
 * собственная дверь ответила на настоящий запрос (daemon/src/outage.mjs). Здесь эта половина
 * не реализуется и не имитируется: увидев живую дверь, сторож просто закрывает свою часть
 * работы и молчит.
 *
 * ═════════════ НО «ЗАПУСТИЛ ПОДЪЁМ» И «ПОДНЯЛ» — ТОЖЕ РАЗНЫЕ ФАКТЫ ═══════════════
 * Ночью на 29.08 сторож отработал безупречно по каждому пункту выше: заметил молчание за
 * тридцать секунд, написал владельцу, запустил подъём и записал попытку. Через десять минут
 * дверь всё ещё молчала, а в журнале скрипта подъёма не было НИ ОДНОЙ строки — процесс не
 * начался вовсе. Слово «ok» в записи означало лишь, что вызов запуска не бросил исключения:
 * запуск отделён от родителя, вывод выброшен, и провал старта был невидим по построению.
 * Сторож считал дело сделанным и уходил ждать, а человеку было сказано «падение» и не сказано,
 * что подъём не состоялся. Без человека демон пролежал бы до утра.
 *
 * Отсюда три правила этого файла, и все три проверяются подделкой запуска, которая молча
 * ничего не делает:
 *   1. ЗАПУЩЕННЫЙ ПОДЪЁМ НЕ ИМЕЕТ ИСХОДА. Он лежит в записи со словом `pending`, и исход ему
 *      называет ДВЕРЬ: ответила в отпущенный срок — `up`, не ответила — `no-door`. «Вызов не
 *      бросил» исходом не считается ни при каких обстоятельствах.
 *   2. НЕУДАЧА — ЭТО ВТОРОЕ СООБЩЕНИЕ ЧЕЛОВЕКУ, с причиной, взятой из вывода самого запуска.
 *      Молчание после «поднимаю» хуже, чем отсутствие сторожа, потому что на сторожа полагаются.
 *   3. ПОВТОР — С ВЫДЕРЖКОЙ И С ПОТОЛКОМ. Несколько неудач подряд — это уже вопрос не к
 *      машине, а к человеку, и звать надо его, а не крутить цикл до утра.
 *
 * Каждый шов — стук, часы, сон, запуск подъёма, отправка, чтение его вывода, файловый
 * ввод-вывод — внедряется, поэтому вся таблица решений проверяется без процесса, без сокета
 * и без телеграма.
 */

