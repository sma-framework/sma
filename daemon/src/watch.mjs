/** Как часто спрашивают дверь. Пятнадцать секунд — минута на объявление провала. */
export const POLL_MS = 15000

/** Сколько подряд ОТКАЗАННЫХ стуков превращают молчание в провал. */
export const MISSES_TO_DECLARE = 3

/**
 * ОТКАЗ И МОЛЧАНИЕ — РАЗНЫЕ ФАКТЫ, И ТЕРПЕНИЕ К НИМ РАЗНОЕ.
 *
 * «В порт никто не слушает» — доказательство смерти, и трёх таких хватает. «Соединение
 * приняли и не ответили за отпущенное время» — не доказательство ничего: ровно так выглядит
 * демон, занятый шестью попытками. 28.08 это стоило владельцу ложной тревоги в телеграме —
 * сторож спрашивал у САМОЙ ТЯЖЁЛОЙ двери продукта с терпением в три секунды, а та под
 * нагрузкой отвечает за семь с половиной и однажды ответила за пятьдесят одну. Демон был жив
 * всё это время; подъём, который сторож запустил, вежливо ничего не сделал, а запись о
 * провале осталась открытой навсегда, потому что закрывает её только воскресший.
 *
 * Поэтому у молчания свой счёт, заметно больший. Повешенный демон — принимающий соединения
 * и не отвечающий — так тоже будет пойман, просто не за минуту, а за несколько. Цена ошибки
 * несимметрична: не пойманное вовремя зависание стоит минут, а ложная тревога стоит доверия
 * к сторожу, после чего его перестают слушать вовсе.
 */
export const TIMEOUT_MISSES_TO_DECLARE = 8

/**
 * ЗАМЕР, А НЕ ПАМЯТЬ: сколько живая дверь занимает под нагрузкой.
 *
 * 28.08, дверь состояния под шестью живыми попытками: 7.5 секунды, однажды 51.
 * 31.08 ночью, три пробы подряд по дешёвой двери `/`: одна НЕ уложилась в 6 секунд, две
 * ответили за 2.7 с и 0.007 с.
 *
 * Число живёт В КОДЕ и рядом с порогом, который из него выводится, потому что порог, взятый
 * с потолка, однажды окажется ниже того, что дверь честно показывала, — и сторож начнёт
 * убивать здоровых. Меняется оно только новым замером, и тогда порог обязан поехать следом.
 */
export const MEASURED_DOOR_LATENCY_MS = 7500

/**
 * Терпение ОДНОГО стука сторожа — КРАТНО больше замеренной задержки под нагрузкой.
 *
 * Десяти секунд не хватало: живая дверь под нагрузкой уходила за шесть, а обе штатные
 * остановки 29.08 честно сказали «дверь молчит, а процесс жив» ровно потому, что спрашивали
 * с коротким терпением. Четырёхкратный запас (30 с против замеренных 7.5) выбран по
 * несимметричной цене ошибки: лишние секунды ожидания стоят секунд, а здоровый демон,
 * объявленный покойником и погашенный, стоит живой работы и доверия к сторожу.
 *
 * ТЕРПЕНИЕ ПО ВРЕМЕНИ ПРИ ЭТОМ ОСТАЛОСЬ ПРЕЖНИМ. Было 12 стуков по 10 с — до пяти минут;
 * стало 8 стуков по 30 — те же минуты, но каждый отдельный стук втрое снисходительнее.
 * Приговор как стоял на СЕРИИ проб, так и стоит: одна не решает ничего.
 */
export const KNOCK_TIMEOUT_MS = 4 * MEASURED_DOOR_LATENCY_MS

/**
 * Дверь, у которой сторож спрашивает «жив ли». Корень раздаётся из собранного файла и
 * остаётся дешёвым под любой нагрузкой — в отличие от двери состояния, которая собирает всю
 * доску. Вопрос «жив ли» не должен зависеть от самого дорогого вычисления в доме.
 */
export const KNOCK_PATH = '/'

/** Реже этого подъём не повторяется: boot демона занимает десятки секунд. */
export const LIFT_COOLDOWN_MS = 120000

/**
 * СКОЛЬКО ЗАПУЩЕННЫЙ ПОДЪЁМ ЖДЁТ ЖИВОЙ ДВЕРИ, прежде чем его назовут неудавшимся.
 *
 * Это ровно та величина, которой у сторожа не было: он записывал исход в момент запуска и
 * потому не мог записать ничего, кроме намерения. Полторы минуты — с запасом на boot демона
 * (десятки секунд) и на виндовую обёртку, которая перед стартом ещё крутит свою подготовку.
 * Ошибиться в большую сторону дешевле: лишняя минута ожидания стоит минуты, а «не удался»,
 * объявленный над ещё загружающимся демоном, стоит ложного сообщения и лишнего процесса.
 */
export const LIFT_DOOR_WAIT_MS = 180000

/**
 * СТАРТОВАЯ УБОРКА — НЕ КЛИН, и это отдельная величина, а не оттенок предыдущей.
 *
 * ЗАМЕР: после подъёма дверь честно молчит ~45 секунд, пока boot обходит копии закрытых задач
 * (29.08 наблюдалось до ~2 минут — обход спрашивает верб проекта отдельным процессом на каждое
 * дерево). Владелец так и говорит про ручное лечение: «после подъёма дать 2–3 минуты на
 * уборку». Сторож, который считает это молчание смертью, поднимает ВТОРОГО демона поверх
 * ещё загружающегося первого — и они дерутся за один порт; это худший исход из возможных,
 * потому что он выглядит как лечение.
 *
 * Отличие проверяемое, а не на глаз: у процесса записан час его старта. Молчание процесса,
 * который поднялся минуту назад, — это «грузится». Молчание процесса, который живёт часами,
 * — это «заклинило».
 */
export const STARTUP_GRACE_MS = 180000

/** Сколько погашение ждёт вежливого конца, прежде чем добить. Те же числа, что у остановки. */
export const KILL_GRACE_MS = 15000
export const KILL_WAIT_MS = 5000
export const KILL_POLL_MS = 250

/**
 * СКОЛЬКО РАЗ ПОДРЯД СТОРОЖ ПРОБУЕТ ПОДНЯТЬ, прежде чем позвать человека.
 *
 * Три — и это не «мало», а признание границы: подъём, не сработавший трижды с растущей
 * выдержкой, не сработает и в сотый раз, потому что дело уже не в гонке и не в занятом порте.
 * Сторож, крутящий цикл до утра, выглядит занятым и не делает ничего; единственное полезное
 * действие в этой точке — разбудить того, кто может открыть журнал.
 */
export const LIFT_ATTEMPTS_MAX = 3

/**
 * Каждое состояние, в котором может закончиться один круг сторожа, замкнутым списком.
 *
 *   up          дверь отвечает — сторожить нечего
 *   back        дверь ответила после провала; о подъёме скажет сам поднявшийся
 *   suspect     молчит, но ещё не столько раз, чтобы это называть падением
 *   starting    молчит, но процесс поднялся только что — это стартовая уборка, а не клин
 *   declared    провал объявлен: человеку сказано, зависший погашен, подъём запущен
 *   lifting     провал продолжается, подъём повторён после выдержки
 *   down        провал продолжается, до следующей попытки ещё рано
 *   abandoned   попытки исчерпаны: человеку сказано, что поднять не вышло, и сторож ждёт его
 *   stopped     двери нет и записи нет — демона погасили штатно, не лезем
 */
export const PHASES = Object.freeze(['up', 'back', 'suspect', 'starting', 'declared', 'lifting', 'down', 'abandoned', 'stopped'])

/**
 * createWatch(deps) → {tick, run, stop, state}.
 *
 * `tick()` — ОДИН круг: стук, решение, действие. Он и есть предмет проверки; `run()` только
 * повторяет его во сне, поэтому в тестах нет ни одного таймера.
 */
export function createWatch({
  config = {},
  probe = (cfg) => probeDoor({ config: cfg, path: KNOCK_PATH, timeoutMs: KNOCK_TIMEOUT_MS }),
  readRecord = (cfg) => readPidRecord({ config: cfg }),
  // ЖИВОСТЬ И СИГНАЛ — те же швы, что у штатной остановки, и по той же причине: процесс
  // ищется по СВОЕЙ записи, никогда по имени двоичного файла.
  isAlive = (pid) => processAlive(pid),
  signalProcess = (pid, sig) => process.kill(pid, sig),
  clearRecord = (cfg) => clearPidRecord({ config: cfg }),
  lift = liftCommand(),
  spawnLift,
  // Вывод запущенного подъёма, как его нашли на диске. Пустая строка — законный ответ («ничего
  // не оставил»), и она сама по себе улика: процесс, не написавший ни строки, не начинался.
  readLiftOutput = () => '',
  notify = (o) => notifyOwner(o),
  openOutageImpl = (o) => openOutage(o),
  stampOutageImpl = (o) => stampOutage(o),
  closeOutageImpl = (o) => closeOutage(o),
  now = Date.now,
  sleep = (ms) => new Promise((r) => setTimeout(r, ms)),
  log = () => {},
  pollMs = POLL_MS,
  missesToDeclare = MISSES_TO_DECLARE,
  timeoutMissesToDeclare = TIMEOUT_MISSES_TO_DECLARE,
  liftCooldownMs = LIFT_COOLDOWN_MS,
  liftDoorWaitMs = LIFT_DOOR_WAIT_MS,
  liftAttemptsMax = LIFT_ATTEMPTS_MAX,
  startupGraceMs = STARTUP_GRACE_MS,
  killGraceMs = KILL_GRACE_MS,
  killWaitMs = KILL_WAIT_MS,
  killPollMs = KILL_POLL_MS,
} = {}) {
  const where = doorUrl(config)
  let misses = 0
  let firstMissAt = 0
  let outage = null
  let saidStarting = false
  // Чей это был процесс в момент объявления провала. Тот же самый на возврате означает, что
  // демон не умирал вовсе, и закрыть провал придётся сторожу — воскресать некому.
  let pidAtFall = null
  let lastLiftAt = 0
  let saidStopped = false
  let running = false

  /** «90 с», «2 мин» — время так, как его читают в журнале. */
  function secs(ms) {
    const s = Math.round(ms / 1000)
    return s < 120 ? `${s} с` : `${Math.round(s / 60)} мин`
  }

  /**
   * Подъём — тем же путём, что и супервизор (liftCommand), и он ложится В ЗАПИСЬ БЕЗ ИСХОДА.
   *
   * `outcome: 'pending'` — это и есть починка ночи на 29.08. Всё, что известно в этот момент:
   * вызов запуска не бросил исключения. Над отделённым от родителя процессом это не значит
   * ровно ничего — ни того, что процесс пошёл, ни того, что он прожил секунду. Исход назовёт
   * дверь, и назовёт его ниже, в `settleLift`. Единственный исход, который МОЖНО назвать
   * здесь, — `no-spawn`: вызов бросил, и дальше ждать нечего.
   *
   * Список попыток на маркере — то, что потом читает квитанция: «поднимал трижды и не поднял»
   * и «поднял с первого раза» — разные истории одного и того же провала.
   */
  function doLift() {
    const at = new Date(now()).toISOString()
    let outcome = 'pending'
    let error = ''
    let logPath = ''
    try {
      const started = spawnLift(lift)
      logPath = String((started && started.log) || '')
    } catch (err) {
      outcome = 'no-spawn'
      error = String((err && err.message) || err)
    }
    lastLiftAt = now()
    const attempt = {
      at,
      cmd: `${lift.cmd} ${lift.args.join(' ')}`,
      outcome,
      ...(logPath ? { log: logPath } : {}),
      ...(error ? { error } : {}),
    }
    outage = stampOutageImpl({ config, marker: outage, patch: { lifts: [...(outage.lifts ?? []), attempt] } })
    log(
      outcome === 'pending'
        ? `подъём ЗАПУЩЕН (${attempt.cmd}) — это ещё не «поднял»: жду живой двери ${secs(liftDoorWaitMs)}.`
        : `подъём НЕ запустился: ${error}`,
    )
    return attempt
  }

  /** Процесс поднялся только что — молчание такого процесса ещё не приговор. Смотри STARTUP_GRACE_MS. */
  function stillStarting(record) {
    const started = Date.parse((record && record.startedAt) || '')
    return Number.isFinite(started) && now() - started < startupGraceMs
  }

  /**
   * Ждать конца процесса по СВОИМ часам: сон внедрён, поэтому ожидание проверяется без процесса.
   *
   * Кругов при этом ровно столько, сколько их помещается в срок, и это не украшение: часы здесь
   * тоже внедрены, а часы, которые сон не двигает (а такие бывают — их двигает прогон), делают
   * ожидание по одному только сроку бесконечным. Сторож, вставший в собственном цикле, — это
   * сторож, которого некому сторожить.
   */
  async function waitGone(pid, deadlineMs) {
    const until = now() + deadlineMs
    const rounds = Math.max(1, Math.ceil(deadlineMs / Math.max(1, killPollMs)))
    for (let i = 0; i < rounds; i += 1) {
      if (!isAlive(pid)) return true
      if (now() >= until) return false
      await sleep(killPollMs)
    }
    return !isAlive(pid)
  }

  /**
   * killHung(record) — ПОГАСИТЬ ЗАВИСШЕГО, прежде чем поднимать нового.
   *
   * ЭТО И ЕСТЬ НЕДОСТАЮЩАЯ ПОЛОВИНА. 29.08 клин держался десять минут ПРИ РАБОТАЮЩЕМ стороже,
   * и сторож не был сломан: он честно объявил провал и честно трижды запустил подъём. Только
   * поднимать было некуда — порт держал тот самый процесс, который перестал отвечать. Подъём
   * над живым зависшим демоном не второй шанс, а проигранная гонка за один адрес, и три таких
   * подъёма подряд ровно так и кончились: «поднять не смог».
   *
   * Поэтому «жив, но дверь молчит серию проб» здесь называется смертью И ЛЕЧИТСЯ КАК СМЕРТЬ:
   * сначала гасим, потом поднимаем. Порядок — не деталь, а единственное, что делает подъём
   * возможным.
   *
   * ЦЕНА НАЗВАНА ЧЕСТНО. Погашение убивает живые попытки, и штатная остановка ровно поэтому
   * отказывается это делать без `--force`. Здесь `--force` уже доказан: серия неответов по
   * дешёвой двери с четырёхкратным запасом терпения, да ещё и после стартовой выдержки, —
   * это процесс, который не обслуживает никого, и его попытки уже потеряны.
   *
   * ВСЛЕПУЮ НЕ СИГНАЛИМ: если процесса из записи нет в живых, гасить нечего, и номер, который
   * система успела отдать кому-то другому, здесь не трогают.
   */
  async function killHung(record) {
    // ЧЕЙ ЭТО ПРОЦЕСС — спрашивается тем же разбором, что и у штатной остановки, и по той же
    // причине: запись, называющая ЧУЖУЮ дверь, — это запись чужого демона, и сигнала она не
    // получает никогда. `gone` и `no-record` тоже уходят отсюда молча: гасить нечего.
    const id = identifyProcess({ config, record, isAlive })
    const pid = id.refusal === '' ? id.pid : null
    if (pid === null) return null
    const at = new Date(now()).toISOString()
    let how = ''
    try {
      signalProcess(pid, 'SIGTERM')
      how = 'SIGTERM'
    } catch (err) {
      if (err && err.code === 'ESRCH') {
        clearRecord(config)
        return null // кончился сам, пока я к нему шёл
      }
      log(`зависший процесс ${pid} не гасится: ${String((err && err.message) || err)}`)
      return stampKill({ at, pid, how: 'refused', error: String((err && err.message) || err) })
    }
    if (!(await waitGone(pid, killGraceMs))) {
      try {
        signalProcess(pid, 'SIGKILL')
        how = 'SIGKILL'
      } catch (err) {
        if (!(err && err.code === 'ESRCH')) {
          log(`зависший процесс ${pid} не добился: ${String((err && err.message) || err)}`)
          return stampKill({ at, pid, how: 'refused', error: String((err && err.message) || err) })
        }
      }
      if (!(await waitGone(pid, killWaitMs))) {
        log(`зависший процесс ${pid} жив и после SIGKILL — подъём всё равно запускаю, но порт может быть занят.`)
        return stampKill({ at, pid, how: 'refused' })
      }
    }
    clearRecord(config)
    log(`дверь ${where} молчит, а процесс ${pid} жив — это не жизнь, а клин: гашу его (${how}) и только потом поднимаю.`)
    return stampKill({ at, pid, how })
  }

  /** Погашение ложится В ЗАПИСЬ О ПРОВАЛЕ: квитанция обязана назвать, кого сторож убил. */
  function stampKill(kill) {
    outage = stampOutageImpl({ config, marker: outage, patch: { kills: [...((outage && outage.kills) || []), kill] } })
    return kill
  }

  /** Лечение целиком: погасить зависшего (если он есть) и запустить подъём. Всегда в этом порядке. */
  async function reviveOnce() {
    await killHung(readRecord(config))
    return doLift()
  }

  /** Последняя попытка, исход которой ещё не назван. Их не может быть двух: см. `settleLift`. */
  function pendingLift() {
    const lifts = (outage && outage.lifts) || []
    const last = lifts[lifts.length - 1]
    return last && last.outcome === 'pending' ? last : null
  }

  /** Отпущенное запуску время вышло, а дверь всё молчит — исход уже определён. */
  function liftOverdue(attempt) {
    const startedAt = Date.parse((attempt && attempt.at) || '')
    return !Number.isFinite(startedAt) || now() - startedAt >= liftDoorWaitMs
  }

  /**
   * ВЫДЕРЖКА МЕЖДУ ПОПЫТКАМИ РАСТЁТ, а считается от последней попытки ПО ЗАПИСИ, а не по
   * памяти процесса: сторож, поднятый посреди чужого провала, обязан продолжить чужой счёт, а
   * не начать долбить дверь заново с нуля. Растёт она потому, что вторая попытка через ту же
   * минуту после первой — это не терпение, а тот же удар, повторённый громче: если первый
   * подъём проиграл гонку за порт или упёрся в незакрывшийся сокет, второму нужно больше
   * времени, чем первому, а не столько же.
   */
  function liftBackoffMs(attempts) {
    return liftCooldownMs * 2 ** Math.max(0, attempts - 1)
  }

  function lastLiftAtOnRecord() {
    const lifts = (outage && outage.lifts) || []
    const last = lifts[lifts.length - 1]
    const at = last ? Date.parse(last.at) : NaN
    return Number.isFinite(at) ? at : lastLiftAt
  }

  /**
   * settleLift(attempt) — назвать исход запущенного подъёма: дверь молчала дольше отпущенного,
   * значит подъём НЕ УДАЛСЯ. Причина берётся из вывода САМОГО ЗАПУСКА, потому что «дверь не
   * ответила» — это наблюдение, а не причина; причина лежит там, куда написал умерший старт.
   */
  function settleLift(attempt) {
    const why = String(readLiftOutput(attempt.log || '') || '').trim()
    const settled = { ...attempt, outcome: 'no-door', ...(why ? { tail: why } : {}) }
    outage = stampOutageImpl({
      config,
      marker: outage,
      patch: { lifts: [...((outage && outage.lifts) || []).slice(0, -1), settled] },
    })
    return { settled, why }
  }

  /**
   * tellLiftFailed(attempt, why) → true, если попытки исчерпаны и сторож зовёт человека.
   *
   * ВТОРОЕ СООБЩЕНИЕ — ОБЯЗАТЕЛЬНОЕ. Человеку сказали «упал, поднимаю»; если подъём не вышел,
   * а второго сообщения нет, картина у него остаётся ложной, и полагается он на неё сильнее,
   * чем полагался бы на пустоту. Говорится оно ОДИН раз за провал (шум обесценивает и первое),
   * и ещё один раз — когда попытки кончились: это уже не отчёт, а вызов человека.
   */
  async function tellLiftFailed(attempt, why) {
    const attempts = ((outage && outage.lifts) || []).length
    const at = new Date(now()).toISOString()
    if (attempts >= liftAttemptsMax) {
      const said = await notify({ config, text: liftGaveUpWords({ marker: outage, attempts, why, attempt }) })
      outage = stampOutageImpl({
        config,
        marker: outage,
        patch: {
          liftGaveUpAt: at,
          liftFailNotifiedAt: said.sent ? at : (outage.liftFailNotifiedAt ?? null),
          liftFailNotice: said.reason,
        },
      })
      log(
        `подъём не удался ${attempts} раза подряд — больше не пробую, дальше это к человеку.${said.sent ? ' Сказал ему.' : ` Сказать в телеграм не вышло: ${said.reason}`}`,
      )
      return true
    }
    if (!outage.liftFailNotifiedAt && !outage.liftFailNotice) {
      const said = await notify({
        config,
        text: liftFailedWords({
          marker: outage,
          attempt,
          attempts,
          attemptsMax: liftAttemptsMax,
          waitMs: liftDoorWaitMs,
          nextInMs: liftBackoffMs(attempts),
          why,
        }),
      })
      outage = stampOutageImpl({
        config,
        marker: outage,
        patch: { liftFailNotifiedAt: said.sent ? at : null, liftFailNotice: said.reason },
      })
      if (!said.sent) log(`о неудавшемся подъёме сказать в телеграм не вышло: ${said.reason}`)
    }
    return false
  }

  async function tick() {
    const door = await probe(config)

    if (door && door.answered) {
      // «Вернулась» и «стоит» — разные новости, и путать их нельзя: первая закрывает провал,
      // вторая не сообщает ни о чём. Один и тот же ответ двери, два разных исхода круга.
      const wasDown = outage !== null
      if (wasDown) {
        // ЕСЛИ ДЕМОН НЕ УМИРАЛ, ЗАКРЫТЬ ПРОВАЛ БОЛЬШЕ НЕКОМУ. О подъёме говорит воскресший —
        // но в ложной тревоге воскресать некому, процесс тот же самый, и запись о провале
        // осталась бы открытой навсегда. 28.08 так и вышло: тревога ушла в телеграм, дверь
        // ответила через минуту, а маркер на диске остался лежать с открытым провалом.
        // Отличие проверяемое, а не на глаз: у процесса та же запись — значит перезапуска не
        // было. Другая запись — был настоящий подъём, и слово остаётся за поднявшимся.
        const nowRecord = readRecord(config)
        const samePid = pidAtFall !== null && nowRecord && nowRecord.pid === pidAtFall
        // ВТОРОЙ ПРИЗНАК — НА СЛУЧАЙ ПОДХВАЧЕННОГО ПРОВАЛА. Сторож, поднятый после чужого
        // объявления, не помнит процесса на момент падения; но время его запуска записано, и
        // процесс, начавшийся РАНЬШЕ, чем дверь замолчала, — тот же самый, который молчал.
        // Ни один перезапуск не может дать процесс старше собственного падения.
        const startedBefore = (() => {
          const started = Date.parse((nowRecord && nowRecord.startedAt) || '')
          const fell = Date.parse((outage && outage.downAt) || '')
          return Number.isFinite(started) && Number.isFinite(fell) && started < fell
        })()
        if (samePid || startedBefore) {
          log(`дверь ${where} снова отвечает (${door.status}) — процесс тот же, что молчал: демон не умирал, тревога была ложной. Закрываю провал сам.`)
          closeOutageImpl({ config, marker: outage, doorBackAt: now(), falseAlarm: true, now })
        } else {
          log(`дверь ${where} снова отвечает (${door.status}). О подъёме скажет сам поднявшийся демон — я не он.`)
        }
        outage = null
        pidAtFall = null
      }
      misses = 0
      firstMissAt = 0
      saidStopped = false
      saidStarting = false
      return { phase: wasDown ? 'back' : 'up', misses: 0, door, outage: null }
    }

    misses += 1
    if (misses === 1) firstMissAt = now()

    // Штатно погашенного не воскрешаем: запись о процессе убирает именно остановка.
    const record = readRecord(config)
    if (!record && !outage) {
      if (!saidStopped) {
        saidStopped = true
        log(`дверь ${where} молчит, записи о процессе нет — это штатная остановка или демон здесь не запускался. Сам поднимать не буду.`)
      }
      return { phase: 'stopped', misses, door, outage: null }
    }

    if (!outage) {
      // «ГРУЗИТСЯ» — НЕ «ЗАКЛИНИЛО», и различает их записанный час старта, а не чутьё.
      // Молчание процесса, которому минута от роду, — это стартовая уборка копий (замер: ~45 с,
      // наблюдалось до ~2 минут). Объявить её падением значит поднять второго демона поверх
      // ещё загружающегося первого и стравить их за один порт.
      if (record && stillStarting(record)) {
        if (!saidStarting) {
          saidStarting = true
          log(`дверь ${where} молчит, но процесс ${record.pid} поднялся ${secs(now() - Date.parse(record.startedAt))} назад — это стартовая уборка, а не клин. Жду.`)
        }
        return { phase: 'starting', misses, door, outage: null }
      }
      saidStarting = false

      // Порог берётся ПО РОДУ ПОСЛЕДНЕГО МОЛЧАНИЯ. Отказ в соединении — доказательство, что в
      // порт никто не слушает, и трёх довольно. Истёкшее ожидание доказывает лишь то, что
      // ответа не было ЗА ЭТО ВРЕМЯ, — а занятый демон выглядит именно так; ему отпускается
      // заметно больше кругов, прежде чем его объявят покойником. Род неизвестен (стук из
      // старого кода, подделка в сьюте) — ведём себя как раньше, по строгому порогу.
      const needed = door && door.kind === 'timeout' ? timeoutMissesToDeclare : missesToDeclare
      if (misses < needed) return { phase: 'suspect', misses, door, outage: null }

      pidAtFall = record ? record.pid : null
      outage = openOutageImpl({
        config,
        downAt: firstMissAt,
        reason: (door && door.reason) || 'нет ответа',
        now,
      })
      log(`провал: дверь ${where} молчит ${misses} стука подряд, с ${outage.downAt}. Говорю человеку и поднимаю.`)
      const said = await notify({ config, text: fallWords(outage) })
      outage = stampOutageImpl({
        config,
        marker: outage,
        patch: {
          fallNotifiedAt: said.sent ? new Date(now()).toISOString() : null,
          fallNotice: said.reason,
        },
      })
      if (!said.sent) log(`о падении сказать в телеграм не вышло: ${said.reason}`)

      // ОТ ПОДЪЁМА УЖЕ ОТКАЗАЛИСЬ — И ЭТО РЕШЕНИЕ ПОДХВАТЫВАЕТСЯ, А НЕ ОТМЕНЯЕТСЯ. Иначе
      // перезапуск сторожа обнулял бы потолок попыток, и «не крутить цикл до утра» держалось бы
      // ровно на том, что сторожа не перезапускали, — то есть ни на чём.
      if (outage.liftGaveUpAt) {
        log(`провал с ${outage.downAt} уже отдан человеку: подъём не удался и повторять его я не буду.`)
        return { phase: 'abandoned', misses, door, outage }
      }

      // ПОДХВАЧЕННЫЙ ПРОВАЛ МОЖЕТ НЕСТИ ЧУЖУЮ НЕЗАВЕРШЁННУЮ ПОПЫТКУ. Сторож, умерший вместе с
      // терминалом, оставил её со словом `pending` и исхода уже не назовёт. Дверь молчит прямо
      // сейчас — значит та попытка её не открыла, и это записывается МОЛЧА: человек секунду
      // назад получил сообщение о падении, и «не смог» о чужой попытке, про которую ему не
      // говорили, был бы шумом. Чужая попытка, ещё не выработавшая своё время, уважается: два
      // подъёма одновременно — это гонка за один порт, а не удвоенная надежда.
      const inherited = pendingLift()
      if (inherited) {
        if (!liftOverdue(inherited)) return { phase: 'declared', misses, door, outage }
        settleLift(inherited)
      }
      const first = await reviveOnce()
      if (first.outcome === 'no-spawn') await tellLiftFailed(first, first.error)
      return { phase: 'declared', misses, door, outage }
    }

    // ── провал уже объявлен: у сторожа остаётся ровно одно дело — довести подъём до исхода ──

    // Попытки кончились и человек позван. Крутить цикл дальше — значит выглядеть занятым и не
    // делать ничего; ждём того, кто может открыть журнал.
    if (outage.liftGaveUpAt) return { phase: 'abandoned', misses, door, outage }

    const pending = pendingLift()
    if (pending) {
      // Отпущенное время ещё идёт: демон может быть в середине boot'а, и объявить его неудачей
      // сейчас — та же поспешность, что объявить падением одно молчание.
      if (!liftOverdue(pending)) return { phase: 'down', misses, door, outage }
      const { settled, why } = settleLift(pending)
      log(
        `подъём НЕ УДАЛСЯ: дверь ${where} не ответила за ${secs(liftDoorWaitMs)} после запуска. ` +
          (why
            ? `Вывод запуска: ${why}`
            : `Запуск не оставил ни строки${settled.log ? ` в ${settled.log}` : ''} — похоже, процесс не начался вовсе.`),
      )
      if (await tellLiftFailed(settled, why)) return { phase: 'abandoned', misses, door, outage }
    }

    if (now() - lastLiftAtOnRecord() >= liftBackoffMs(((outage && outage.lifts) || []).length)) {
      // И ПОВТОРНЫЙ ПОДЪЁМ ТОЖЕ ГАСИТ: за минуты выдержки на порту мог осесть либо тот же
      // зависший, либо полу-поднявшийся демон, который умер, не открыв двери. И тот и другой
      // держат адрес, ради которого запускается следующая попытка.
      const attempt = await reviveOnce()
      // Бросок на самом вызове — исход, известный сразу: ждать двери от процесса, который не
      // запустился, нечего, и человеку об этом говорят тем же вторым сообщением.
      if (attempt.outcome === 'no-spawn' && (await tellLiftFailed(attempt, attempt.error))) {
        return { phase: 'abandoned', misses, door, outage }
      }
      return { phase: 'lifting', misses, door, outage }
    }
    return { phase: 'down', misses, door, outage }
  }

  return {
    tick,
    /** Что сторож думает прямо сейчас — читается тестом и командой, не угадывается. */
    state: () => ({ misses, firstMissAt, outage, lastLiftAt, running }),
    /** run() — тот же круг во сне, пока не попросят остановиться. */
    async run() {
      running = true
      while (running) {
        try {
          await tick()
        } catch (err) {
          // Сторож, умерший на собственной ошибке, — это сторож, которого некому сторожить.
          log(`круг не отработал: ${String((err && err.stack) || err)}`)
        }
        if (!running) break
        await sleep(pollMs)
      }
    },
    stop() {
      running = false
    },
  }
}
