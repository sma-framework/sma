/**
 * ЗАМОК НА СЛОВАРЬ СТУПЕНЕЙ ФАЗЫ — семь мест, один канон, одна проверка.
 *
 * Дорога фазы записана в этом доме СЕМЬ РАЗ, руками, в семи разных файлах: закрытый словарь
 * очереди, таблица команд, карта «чем стадия доказывается», проекция карточки, тип окна,
 * подписи с порядком и раскладка доски. Ни одно из семи не выводится из другого — и это
 * сделано осознанно (частота чтения важнее одного источника), но у осознанной цены есть
 * счёт: семь рукописных списков расходятся молча.
 *
 * ЧЕМ ИМЕННО ЭТО ПЛАТИТСЯ, сказано не нами: докстрока подписей стадий на стороне окна уже
 * называет этот класс поимённо — «два написания одной дороги однажды разошлись бы, и
 * "стадия 3 из 4" указывала бы не на ту стадию, которую человек видит открытой». Это не
 * гипотеза, это предупреждение, оставленное автором того файла. Здесь оно превращается из
 * прозы в прогон.
 *
 * ПОЧЕМУ ЗАМОК, А НЕ ВЫВОД ОДНОГО ИЗ ДРУГОГО. Свести семь мест к одному нельзя дёшево:
 * четыре из них — на стороне демона (модули node), три — на стороне окна (модули
 * TypeScript, собираемые отдельным сборщиком), и общий модуль между этими двумя мирами
 * тянет за собой сборку окна в рантайм демона. Поэтому дом держит семь копий и ОДИН тест,
 * который делает их расхождение красным. Тест дешевле общего модуля и честнее намерения.
 *
 * КАК ЧИТАЮТСЯ СЕМЬ МЕСТ — двумя способами, и выбор сказан вслух:
 *   — ЖИВОЙ ИМПОРТ там, где константа экспортирована: словарь очереди, таблица команд, карта
 *     артефактов, проекция карточки, подписи и порядок стадий, столбики доски и их слова.
 *     Живой импорт сильнее чтения текста: он утверждает ЗНАЧЕНИЕ, которое получит читатель,
 *     а не буквы, которые кто-то написал.
 *   — ЧТЕНИЕ ИСХОДНИКА КАК ТЕКСТА там, где константа модулю-соседу не видна: список стадий
 *     и его столбиковый двойник внутри раскладки доски объявлены без `export`, и тип стадии
 *     окна — это тип, у которого во время исполнения нет тела вовсе. Экспортировать их
 *     НАРОЧНО ради теста мы отказались: это расширило бы поверхность модуля ради проверки,
 *     а чтение файла как текста — ход, уже принятый в этом доме (замок словаря маршрутизатора
 *     и сверка договора окна оба читают исходник глазами регулярного выражения).
 *
 * ЭТОТ ФАЙЛ КРАСЕН ПРИ РОЖДЕНИИ, И ЭТО ЕГО ПЕРВАЯ РАБОТА. Пятая ступень — дизайн, между
 * планом и исполнением — на момент появления файла не стоит ни в одном из семи мест.
 * Красный прогон снят в квитанцию; работа, которая вписывает слово во все семь мест ОДНИМ
 * коммитом, делает его зелёным. Частичное касание словаря останется красным — ровно то
 * поведение, ради которого замок и ставится.
 */

import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'

import { TASK_STAGES } from '../src/queue/adapter.mjs'
import { STAGE_COMMANDS, stageCommand, assertNoAutomation } from '../src/policy/phase-cycle.mjs'
import { STAGE_ARTIFACTS } from '../src/front/questions.mjs'
import { PHASE_STAGES } from '../src/front/state.mjs'
import { STAGE_LABEL, STAGE_ORDER } from '../../spa/src/shell/format'
import { BOARD_COLUMNS, COLUMN_WORD } from '../../spa/src/screens/tasks/units'

/**
 * КАНОН — дорога фазы, названная в этом файле один раз и целиком.
 *
 * Порядок — часть канона, не украшение: карточка рисует по нему полосу, окошко показателей
 * считает по нему «стадия N из 5», а доска ставит по нему столбики. Список, совпавший по
 * составу и разошедшийся по порядку, — тот же дефект, только тише.
 */
const CANON = ['discuss', 'plan', 'design', 'execute', 'verify'] as const

const UNITS_SRC = readFileSync(new URL('../../spa/src/screens/tasks/units.ts', import.meta.url), 'utf8')
const TYPES_SRC = readFileSync(new URL('../../spa/src/api/types.ts', import.meta.url), 'utf8')

/**
 * Слова одного литерала-массива, прочитанные из исходника по имени константы.
 *
 * Берётся ПЕРВОЕ объявление имени — то, где за именем стоит знак равенства и скобка; места
 * использования той же константы ниже по файлу под шаблон не попадают, потому что за ними
 * не идёт присваивание массива.
 */
function literalArray(source: string, name: string): string[] {
  const re = new RegExp(`\\b${name}\\b[^=\\n]*=\\s*\\[([^\\]]*)\\]`)
  const m = re.exec(source)
  if (!m) throw new Error(`литерал массива ${name} не найден в исходнике`)
  return [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1])
}

/** Слова одного литерала-объединения типов, прочитанные из исходника по имени типа. */
function literalUnion(source: string, name: string): string[] {
  const re = new RegExp(`\\btype\\s+${name}\\b[^=\\n]*=([^\\n]+)`)
  const m = re.exec(source)
  if (!m) throw new Error(`объединение ${name} не найдено в исходнике`)
  return [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1])
}

describe('семь мест словаря ступеней несут один канон', () => {
  it('закрытый словарь очереди — канон целиком и в порядке', () => {
    expect([...TASK_STAGES]).toEqual([...CANON])
  })

  it('таблица команд стадий — те же ступени, тем же порядком ключей', () => {
    expect(Object.keys(STAGE_COMMANDS)).toEqual([...CANON])
  })

  it('карта «чем стадия доказывается» — тот же СОСТАВ (порядок ключей карты каноном не является)', () => {
    expect(Object.keys(STAGE_ARTIFACTS).slice().sort()).toEqual([...CANON].slice().sort())
  })

  it('проекция карточки фазы — канон целиком и в порядке', () => {
    expect([...PHASE_STAGES]).toEqual([...CANON])
  })

  it('тип стадии на стороне окна — те же ступени в том же порядке', () => {
    expect(literalUnion(TYPES_SRC, 'PhaseStage')).toEqual([...CANON])
  })

  it('порядок стадий на стекле — канон; у каждой ступени есть человеческая подпись', () => {
    expect([...STAGE_ORDER]).toEqual([...CANON])
    expect(Object.keys(STAGE_LABEL).slice().sort()).toEqual([...CANON].slice().sort())
    for (const stage of CANON) expect(String(STAGE_LABEL[stage] ?? '').trim()).not.toEqual('')
  })

  it('список стадий экрана задач — канон целиком и в порядке', () => {
    expect(literalArray(UNITS_SRC, 'STAGES')).toEqual([...CANON])
  })
})

describe('доска задач: стадия N фазы и есть столбик N', () => {
  it('столбиковый двойник списка стадий совпадает с ним один в один', () => {
    expect(literalArray(UNITS_SRC, 'STAGE_COLUMN')).toEqual(literalArray(UNITS_SRC, 'STAGES'))
  })

  it('дизайн стоит между планированием и исполнением, а два хвостовых столбика — на месте', () => {
    expect(BOARD_COLUMNS).toEqual([...CANON, 'you', 'done'])
    expect(BOARD_COLUMNS.indexOf('design')).toBe(BOARD_COLUMNS.indexOf('plan') + 1)
    expect(BOARD_COLUMNS.indexOf('execute')).toBe(BOARD_COLUMNS.indexOf('design') + 1)
  })

  it('тип столбика знает ровно те же слова, и у каждого столбика есть заголовок', () => {
    expect(literalUnion(UNITS_SRC, 'BoardColumn')).toEqual([...CANON, 'you', 'done'])
    for (const column of BOARD_COLUMNS) expect(String(COLUMN_WORD[column] ?? '').trim()).not.toEqual('')
  })
})

describe('команда пятой ступени: замороженная форма, и ни одного флага автоответа', () => {
  it('ступень дизайна запускается своей командой с текстовым выводом', () => {
    expect(stageCommand('design', '21')).toBe('/sma-design-phase 21 --text')
  })

  it('страж флагов эту команду пропускает — машине нечем ответить за человека', () => {
    const command = stageCommand('design', '21') as string
    expect(assertNoAutomation(command)).toBe(command)
  })

  it('у каждой ступени канона есть команда, и ни одна не несёт автофлага', () => {
    for (const stage of CANON) {
      const command = stageCommand(stage, '7')
      expect(command).not.toBeNull()
      expect(assertNoAutomation(command as string)).toBe(command)
    }
  })
})
